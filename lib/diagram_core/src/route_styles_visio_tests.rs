fn page(code: i64) -> super::tests::Fx {
    let mut f = fx();
    for (cell, v) in [("LineToNodeX", 2.5 * MM), ("LineToNodeY", 2.5 * MM), ("LineToLineX", 2.5 * MM), ("LineToLineY", 2.5 * MM), ("AvenueSizeX", 7.5 * MM), ("AvenueSizeY", 7.5 * MM), ("BlockSizeX", 5.0 * MM), ("BlockSizeY", 5.0 * MM), ("RouteStyle", code as f64)] {
        f.set(None, cell, v);
    }
    f
}

#[test]
fn own_drawings_against_visio() {
    let mut bad = Vec::new();
    for o in OWN {
        let mut f = page(o.code);
        let a = f.rect(1, [o.begin[0], o.begin[1]], [o.begin[2], o.begin[3]]);
        let b = f.rect(2, [o.end[0], o.end[1]], [o.end[2], o.end[3]]);
        if let Some((w, p)) = o.wall {
            let s = f.rect(3, [w[0], w[1]], [w[2], w[3]]);
            if p & route::PASS_X != 0 {
                f.set(Some(s), "ShapePermeableX", 1.0);
            }
            if p & route::PASS_Y != 0 {
                f.set(Some(s), "ShapePermeableY", 1.0);
            }
        }
        let c = f.connect(a, b);
        if o.walk != 0.0 {
            f.set(Some(c), "WalkPreference", o.walk);
            f.update(&[c]);
        }
        let got = f.path(c);
        let fixed = f.value(c, "ConFixedCode").unwrap_or(0.0) as i64;
        let mut ok = same_way(&got, o.want);
        let mut got2 = Vec::new();
        if !o.after.is_empty() {
            let (s, at) = if o.moved == 0 { (a, o.begin) } else { (b, o.end) };
            f.move_to(s, [at[0], at[1] - 0.3]);
            got2 = f.path(c);
            ok &= same_way(&got2, o.after);
        }
        assert_eq!(fixed, o.fixed, "{}: ConFixedCode", o.name);
        match DETOURS.iter().find(|(n, _)| *n == o.name) {
            // an exception still has Visio's form, and still differs (else it leaves the list)
            Some((_, why)) => {
                assert!(got.len() == o.want.len() && !ok, "{} ({why}): ours {got:?}, Visio {:?}", o.name, o.want);
            }
            None if !ok => bad.push(alloc::format!("{}: ours {got:?} / moved {got2:?}, Visio {:?} / {:?}", o.name, o.want, o.after)),
            None => {}
        }
    }
    assert!(bad.is_empty(), "{bad:#?}");
}

#[test]
fn grid_against_visio() {
    let mut bad = Vec::new();
    for &(code, place, at, want, moved, fixed) in GRID {
        let mut f = page(code);
        let p = f.rect(1, [8.5, 5.5], [1.6, 0.8]);
        let ch = f.rect(2, at, [1.4, 0.8]);
        let c = f.connect(p, ch);
        let got = f.path(c);
        let ours = f.value(c, "ConFixedCode").unwrap_or(0.0) as i64;
        f.move_to(ch, [at[0], at[1] - 0.3]);
        let got2 = f.path(c);
        if !same_way(&got, want) || !same_way(&got2, moved) || ours != fixed {
            bad.push(alloc::format!("style {code} {place}: ours {got:?} / moved {got2:?} (ConFixedCode {ours}), Visio {want:?} / {moved:?} ({fixed})"));
        }
    }
    assert!(bad.is_empty(), "{bad:#?}");
}
