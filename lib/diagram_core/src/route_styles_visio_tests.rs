fn same_way(got: &[[f64; 2]], want: &[[f64; 2]]) -> bool {
    got.len() == want.len() && got.iter().zip(want).all(|(a, b)| (a[0] - b[0]).abs() <= 0.01 && (a[1] - b[1]).abs() <= 0.01)
}

