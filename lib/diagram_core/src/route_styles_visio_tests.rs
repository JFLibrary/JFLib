#[test]
fn own_drawings_against_visio() {
    let mut bad = Vec::new();
    for o in OWN {
        let mut f = page(o.code);
        let a = f.rect(1, [o.begin[0], o.begin[1]], [o.begin[2], o.begin[3]]);
        let b = f.rect(2, [o.end[0], o.end[1]], [o.end[2], o.end[3]]);
        if let Some((w, p)) = o.wall {
            let s = f.rect(3, [w[0], w[1]], [w[2], w[3]]);
            f.set(Some(s), "ObjType", 1.0);
            if p & route::PASS_X != 0 {
                f.set(Some(s), "ShapePermeableX", 1.0);
            }
            if p & route::PASS_Y != 0 {
                f.set(Some(s), "ShapePermeableY", 1.0);
            }
        }
        let c = f.connect(a, b);
        if o.walk != 0.0 {
            f.set(Some(c), "WalkPreference", o.walk);
            f.update(&[c]);
        }
        let got = f.path(c);
        let fixed = f.value(c, "ConFixedCode").unwrap_or(0.0) as i64;
        let mut ok = same_way(&got, o.want);
        let mut got2 = Vec::new();
        if !o.after.is_empty() {
            let (s, at) = if o.moved == 0 { (a, o.begin) } else { (b, o.end) };
            f.move_to(s, [at[0], at[1] - 0.3]);
            got2 = f.path(c);
            ok &= same_way(&got2, o.after);
        }
        assert_eq!(fixed, o.fixed, "{}: ConFixedCode", o.name);
        match DETOURS.iter().find(|(n, _)| *n == o.name) {
            // an exception still has Visio's form, and still differs (else it leaves the list)
            Some((_, why)) => {
                assert!(got.len() == o.want.len() && !ok, "{} ({why}): ours {got:?}, Visio {:?}", o.name, o.want);
            }
            None if !ok => bad.push(alloc::format!("{}: ours {got:?} / moved {got2:?}, Visio {:?} / {:?}", o.name, o.want, o.after)),
            None => {}
        }
    }
    assert!(bad.is_empty(), "{bad:#?}");
}

