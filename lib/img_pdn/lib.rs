/// a new FMT_ARGB surface with the composite of the visible layers (paint.net blend modes
/// and opacity, k_bm_row); layers of any surface format with the document's size (ERR_DIMS
/// otherwise)  [pdn_flatten]
pub fn flatten(doc: &DocRef) -> Result<Surface, i32> {
    let mut sf = surf_alloc(doc.w, doc.h, FMT_ARGB, &ImgDec::default())?;
    let w4 = doc.w as usize * 4;
    let ds = sf.stride as usize;
    let mut row = vec![0u8; w4];
    let mut first = true; // the canvas is still transparent
    for l in &doc.layers {
        if l.visible == 0 || l.opacity == 0 {
            continue; // opacity 0 changes nothing
        }
        let s = l.sf;
        if s.w as u32 != doc.w || s.h as u32 != doc.h || s.px.is_empty() {
            return Err(ERR_DIMS);
        }
        let ss = s.stride as usize;
        if first {
            first = false;
            for y in 0..doc.h as usize {
                let dst = &mut sf.px[y * ds..y * ds + w4];
                if s.fmt == FMT_ARGB {
                    first_row(dst, &s.px[y * ss..y * ss + w4], l.opacity as u32);
                } else {
                    get_row(s, y, &mut row, FMT_ARGB);
                    first_row(dst, &row, l.opacity as u32);
                }
            }
            continue;
        }
        blend_layer(&mut sf, l, &mut row, doc.w, doc.h);
    }
    Ok(sf)
}

/// flatten of an owned document (decode_flat): the first visible layer becomes the composite
/// in place instead of being copied onto a new transparent canvas -- the same result (the
/// row padding zeroed like a new surface) without the second full-size surface and its page
/// faults.  A first layer that is not a plain FMT_ARGB surface of the document's size takes
/// flatten itself (same result, same errors).
pub(crate) fn flatten_owned(doc: &mut PdnDoc) -> Result<Surface, i32> {
    let r = dims_check(doc.w, doc.h, &ImgDec::default()); // flatten's surf_alloc check
    if r != 0 {
        return Err(r);
    }
    let Some(k) = doc.layers.iter().position(|l| l.visible != 0 && l.opacity != 0) else {
        return flatten(&doc.view());
    };
    let w4 = doc.w as usize * 4;
    let stride = (w4 + 63) & !63; // Surface::new's layout
    let bytes = (stride * doc.h as usize).max(64);
    let s = &doc.layers[k].sf;
    if s.fmt != FMT_ARGB
        || s.w as u32 != doc.w
        || s.h as u32 != doc.h
        || s.stride as usize != stride
        || s.px.len() != bytes
        || s.flags != SFF_OWNED
        || s.opac != 255
        || s.blend != 0
    {
        return flatten(&doc.view());
    }
    let op = doc.layers[k].opacity as u32;
    let mut sf = core::mem::take(&mut doc.layers[k].sf);
    let rows = stride * doc.h as usize;
    for row in sf.px[..rows].chunks_exact_mut(stride) {
        let (pix, pad) = row.split_at_mut(w4);
        first_inplace(pix, op);
        pad.fill(0);
    }
    sf.px[rows..].fill(0);
    let mut row = vec![0u8; w4];
    for l in &doc.layers[k + 1..] {
        if l.visible == 0 || l.opacity == 0 {
            continue;
        }
        if l.sf.w as u32 != doc.w || l.sf.h as u32 != doc.h || l.sf.px.is_empty() {
            return Err(ERR_DIMS);
        }
        blend_layer(&mut sf, &l.view(), &mut row, doc.w, doc.h);
    }
    Ok(sf)
}

// layer l (checked: the document's size) blended onto the canvas sf (k_bm_row per row; other
// formats than FMT_ARGB through get_row into `row`)
fn blend_layer(sf: &mut Surface, l: &LayerRef, row: &mut [u8], w: u32, h: u32) {
    let mode = if l.blend <= PDNB_XOR { l.blend } else { 0 };
    let mode_op = (l.opacity as u32) << 8 | mode as u32;
    let s = l.sf;
    let (w4, ds, ss) = (w as usize * 4, sf.stride as usize, s.stride as usize);
    for y in 0..h as usize {
        let dst = &mut sf.px[y * ds..y * ds + w4];
        if s.fmt == FMT_ARGB {
            bm_row_inplace(dst, &s.px[y * ss..y * ss + w4], mode_op);
        } else {
            get_row(s, y, row, FMT_ARGB);
            bm_row_inplace(dst, row, mode_op);
        }
    }
}

// The first visible layer onto the transparent canvas: with lhs = 0 the blend formula has
// y = x = 0 and z = totalA = rhsA = INT_SCALE(alpha, opacity) for every mode, so the pixel
// is the layer's colour with alpha rhsA, or 0 where rhsA is 0 -- what k_bm_row writes there
// (perf-inflate: a copy instead of a blend pass).
#[inline(always)]
fn first_px(v: u32, op: u32) -> u32 {
    let a = div255((v >> 24) * op);
    if a == 0 { 0 } else { v & 0x00FF_FFFF | a << 24 }
}

// one row of the first layer (straight BGRA) into a row of the transparent canvas
fn first_row(dst: &mut [u8], src: &[u8], op: u32) {
    let px = dst.chunks_exact_mut(4).zip(src.chunks_exact(4));
    if op == 255 {
        // INT_SCALE(alpha, 255) = alpha
        for (d, s) in px {
            let v = u32::from_le_bytes([s[0], s[1], s[2], s[3]]);
            d.copy_from_slice(&(if v >> 24 == 0 { 0 } else { v }).to_le_bytes());
        }
    } else {
        for (d, s) in px {
            let v = u32::from_le_bytes([s[0], s[1], s[2], s[3]]);
            d.copy_from_slice(&first_px(v, op).to_le_bytes());
        }
    }
}

// first_row in place (the layer's own pixels become the canvas)
fn first_inplace(pix: &mut [u8], op: u32) {
    for p in pix.chunks_exact_mut(4) {
        let v = u32::from_le_bytes([p[0], p[1], p[2], p[3]]);
        let n = if op == 255 {
            if v >> 24 == 0 { 0 } else { v }
        } else {
            first_px(v, op)
        };
        if n != v {
            p.copy_from_slice(&n.to_le_bytes());
        }
    }
}

