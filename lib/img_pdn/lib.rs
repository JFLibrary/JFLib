// ------------------------------------------------------------------ documents

/// a paint.net document (PDNDOC)
#[derive(Default)]
pub struct PdnDoc {
    pub w: u32,
    pub h: u32,
    pub unit: u32, // PDU_* (paint.net MeasurementUnit)
    pub dpux: f64, // dots per unit (IEEE double, as stored by paint.net)
    pub dpuy: f64,
    /// bottom layer first (PD_N = layers.len(); none after a PDND_PROBE decode)
    pub layers: Vec<PdnLayer>,
    /// Document.Metadata, serialized: items {u32 klen, key, u32 vlen, value} (UTF-8, the
    /// KeyValuePair / NameValueCollection entries in file order); empty = none
    pub nvc: Vec<u8>,
    /// decoded: IMGF_PDN, size, 8-bit RGBA, resolution (dpix / dpiy / resunit from the
    /// metadata EXIF items 296 / 282 / 283) and the ICC profile (34675); for view(): the
    /// ICC profile to embed
    pub meta: Option<ImgMeta>,
    /// the file's XML header (UTF-8)
    pub xml: Vec<u8>,
}

/// a layer (PDNLAYER)
#[derive(Default)]
pub struct PdnLayer {
    /// decoded: FMT_ARGB straight (paint.net ColorBgra); for the writer any of FMT_XRGB,
    /// FMT_PARGB, FMT_ARGB, FMT_A8 with the document's size
    pub sf: Surface,
    /// UTF-8 name; the writer (and the assembly's NUL-terminated strings) end it at the
    /// first NUL, the reader cuts it there
    pub name: Vec<u8>,
    pub opacity: u8, // 0..255
    pub visible: u8, // 0 / 1
    pub blend: u8,   // PDNB_*
    pub isbg: u8,    // 1 = background layer
    /// layer metadata, serialized like PdnDoc::nvc; empty = none
    pub meta: Vec<u8>,
}

/// the writer's view of a document: everything borrowed
pub struct DocRef<'a> {
    pub w: u32,
    pub h: u32,
    pub unit: u32,
    pub dpux: f64,
    pub dpuy: f64,
    pub layers: Vec<LayerRef<'a>>,
    pub nvc: &'a [u8],
    /// the ICC profile to embed (EXIF item 34675); empty = none
    pub icc: &'a [u8],
}

/// the writer's view of a layer
#[derive(Clone, Copy)]
pub struct LayerRef<'a> {
    pub sf: &'a Surface,
    pub name: &'a [u8],
    pub opacity: u8,
    pub visible: u8,
    pub blend: u8,
    pub isbg: u8,
    pub meta: &'a [u8],
}

impl PdnLayer {
    pub fn view(&self) -> LayerRef<'_> {
        LayerRef {
            sf: &self.sf,
            name: &self.name,
            opacity: self.opacity,
            visible: self.visible,
            blend: self.blend,
            isbg: self.isbg,
            meta: &self.meta,
        }
    }
}

impl PdnDoc {
    /// the document as the writer sees it (ICC profile from meta)
    pub fn view(&self) -> DocRef<'_> {
        DocRef {
            w: self.w,
            h: self.h,
            unit: self.unit,
            dpux: self.dpux,
            dpuy: self.dpuy,
            layers: self.layers.iter().map(PdnLayer::view).collect(),
            nvc: &self.nvc,
            icc: self.meta.as_ref().map_or(&[][..], |m| &m.icc),
        }
    }
}

/// the bytes of a NUL-terminated name: up to the first NUL
pub(crate) fn cstr(s: &[u8]) -> &[u8] {
    match s.iter().position(|&b| b == 0) {
        Some(k) => &s[..k],
        None => s,
    }
}

