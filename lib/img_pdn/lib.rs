// img_pdn -- paint.net documents (.pdn): read and write, compatible with paint.net 5.1, and
// the MS-NRBF (.NET BinaryFormatter) parser / writer they are built on
//                                                    [src/img/pdn.s, src/img/nrbf.s]
//
//   CODEC                              the IMGCODEC (pdn_codec): probe, flat decode (the
//                                      composite), flat encode (one-layer document)
//   decode(data, dec) -> PdnDoc        pdn_decode: the file with every layer
//   decode_ex(data, dec, flags)        pdn_decode_ex: PDND_PROBE = size, resolution and
//                                      metadata only (no layers)
//   encode(doc, opt) -> file bytes     pdn_encode (IO_EFFORT = deflate level 1..9, default 1)
//   encode_ex(doc, opt, flags)         pdn_encode_ex: PDNE_BLENDOP = the 3.x blendOp classes
//   flatten(doc) -> Surface            pdn_flatten: the composite of the visible layers
//                                      (FMT_ARGB, paint.net blend modes and opacity)
//   probe / decode_flat / encode_flat  pdn_probe / pdn_decode_flat / pdn_encode_flat
//   nrbf::Nrbf, nrbf::Nw               the NRBF reader / writer (nrbf.s)
//
// The document records of the assembly (img.inc PDNDOC / PDNLAYER) are PdnDoc / PdnLayer:
// the reader returns an owned PdnDoc (pdn_free = drop).  The writer takes a borrowed view,
// DocRef / LayerRef, so a caller hands its own layers over without copying pixels (PaintCraft's
// save_pdn borrows its layer surfaces the same way); PdnDoc::view() makes one of a PdnDoc.
// PaintCraft (R11): open_pdn = decode(data, Some(&dec)), then move each layer's surface, name
// and metadata blob out of doc.layers (core::mem::take) and use doc.unit / dpux / dpuy;
// save_pdn = a DocRef over its layers (LayerRef per layer) and encode(&docref, Some(&opt)).
// Field semantics are those of the asm records: opacity / visible / blend / isbg as stored,
// blend values > PDNB_XOR mean Normal, the metadata blobs are {u32 klen, key, u32 vlen,
// value}* in file order, the writer accepts FMT_XRGB / PARGB / ARGB / A8 layers.
// Threads: deferred payloads with several chunks are decoded, and every layer's chunks are
// compressed, on the plat::parallel_for pool (as the assembly's Z1 worker-pool loops).
//
// File format (confirmed on paint.net 5.1.12 files):
//   "PDN3" | u24 LE n | n bytes UTF-8 XML header (size + thumbnail PNG in base64) |
//   00 01 | MS-NRBF object graph | the deferred MemoryBlock payloads, in the order of the
//   MemoryBlock objects in the stream: u8 format (0 gzip, 1 raw), u32 BE chunk size, then
//   ceil(length / chunk) chunks in any order {u32 BE index, u32 BE size, data}.
//   Legacy: "PDN3" + header + 1F 8B = gzip of everything else; a bare gzip file (<= 2.0).
// Resolution and the ICC profile live in the document metadata as EXIF items
// ("$exif.tagN[0]" = <exif id="296|282|283|34675" ... value="base64" />).
//
// Modules: nrbf (nrbf.s), dec (the reader: pdn.s decoding), enc (the writer: pdn.s encoding),
// template (the NRBF class templates, generated by tools/gen_pdn_template.py).
#![no_std]
#![forbid(unsafe_code)]

