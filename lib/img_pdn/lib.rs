/// find `name` (e.g. `id="`) in s and return the text up to the next '"'  [pdn_attr]
pub(crate) fn attr<'s>(s: &'s [u8], name: &[u8]) -> Option<&'s [u8]> {
    let n = name.len();
    let mut i = 0usize;
    while s.len() - i >= n {
        if &s[i..i + n] == name {
            let v = &s[i + n..];
            let e = v.iter().position(|&b| b == b'"')?;
            return Some(&v[..e]);
        }
        i += 1;
    }
    None
}

/// decimal value of attribute `name` (0..999999999), -1 when absent or not a number
/// [pdn_attr_int]
pub(crate) fn attr_int(s: &[u8], name: &[u8]) -> i32 {
    let Some(v) = attr(s, name) else { return -1 };
    if v.is_empty() || v.len() > 9 {
        return -1;
    }
    let mut x = 0i32;
    for &c in v {
        let d = c.wrapping_sub(b'0');
        if d > 9 {
            return -1;
        }
        x = x * 10 + d as i32;
    }
    x
}

static B64: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";

// base64 character -> value (0xFF = invalid)  [pdn_b64_rev]
static B64_REV: [u8; 256] = {
    let mut t = [0xFFu8; 256];
    let mut i = 0;
    while i < 64 {
        t[B64[i] as usize] = i as u8;
        i += 1;
    }
    t
};

/// base64 -> dst: bytes written, -1 on a bad character or when the output does not fit;
/// '=' ends the data  [pdn_b64dec]
pub(crate) fn b64dec(src: &[u8], dst: &mut [u8]) -> i64 {
    let mut n = 0usize;
    let mut acc = 0u32;
    let mut bits = 0u32;
    for &c in src {
        if c == b'=' {
            break;
        }
        let v = B64_REV[c as usize];
        if v > 63 {
            return -1;
        }
        acc = acc << 6 | v as u32;
        bits += 6;
        if bits < 8 {
            continue;
        }
        bits -= 8;
        if n >= dst.len() {
            return -1;
        }
        dst[n] = (acc >> bits) as u8;
        n += 1;
        acc &= (1 << bits) - 1;
    }
    n as i64
}

/// base64 of src (4 * ceil(n / 3) bytes) into dst  [pdn_b64enc]
pub(crate) fn b64enc(src: &[u8], dst: &mut [u8]) -> usize {
    let mut o = 0;
    let mut it = src.chunks_exact(3);
    for c in &mut it {
        let v = (c[0] as u32) << 16 | (c[1] as u32) << 8 | c[2] as u32;
        dst[o] = B64[(v >> 18) as usize];
        dst[o + 1] = B64[(v >> 12 & 63) as usize];
        dst[o + 2] = B64[(v >> 6 & 63) as usize];
        dst[o + 3] = B64[(v & 63) as usize];
        o += 4;
    }
    let r = it.remainder();
    if !r.is_empty() {
        let mut v = (r[0] as u32) << 16;
        if r.len() >= 2 {
            v |= (r[1] as u32) << 8;
        }
        dst[o] = B64[(v >> 18) as usize];
        dst[o + 1] = B64[(v >> 12 & 63) as usize];
        dst[o + 2] = if r.len() >= 2 { B64[(v >> 6 & 63) as usize] } else { b'=' };
        dst[o + 3] = b'=';
        o += 4;
    }
    o
}

/// base64 length of n bytes
pub(crate) fn b64len(n: usize) -> usize {
    (n + 2) / 3 * 4
}

/// append v in decimal  [pdn_utoa]
pub(crate) fn utoa(v: u32, out: &mut Vec<u8>) {
    let mut t = [0u8; 10];
    let mut k = 0;
    let mut x = v;
    loop {
        t[k] = b'0' + (x % 10) as u8;
        k += 1;
        x /= 10;
        if x == 0 {
            break;
        }
    }
    while k > 0 {
        k -= 1;
        out.push(t[k]);
    }
}
