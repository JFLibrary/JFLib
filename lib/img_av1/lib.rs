// ---- test stages (av1_set_stage): output after that step  [av1.inc AVS_*]
pub const AVS_FINAL: u32 = 0;
pub const AVS_RECON: u32 = 1; // reconstruction, no in-loop filter
pub const AVS_LF: u32 = 2; // after the deblocking filter
pub const AVS_CDEF: u32 = 3;
pub const AVS_SR: u32 = 4; // after superres (of the CDEF output)
pub const AVS_LR: u32 = 5; // after loop restoration (film grain not applied)

/// the decoded frame (A1P of av1.inc): u16 sample planes owned by the decoder
pub struct Pic<'a> {
    pub w: u32, // output size (UpscaledWidth x FrameHeight)
    pub h: u32,
    pub bd: u32,   // BitDepth
    pub subx: u32, // subsampling (1 / 1 for monochrome)
    pub suby: u32,
    pub mono: u32,
    pub cdp: u32, // color_description_present_flag
    pub prim: u32,
    pub trc: u32,
    pub mc: u32,
    pub full: u32, // color_range
    pub csp: u32,  // chroma_sample_position
    pub planes: [&'a [u16]; 3], // (empty for the chroma of a monochrome frame)
    pub strides: [u32; 3],      // in samples
    pub rw: u32,                // render size
    pub rh: u32,
}
