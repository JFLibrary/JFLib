// img_av1 -- AV1 intra decoder for AVIF still images (AV1 bitstream specification; model:
// tools/av1_ref.py, bit-exact)                                  [src/img/av1*.s]
//
//   Av1Dec::new() -> decoder                  av1_new (av1_free = drop)
//   dec.set_cancel(flag)                      av1_set_cancel: polled per superblock
//   dec.set_stage(stage)                      av1_set_stage: test hook, AVS_* (output after that step)
//   dec.set_nograin(flag)                     av1_set_nograin: 1 = do not apply film grain
//   dec.obus(data) -> Ok / Err(ERR_*)         av1_obus: OBUs in the low-overhead format: sequence
//                                             header, frame header / frame / tile groups of the
//                                             first shown frame (decoded when its last tile
//                                             arrives); temporal delimiters, metadata, padding and
//                                             everything after the first frame are ignored
//   dec.finish() -> Pic / Err(ERR_*)          av1_finish: the decoded frame (film grain applied)
//   dec.qindex(seg, curq) -> qindex           av1_qindex: get_qindex( curq < 0, seg )
//
// Supported: profiles 0..2 (8 / 10 / 12 bits, 4:0:0 / 4:2:0 / 4:2:2 / 4:4:4), key frames and
// intra-only frames with every intra tool, operating point 0.  ERR_UNSUPPORTED: inter / switch
// frames, show_existing_frame, frames that are not shown, intra block copy, large scale tile.
//
// Modules: dec (av1.s: OBUs, headers, frame buffers, tile groups, the post filter chain), sym
// (av1_sym.s), blk (av1_blk.s: tile / block syntax), coef (av1_coef.s), ipred (av1_ipred.s), itx
// (av1_itx.s), txfn (av1_txfn.s, generated), lf (av1_lf.s), cdef (av1_cdef.s), lr (av1_lr.s:
// superres, loop restoration), fg (av1_fg.s), tab (av1_tab.s, generated by tools/gen_av1.py).
// The deblocking filter, CDEF and loop restoration run on the worker pool (plat::parallel_for)
// like the assembly's; every item writes its own rows (or columns), so the bytes never depend
// on the thread count.
