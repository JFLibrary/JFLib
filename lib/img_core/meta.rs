use gfx::straight::{premul_inplace, premul_row, unpremul_inplace, unpremul_row};
use gfx::{FMT_A8, FMT_ARGB, FMT_PARGB, FMT_XRGB};

// ------------------------------------------------------------------ metadata records

/// the blobs of an ImgMeta (IM_ICC / IM_EXIF / IM_XMP)
#[derive(Clone, Copy, PartialEq, Eq)]
pub enum Blob {
    Icc,
    Exif,
    Xmp,
}

/// store a copy of src as the blob (replacing one already there); an empty src stores
/// nothing  [img_meta_blob]
pub fn meta_blob(meta: &mut ImgMeta, which: Blob, src: &[u8]) {
    if src.is_empty() {
        return;
    }
    let b = match which {
        Blob::Icc => &mut meta.icc,
        Blob::Exif => &mut meta.exif,
        Blob::Xmp => &mut meta.xmp,
    };
    *b = src.to_vec();
}

/// drop the ICC / EXIF / XMP blobs (the other fields stay)  [img_meta_free]
pub fn meta_free(meta: &mut ImgMeta) {
    meta.icc = Vec::new();
    meta.exif = Vec::new();
    meta.xmp = Vec::new();
}

// ------------------------------------------------------------------ limits

/// w and h must be 1..IMG_MAXDIM (ERR_DIMS), w * h at most dec's pixel budget (ERR_LIMIT)
/// [img_dims_check]
pub fn dims_check(w: u32, h: u32, dec: &ImgDec) -> i32 {
    if w.wrapping_sub(1) > IMG_MAXDIM - 1 || h.wrapping_sub(1) > IMG_MAXDIM - 1 {
        return ERR_DIMS;
    }
    if w as u64 * h as u64 > dec.max_pixels() { ERR_LIMIT } else { 0 }
}

/// bytes against dec's memory budget (0 = no limit)  [img_mem_check]
pub fn mem_check(bytes: u64, dec: &ImgDec) -> i32 {
    if dec.maxmem != 0 && bytes > dec.maxmem { ERR_LIMIT } else { 0 }
}

/// dims_check, then a zeroed surface  [img_surf_alloc]
pub fn surf_alloc(w: u32, h: u32, fmt: u8, dec: &ImgDec) -> Result<Surface, i32> {
    let r = dims_check(w, h, dec);
    if r != 0 {
        return Err(r);
    }
    Ok(Surface::new(w as i32, h as i32, fmt))
}

// ------------------------------------------------------------------ pixel formats

fn row_range(sf: &Surface, y: usize) -> core::ops::Range<usize> {
    let o = y * sf.stride as usize;
    o..o + sf.w.max(0) as usize * if sf.fmt == FMT_A8 { 1 } else { 4 }
}

// im_opaque_row: copy with alpha forced to 255
fn opaque_row(dst: &mut [u8], src: &[u8]) {
    for (d, s) in dst.chunks_exact_mut(4).zip(src.chunks_exact(4)) {
        d[..3].copy_from_slice(&s[..3]);
        d[3] = 255;
    }
}

fn opaque_inplace(buf: &mut [u8]) {
    for p in buf.chunks_exact_mut(4) {
        p[3] = 255;
    }
}

/// row y of sf as w BGRA pixels in dst: fmt FMT_ARGB = straight, FMT_PARGB =
/// premultiplied  [img_get_row]
pub fn get_row(sf: &Surface, y: usize, dst: &mut [u8], fmt: u8) {
    let w = sf.w.max(0) as usize;
    let dst = &mut dst[..w * 4];
    if sf.fmt > FMT_ARGB {
        dst.fill(0);
        return;
    }
    let src = &sf.px[row_range(sf, y)];
    match sf.fmt {
        FMT_XRGB => opaque_row(dst, src),
        FMT_A8 => {
            for (d, &g) in dst.chunks_exact_mut(4).zip(src) {
                d.copy_from_slice(&[g, g, g, 255]);
            }
        }
        FMT_PARGB => {
            if fmt == FMT_PARGB {
                dst.copy_from_slice(src);
            } else {
                unpremul_row(dst, src);
            }
        }
        _ => {
            if fmt == FMT_ARGB {
                dst.copy_from_slice(src);
            } else {
                premul_row(dst, src);
            }
        }
    }
}

/// FMT_ARGB -> FMT_PARGB in place (other formats are left alone)  [img_premultiply]
pub fn premultiply(sf: &mut Surface) {
    if sf.fmt == FMT_ARGB {
        convert(sf, FMT_PARGB);
    }
}

/// FMT_PARGB -> FMT_ARGB in place (other formats are left alone)  [img_unpremultiply]
pub fn unpremultiply(sf: &mut Surface) {
    if sf.fmt == FMT_PARGB {
        convert(sf, FMT_ARGB);
    }
}

/// convert sf in place to fmt (FMT_PARGB or FMT_ARGB) from FMT_XRGB (alpha 255), FMT_PARGB
/// or FMT_ARGB -> 0 / ERR_UNSUPPORTED  [img_convert]
pub fn convert(sf: &mut Surface, fmt: u8) -> i32 {
    if fmt != FMT_PARGB && fmt != FMT_ARGB {
        return ERR_UNSUPPORTED;
    }
    let from = sf.fmt;
    if from == fmt {
        return 0;
    }
    if from == FMT_A8 || from > FMT_ARGB {
        return ERR_UNSUPPORTED;
    }
    for y in 0..sf.h.max(0) as usize {
        let r = row_range(sf, y);
        let row = &mut sf.px[r];
        match from {
            FMT_XRGB => opaque_inplace(row),
            FMT_PARGB => unpremul_inplace(row),
            _ => premul_inplace(row),
        }
    }
    sf.fmt = fmt;
    0
}

/// a new w x h surface (FMT_PARGB or FMT_ARGB) holding src through get_row
/// [img_surf_convert]
pub fn surf_convert(src: &Surface, fmt: u8) -> Result<Surface, i32> {
    if fmt != FMT_PARGB && fmt != FMT_ARGB {
        return Err(ERR_UNSUPPORTED);
    }
    let mut d = Surface::new(src.w, src.h, fmt);
    if d.px.is_empty() {
        return Err(ERR_NOMEM);
    }
    let stride = d.stride as usize;
    let w = src.w.max(0) as usize;
    for y in 0..src.h.max(0) as usize {
        get_row(src, y, &mut d.px[y * stride..y * stride + w * 4], fmt);
    }
    d.opac = src.opac;
    d.blend = src.blend;
    Ok(d)
}

// ------------------------------------------------------------------ orientation

/// transform a 32-bit surface for display by its EXIF orientation: 2 mirror, 3 rotate
/// 180, 4 flip, 5 transpose, 6 rotate 90 clockwise, 7 transverse, 8 rotate 90
/// counter-clockwise (1 and invalid values: nothing); 5..8 swap width and height (a new
/// pixel buffer; opacity and blend mode kept) -> 0 / ERR_NOMEM  [img_orient]
pub fn orient(sf: &mut Surface, o: u32) -> i32 {
    match o {
        2 => ops::flip_h(sf),
        3 => ops::rotate180(sf),
        4 => ops::flip_v(sf),
        5..=8 => {
            let Ok(mut n) = ops::rotate90(sf, if o == 8 { -1 } else { 1 }) else { return ERR_NOMEM };
            if o == 5 {
                ops::flip_h(&mut n);
            }
            if o == 7 {
                ops::flip_v(&mut n);
            }
            n.opac = sf.opac;
            n.blend = sf.blend;
            *sf = n;
        }
        _ => {}
    }
    0
}

/// every alpha byte of a 32-bit surface is 255  [img_all_opaque, png.s]
pub fn all_opaque(sf: &Surface) -> bool {
    let w = sf.w.max(0) as usize;
    let stride = sf.stride as usize;
    (0..sf.h.max(0) as usize).all(|y| {
        let row = &sf.px[y * stride..y * stride + w * 4];
        row.chunks_exact(4).fold(255u8, |a, p| a & p[3]) == 255
    })
}

/// premultiplied -> straight of one pixel  [unpremul, png.s]
pub fn unpremul(p: u32) -> u32 {
    gfx::straight::unpremul_px(p)
}

// ------------------------------------------------------------------ sample depth

/// round(v / 257) for v = 0..65535  [img_u16_to_u8]
#[inline]
pub fn u16_to_u8(v: u32) -> u8 {
    (((v & 0xFFFF) * 255 + 32895) >> 16) as u8
}

/// 16-bit samples (be: big endian) -> bytes round(v / 257); n = dst.len() (bounded by the
/// source)  [img_row_u16_to_u8]
pub fn row_u16_to_u8(dst: &mut [u8], src: &[u8], be: bool) {
    // one loop per byte order, so that each vectorizes (the assembly: SSE2, 8 per step)
    if be {
        for (d, s) in dst.iter_mut().zip(src.chunks_exact(2)) {
            *d = u16_to_u8(u16::from_be_bytes([s[0], s[1]]) as u32);
        }
    } else {
        for (d, s) in dst.iter_mut().zip(src.chunks_exact(2)) {
            *d = u16_to_u8(u16::from_le_bytes([s[0], s[1]]) as u32);
        }
    }
}

/// IEEE 754 half (low 16 bits of h) -> single precision bits (subnormals, infinities and
/// NaN preserved)  [img_half_to_f32]
pub fn half_to_f32(h: u32) -> u32 {
    let sign = (h & 0x8000) << 16;
    let e = (h >> 10) & 31;
    let mut m = h & 0x3FF;
    if e == 31 {
        return sign | 0x7F80_0000 | m << 13;
    }
    if e != 0 {
        return sign | (e + 112) << 23 | m << 13;
    }
    if m == 0 {
        return sign;
    }
    let mut e = 113u32;
    loop {
        e -= 1;
        m <<= 1;
        if m & 0x400 != 0 {
            break;
        }
    }
    sign | e << 23 | (m & 0x3FF) << 13
}

// im_f2u8: clamp to 0..1 (NaN -> 0), * 255, round
#[inline]
fn f2u8(x: f32) -> u8 {
    let v = rt::fx::minss(rt::fx::maxss(x, 0.0), 1.0) * 255.0 + 0.5;
    rt::fx::cvtt(v) as u8
}

/// IEEE halves -> bytes round(clamp(v, 0, 1) * 255), NaN -> 0  [img_row_half_to_u8]
pub fn row_half_to_u8(dst: &mut [u8], src: &[u16]) {
    for (d, &h) in dst.iter_mut().zip(src) {
        *d = f2u8(f32::from_bits(half_to_f32(h as u32)));
    }
}

/// floats -> bytes round(clamp(v, 0, 1) * 255), NaN -> 0  [img_row_f32_to_u8]
pub fn row_f32_to_u8(dst: &mut [u8], src: &[f32]) {
    for (d, &x) in dst.iter_mut().zip(src) {
        *d = f2u8(x);
    }
}

/// linear-light floats -> sRGB-encoded bytes (clamp 0..1, NaN -> 0, 4096-entry table)
/// [img_row_f32_to_srgb8]
pub fn row_f32_to_srgb8(dst: &mut [u8], src: &[f32]) {
    for (d, &x) in dst.iter_mut().zip(src) {
        let v = rt::fx::minss(rt::fx::maxss(x, 0.0), 1.0) * 4095.0 + 0.5;
        *d = LIN_SRGB[(rt::fx::cvtt(v) & 4095) as usize];
    }
}

/// sRGB decode (IEC 61966-2-1) of v / 255  [g_img_srgb_lin]
#[inline]
pub fn srgb_lin(v: u8) -> f32 {
    f32::from_bits(SRGB_LIN_BITS[v as usize])
}

// ------------------------------------------------------------------ JPEG segments

/// a JPEG segment walker (JSEG): pos = next read offset (start: 2, after SOI); ptr / len =
/// the payload of the current segment (offset into the data)
#[derive(Clone, Copy, Default)]
pub struct JSeg {
    pub pos: usize,
    pub ptr: usize,
    pub len: usize,
}

impl JSeg {
    pub fn new() -> JSeg {
        JSeg { pos: 2, ptr: 0, len: 0 }
    }
}

/// the next JPEG marker segment from js.pos: skips bytes that are not 0xFF, fill bytes,
/// standalone markers (TEM, RSTn); returns the marker (0xC0..0xFE) with js.ptr / js.len =
/// the payload (after the 2 length bytes) and js.pos behind it; 0xD9 (EOI) and 0xD8 (SOI)
/// come with len 0; 0 = end of data, a truncated segment or a length < 2  [jpg_seg_next]
pub fn jpg_seg_next(data: &[u8], js: &mut JSeg) -> u32 {
    let len = data.len();
    let mut p = js.pos;
    loop {
        while p < len && data[p] != 0xFF {
            p += 1; // garbage between segments
        }
        if p >= len {
            break;
        }
        let m = loop {
            p += 1;
            if p >= len {
                js.pos = len;
                return 0;
            }
            if data[p] != 0xFF {
                break data[p] as u32; // (0xFF: a fill byte)
            }
        };
        p += 1;
        if m == 0 || m == 0x01 {
            continue; // TEM
        }
        if m == 0xD8 || m == 0xD9 {
            js.ptr = p;
            js.len = 0;
            js.pos = p;
            return m;
        }
        if (0xD0..=0xD7).contains(&m) {
            continue; // stray RSTn
        }
        if len - p < 2 {
            break;
        }
        let sl = (data[p] as usize) << 8 | data[p + 1] as usize;
        if sl < 2 || sl > len - p {
            break;
        }
        js.ptr = p + 2;
        js.len = sl - 2;
        js.pos = p + sl;
        return m;
    }
    js.pos = len;
    0
}

