// meta -- shared helpers of the codecs: metadata blobs, size limits, straight <->
// premultiplied conversion, orientation, sample depth conversion, JPEG segment walking
//                                                                      [src/img/imgmeta.s]
//
//   meta_blob(meta, Blob, src)            copy src into the ICC / EXIF / XMP blob (len 0: nothing)
//   meta_free(meta)                       drop the blobs (the other fields stay)
//   dims_check(w, h, dec) -> 0 / ERR_DIMS / ERR_LIMIT    w, h 1..IMG_MAXDIM, w * h <= maxpx
//   mem_check(bytes, dec) -> 0 / ERR_LIMIT               against dec.maxmem (0 = no limit)
//   surf_alloc(w, h, fmt, dec) -> Ok(surface) / Err(ERR_*)   dims_check + a zeroed surface
//   premultiply(sf) / unpremultiply(sf)   FMT_ARGB <-> FMT_PARGB in place (others untouched)
//   convert(sf, fmt) -> 0 / ERR_UNSUPPORTED   in place to FMT_PARGB / FMT_ARGB from XRGB,
//                                         PARGB, ARGB
//   surf_convert(src, fmt) -> Ok(surface) / Err(ERR_*)   a new surface from any get_row source
//   get_row(sf, y, dst, fmt)              row y as w straight (FMT_ARGB) / premultiplied
//                                         (FMT_PARGB) BGRA pixels from XRGB (alpha 255),
//                                         PARGB, ARGB, A8 (grey); other formats: transparent
//   orient(sf, o) -> 0                    apply an EXIF orientation 2..8 (5..8 swap w and h)
//   u16_to_u8(v)                          round(v / 257)
//   row_u16_to_u8(dst, src, be)           16-bit samples (bytes, LE / BE) -> bytes
//   half_to_f32(h)                        IEEE half -> single precision bits
//   row_half_to_u8(dst, src) / row_f32_to_u8(dst, src)   round(clamp(v, 0, 1) * 255), NaN -> 0
//   row_f32_to_srgb8(dst, src)            linear floats -> sRGB bytes (4096-entry table)
//   jpg_seg_next(data, js) -> marker      JPEG marker segment iterator (JSeg)
//   srgb_lin(v) / SRGB_LIN_BITS           sRGB byte -> linear light (f32)
//   all_opaque(sf) -> bool                every alpha of a 32-bit surface is 255  [png.s]
//   unpremul(p)                           premultiplied -> straight, one pixel  [png.s]
//
// Straight -> premultiplied: round(c * a / 255); premultiplied -> straight: min(255,
// (c * ceil(255 * 2^24 / a) + 2^23) >> 24), a = 0 gives 0 (gfx::straight's kernels have
// exactly these rules).

use alloc::vec::Vec;

