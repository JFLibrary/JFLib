const fn put_le(b: &mut [u8; BI_CAP], o: usize, v: u32) {
    b[o] = v as u8;
    b[o + 1] = (v >> 8) as u8;
    b[o + 2] = (v >> 16) as u8;
    b[o + 3] = (v >> 24) as u8;
}

const fn put_be(b: &mut [u8; BI_CAP], o: usize, v: u32) {
    put_le(b, o, v.swap_bytes());
}

/// n big-endian u32 from host i32  [bw_be]
const fn bw_be(b: &mut [u8; BI_CAP], o: usize, src: &[i32], n: usize) {
    let mut i = 0;
    while i < n {
        put_be(b, o + i * 4, src[i] as u32);
        i += 1;
    }
}

/// one 'enUS' record (<= 200 characters) -> element bytes  [bw_mluc]
const fn bw_mluc(b: &mut [u8; BI_CAP], o: usize, s: &[u8]) -> usize {
    put_le(b, o, TYP_MLUC);
    put_le(b, o + 4, 0);
    put_le(b, o + 8, 0x01000000);
    put_le(b, o + 12, 0x0C000000);
    put_le(b, o + 16, 0x53556E65); // 'enUS'
    put_le(b, o + 24, 0x1C000000); // offset 28
    let mut n = 0;
    while n < s.len() && s[n] != 0 {
        b[o + 28 + n * 2] = 0;
        b[o + 29 + n * 2] = s[n];
        n += 1;
        if n >= 200 {
            break;
        }
    }
    put_be(b, o + 20, (n * 2) as u32);
    n * 2 + 28
}

/// tag table entry i: sig, offset, size  [BTAG2]
const fn btag(b: &mut [u8; BI_CAP], i: usize, sig: u32, off: usize, size: usize) {
    put_le(b, 132 + i * 12, sig);
    put_be(b, 136 + i * 12, off as u32);
    put_be(b, 140 + i * 12, size as u32);
}

/// built-in profile id -> (bytes, length)  [bi_make]
const fn bi_make(id: usize) -> ([u8; BI_CAP], usize) {
    let mut b = [0u8; BI_CAP];
    let bd = &BD[id];
    let gray = bd.cs == CS_GRAY;
    let ntag = if gray { 4 } else { 10 };
    let mut pos = ntag * 12 + 132; // first element
    let mut t = 0; // tag index
    let n = bw_mluc(&mut b, pos, bd.desc);
    btag(&mut b, t, TAG_DESC, pos, n);
    t += 1;
    pos += (n + 3) & !3;
    let n = bw_mluc(&mut b, pos, S_BI_CPRT);
    btag(&mut b, t, TAG_CPRT, pos, n);
    t += 1;
    pos += (n + 3) & !3;
    // wtpt = D50
    put_le(&mut b, pos, TYP_XYZ);
    bw_be(&mut b, pos + 8, &I_D50, 3);
    btag(&mut b, t, TAG_WTPT, pos, 20);
    t += 1;
    pos += 20;
    if !gray {
        // chad (sf32, 9 values) and the colorants
        put_le(&mut b, pos, TYP_SF32);
        bw_be(&mut b, pos + 8, &bd.chad, 9);
        btag(&mut b, t, TAG_CHAD, pos, 44);
        t += 1;
        pos += 44;
        let mut c = 0;
        while c < 3 {
            put_le(&mut b, pos, TYP_XYZ);
            let m = [bd.mat[c * 3], bd.mat[c * 3 + 1], bd.mat[c * 3 + 2]];
            bw_be(&mut b, pos + 8, &m, 3);
            btag(&mut b, t, TAG_COLS[c], pos, 20);
            t += 1;
            pos += 20;
            c += 1;
        }
    }
    // para curve shared by the TRC tags
    put_le(&mut b, pos, TYP_PARA);
    b[pos + 8] = (bd.pt >> 8) as u8;
    b[pos + 9] = bd.pt as u8;
    let np = PARA_NP[bd.pt as usize] as usize;
    bw_be(&mut b, pos + 12, &bd.par, np);
    let el = np * 4 + 12; // element bytes
    if gray {
        btag(&mut b, t, TAG_KTRC, pos, el);
    } else {
        btag(&mut b, t, TAG_RTRC, pos, el);
        btag(&mut b, t + 1, TAG_GTRC, pos, el);
        btag(&mut b, t + 2, TAG_BTRC, pos, el);
    }
    pos = (pos + el + 3) & !3;
    // header
    put_be(&mut b, 0, pos as u32);
    put_le(&mut b, 8, 0x00003004); // version 4.3
    put_le(&mut b, 12, CL_MNTR);
    put_le(&mut b, 16, bd.cs);
    put_le(&mut b, 20, PCS_XYZ);
    put_le(&mut b, 24, 0x0100EA07); // 2026-01-01
    b[28] = 0x00;
    b[29] = 0x01;
    put_le(&mut b, 36, SIG_ACSP);
    bw_be(&mut b, 68, &I_D50, 3);
    put_be(&mut b, 128, ntag as u32);
    (b, pos)
}

static BI: [([u8; BI_CAP], usize); BI_COUNT] = [bi_make(0), bi_make(1), bi_make(2), bi_make(3), bi_make(4)];

/// the bytes of built-in profile id (ICC_BI_*), None for an unknown id  [icc_builtin]
pub fn icc_builtin(id: u32) -> Option<&'static [u8]> {
    let (b, n) = BI.get(id as usize)?;
    Some(&b[..*n])
}

