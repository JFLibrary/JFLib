/// UTF-8 encode cp into dst (room bytes) -> bytes written (0 = no room)  [u8_put]
fn u8_put(dst: &mut [u8], room: usize, cp: u32) -> usize {
    if cp < 0x80 {
        if room < 1 {
            return 0;
        }
        dst[0] = cp as u8;
        1
    } else if cp < 0x800 {
        if room < 2 {
            return 0;
        }
        dst[0] = (cp >> 6 | 0xC0) as u8;
        dst[1] = (cp & 0x3F | 0x80) as u8;
        2
    } else if cp < 0x10000 {
        if room < 3 {
            return 0;
        }
        dst[0] = (cp >> 12 | 0xE0) as u8;
        dst[1] = (cp >> 6 & 0x3F | 0x80) as u8;
        dst[2] = (cp & 0x3F | 0x80) as u8;
        3
    } else {
        if room < 4 {
            return 0;
        }
        dst[0] = (cp >> 18 | 0xF0) as u8;
        dst[1] = (cp >> 12 & 0x3F | 0x80) as u8;
        dst[2] = (cp >> 6 & 0x3F | 0x80) as u8;
        dst[3] = (cp & 0x3F | 0x80) as u8;
        4
    }
}

/// the offset of the mluc record with that language, if any  [mluc_pick]
fn mluc_pick(el: &[u8], nrec: usize, recsz: usize, lang: [u8; 2]) -> Option<usize> {
    (0..nrec).map(|i| 16 + i * recsz).find(|&o| el[o..o + 2] == lang)
}

/// the 'desc' tag of a profile as UTF-8 into buf (cap = buf.len(), NUL-terminated) -> text
/// bytes (0 = none)  [icc_describe]
pub fn icc_describe(icc: &[u8], buf: &mut [u8]) -> usize {
    if buf.is_empty() {
        return 0;
    }
    buf[0] = 0;
    let room = buf.len() - 1; // without the NUL
    if icc_check(icc) < 0 {
        return 0;
    }
    let Some(el) = tag_find(icc, TAG_DESC) else { return 0 };
    let size = el.len();
    if size < 12 {
        return 0;
    }
    let mut n = 0;
    if le32(el, 0) == TYP_DESC {
        let cnt = (be32(el, 8) as usize).min(size - 12);
        for &c in &el[12..12 + cnt] {
            if n >= room || c == 0 {
                break;
            }
            buf[n] = if c >= 0x80 { b'?' } else { c };
            n += 1;
        }
    } else {
        if le32(el, 0) != TYP_MLUC || size < 16 {
            return 0;
        }
        let recsz = be32(el, 12) as usize;
        if recsz < 12 {
            return 0;
        }
        let nrec = (be32(el, 8) as usize).min((size - 16) / recsz);
        if nrec == 0 {
            return 0;
        }
        // prefer 'de', then 'en', else record 0
        let rec = mluc_pick(el, nrec, recsz, *b"de").or_else(|| mluc_pick(el, nrec, recsz, *b"en")).unwrap_or(16);
        let bytes = be32(el, rec + 4) as usize;
        let off = be32(el, rec + 8) as usize;
        if bytes.checked_add(off).is_none_or(|e| e > size) {
            return 0;
        }
        let units = bytes >> 1;
        let txt = &el[off..off + units * 2];
        let unit = |i: usize| u16::from_be_bytes([txt[i * 2], txt[i * 2 + 1]]) as u32;
        let mut i = 0;
        while i < units {
            let mut cp = unit(i);
            i += 1;
            if cp == 0 {
                break;
            }
            if cp & 0xFC00 == 0xD800 {
                if i < units && unit(i) & 0xFC00 == 0xDC00 {
                    cp = ((cp - 0xD800) << 10) + (unit(i) - 0xDC00) + 0x10000;
                    i += 1;
                } else {
                    cp = 0x3F;
                }
            }
            let k = u8_put(&mut buf[n..], room - n, cp);
            if k == 0 {
                break;
            }
            n += k;
        }
    }
    buf[n] = 0;
    n
}
