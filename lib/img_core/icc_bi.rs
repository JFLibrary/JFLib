// icc_bi -- the built-in ICC profiles and the profile description of icc_xform
//                                                                   [src/img/icc_xform.s]
//
//   icc_builtin(id) -> profile bytes | None     ICC_BI_SRGB / _A98 / _P3 / _ROMM /
//                                               _GRAY22  [icc_builtin]
//   icc_describe(icc, buf) -> bytes             the 'desc' tag as UTF-8 (v2 desc; v4 mluc:
//                                               German, else English, else the first
//                                               record), NUL-terminated in buf; 0 = none
//                                               (buf[0] = 0)  [icc_describe]
//
// Built-in profiles (bi_make; own numbers, no copied files): ICC v4.3, class mntr, PCS XYZ,
// D50 wtpt, desc / cprt as mluc, chad (Bradford from the space's white), colorants as
// s15.16, TRC as para.  The assembly writes them into static buffers on the first call;
// here the same function runs at compile time (const fn), so the bytes are static from the
// start and every thread may ask for them.

use crate::icc::icc_check;
use crate::icc_eval::{
    be32, le32, tag_find, CL_MNTR, CS_GRAY, CS_RGB, PARA_NP, PCS_XYZ, SIG_ACSP, TAG_BTRC, TAG_CHAD, TAG_COLS,
    TAG_CPRT, TAG_DESC, TAG_GTRC, TAG_KTRC, TAG_RTRC, TAG_WTPT, TYP_DESC, TYP_MLUC, TYP_PARA, TYP_SF32, TYP_XYZ,
};

const BI_CAP: usize = 1024; // bytes per generated profile
const BI_COUNT: usize = 5;

/// a built-in profile: colour space, para type, description, colorants (r, g, b XYZ), chad,
/// para g a b c d (s15.16)  [BD]
struct Bd {
    cs: u32,
    pt: u32,
    desc: &'static [u8],
    mat: [i32; 9],
    chad: [i32; 9],
    par: [i32; 5],
}

const I_D50: [i32; 3] = [63190, 65536, 54061];
const S_BI_CPRT: &[u8] = b"Public domain, generated by jfguiLib";
const CHAD_D65: [i32; 9] = [68674, 1502, -3291, 1939, 64912, -1119, -606, 988, 49262];
const PAR_SRGB: [i32; 5] = [157286, 62119, 3417, 5072, 2651];

