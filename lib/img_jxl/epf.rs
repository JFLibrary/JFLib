// epf -- JPEG XL edge preserving filter (stage_epf.cc; model: tools/jxl_ref.py epf0, epf1,
// epf2, epf_sigma_pixels, epf_weight, epf_finish)                       [src/img/jxl_epf.s]
//
//   jr_epf(jx, jf, jrn) -> 0 / ERR_*   the frame's EPF iterations on the 3 colour planes (in
//                                      place)
//   jr_epf_from(jx, jf, pad0, bufs, jrn)   jxl-speed: the same with the first stage reading
//                                      pad0 (pads_into of the planes before) and the later
//                                      stages padding into bufs (the writer's Recon: the
//                                      frame padded once for every sharpness it tries)
//
// The assembly's row kernels ep_k0 .. ep_k2 are generated by tools/jxl_epfgen.py (four samples
// per SSE vector); here they are one simd::Kernel (SSE2: 4, AVX2: 8 samples per register,
// every lane computes what the assembly computes for its sample) with the same operation
// sequence and operand order: weights max( sad * inv_sigma + 1, 0 ), accumulation q * wt +
// acc, result acc * (1 / wsum).

use alloc::vec;
use alloc::vec::Vec;

use img_core::ERR_HDR;
use simd::{Kernel, Simd, Sse2};

use crate::frm::Jf;
use crate::hdr::Jx;
use crate::rnd::{jr_pad_into, r4, Jrn};
use crate::tab;

const OFFS0: [(isize, isize); 12] =
    [(-2, 0), (-1, -1), (-1, 0), (-1, 1), (0, -2), (0, -1), (0, 1), (0, 2), (1, -1), (1, 0), (1, 1), (2, 0)];
const PLUS: [(isize, isize); 5] = [(0, 0), (-1, 0), (0, -1), (1, 0), (0, 1)];
const DIRS: [(isize, isize); 4] = [(-1, 0), (0, -1), (0, 1), (1, 0)];

/// one row of one EPF stage
struct EpfRow<'a> {
    stage: u32,
    p: isize,
    rows: [[&'a [f32]; 7]; 3], // rows[c][dy + 3]: padded row y + dy from column -p
    out: [&'a mut [f32]; 3],
    isg: &'a [f32],
    skip: &'a [i32],
    sc: [f32; 3],
    n: usize, // samples (a multiple of 4)
}

impl EpfRow<'_> {
    /// the samples (c, dy, dx) of the lanes at x
    #[inline(always)]
    fn q<S: Simd>(&self, s: S, c: usize, dy: isize, dx: isize, x: usize) -> S::V {
        s.load_f32(&self.rows[c][(dy + 3) as usize][(x as isize + self.p + dx) as usize..])
    }

    /// |a - b|
    #[inline(always)]
    fn ad<S: Simd>(s: S, a: S::V, b: S::V) -> S::V {
        s.and(s.subf(a, b), s.splat32(0x7FFF_FFFF))
    }

    /// weight of one direction and its accumulation
    #[inline(always)]
    #[allow(clippy::too_many_arguments)]
    fn acc<S: Simd>(&self, s: S, sad: S::V, isg: S::V, wsum: &mut S::V, a: &mut [S::V; 3], oy: isize, ox: isize, x: usize) {
        let mut wt = s.mulf(sad, isg);
        wt = s.addf(wt, s.splatf(1.0));
        wt = s.maxf(wt, s.zero());
        *wsum = s.addf(*wsum, wt);
        for c in 0..3 {
            let q = self.q(s, c, oy, ox, x);
            a[c] = s.addf(a[c], s.mulf(q, wt));
        }
    }

    /// the samples of the lanes at x
    #[inline(always)]
    fn chunk<S: Simd>(&mut self, s: S, x: usize) {
        let isg = s.load_f32(&self.isg[x..]);
        let mut a = [self.q(s, 0, 0, 0, x), self.q(s, 1, 0, 0, x), self.q(s, 2, 0, 0, x)];
        let mut wsum = s.splatf(1.0);
        match self.stage {
            0 => {
                for &(oy, ox) in &OFFS0 {
                    let mut sad = s.zero();
                    for c in 0..3 {
                        let mut t = s.zero();
                        for &(py, px) in &PLUS {
                            let d = Self::ad(s, self.q(s, c, py, px, x), self.q(s, c, oy + py, ox + px, x));
                            t = s.addf(t, d);
                        }
                        t = s.mulf(t, s.splatf(self.sc[c]));
                        sad = s.addf(sad, t);
                    }
                    self.acc(s, sad, isg, &mut wsum, &mut a, oy, ox, x);
                }
            }
            1 => {
                let mut tot = [s.zero(); 4];
                for c in 0..3 {
                    let p20 = self.q(s, c, -2, 0, x);
                    let p21 = self.q(s, c, -1, 0, x);
                    let p11 = self.q(s, c, -1, -1, x);
                    let p31 = self.q(s, c, -1, 1, x);
                    let p02 = self.q(s, c, 0, -2, x);
                    let p12 = self.q(s, c, 0, -1, x);
                    let p22 = self.q(s, c, 0, 0, x);
                    let p32 = self.q(s, c, 0, 1, x);
                    let p42 = self.q(s, c, 0, 2, x);
                    let p13 = self.q(s, c, 1, -1, x);
                    let p23 = self.q(s, c, 1, 0, x);
                    let p33 = self.q(s, c, 1, 1, x);
                    let p24 = self.q(s, c, 2, 0, x);
                    let mut s0 = Self::ad(s, p20, p21);
                    let mut s1 = Self::ad(s, p11, p21);
                    let mut s2 = Self::ad(s, p31, p21);
                    let mut t = Self::ad(s, p02, p12);
                    s1 = s.addf(s1, t);
                    t = Self::ad(s, p11, p12);
                    s0 = s.addf(s0, t);
                    t = Self::ad(s, p12, p22);
                    s1 = s.addf(s1, t);
                    s2 = s.addf(s2, t);
                    t = Self::ad(s, p22, p21);
                    let mut s3 = t;
                    s0 = s.addf(s0, t);
                    t = Self::ad(s, p31, p32);
                    s0 = s.addf(s0, t);
                    t = Self::ad(s, p22, p32);
                    s1 = s.addf(s1, t);
                    s2 = s.addf(s2, t);
                    t = Self::ad(s, p42, p32);
                    s2 = s.addf(s2, t);
                    t = Self::ad(s, p13, p12);
                    s3 = s.addf(s3, t);
                    t = Self::ad(s, p22, p23);
                    s0 = s.addf(s0, t);
                    s3 = s.addf(s3, t);
                    t = Self::ad(s, p13, p23);
                    s1 = s.addf(s1, t);
                    t = Self::ad(s, p33, p23);
                    s2 = s.addf(s2, t);
                    t = Self::ad(s, p33, p32);
                    s3 = s.addf(s3, t);
                    t = Self::ad(s, p24, p23);
                    s3 = s.addf(s3, t);
                    let sc = s.splatf(self.sc[c]);
                    tot[0] = s.addf(tot[0], s.mulf(s0, sc));
                    tot[1] = s.addf(s.mulf(s1, sc), tot[1]);
                    tot[2] = s.addf(s.mulf(s2, sc), tot[2]);
                    tot[3] = s.addf(s.mulf(s3, sc), tot[3]);
                }
                for (i, &(oy, ox)) in DIRS.iter().enumerate() {
                    self.acc(s, tot[i], isg, &mut wsum, &mut a, oy, ox, x);
                }
            }
            _ => {
                for &(oy, ox) in &DIRS {
                    let mut sad = s.zero();
                    for c in 0..3 {
                        let d = Self::ad(s, self.q(s, c, oy, ox, x), self.q(s, c, 0, 0, x));
                        let d = s.mulf(d, s.splatf(self.sc[c]));
                        sad = if c == 0 { d } else { s.addf(sad, d) };
                    }
                    self.acc(s, sad, isg, &mut wsum, &mut a, oy, ox, x);
                }
            }
        }
        // finish: skip ? p : acc / wsum
        let inv = s.divf(s.splatf(1.0), wsum);
        let mask = s.load_i32(&self.skip[x..]);
        for c in 0..3 {
            let v = s.mulf(a[c], inv);
            let p = s.and(self.q(s, c, 0, 0, x), mask);
            let r = s.or(p, s.andnot(mask, v));
            s.store_f32(&mut self.out[c][x..], r);
        }
    }
}

impl Kernel for EpfRow<'_> {
    type Out = ();
    #[inline(always)]
    fn run<S: Simd>(mut self, s: S) {
        let lanes = S::BYTES / 4;
        let mut x = 0;
        while x + lanes <= self.n {
            self.chunk(s, x);
            x += lanes;
        }
        while x < self.n {
            self.chunk(Sse2, x); // (the last 4 samples of an AVX2 row)
            x += 4;
        }
    }
}

/// the padded copies of the colour planes that stage reads (border 3 - stage), into bufs
/// (reused when they have the size: jr_pad_into)  [jxl-speed]
pub(crate) fn pads_into(jrn: &Jrn, stage: u32, bufs: &mut Vec<Vec<f32>>) -> i32 {
    if jrn.p.len() < 3 {
        return ERR_HDR;
    }
    bufs.resize_with(3, Vec::new);
    for c in 0..3 {
        if let Err(e) = jr_pad_into(&jrn.p[c], 3 - stage, &mut bufs[c]) {
            return e;
        }
    }
    0
}

/// ep_run: one EPF stage over the colour planes
fn run(jf: &Jf, jrn: &mut Jrn, stage: u32) -> i32 {
    let mut pads = Vec::new();
    let r = pads_into(jrn, stage, &mut pads);
    if r != 0 {
        return r;
    }
    run_with(jf, &pads, jrn, stage)
}

/// one EPF stage: reads pads (pads_into of the planes), writes the colour planes of jrn
fn run_with(jf: &Jf, pads: &[Vec<f32>], jrn: &mut Jrn, stage: u32) -> i32 {
    let p = 3 - stage;
    let sm = if stage == 1 {
        tab::EPF[0]
    } else {
        let v = if stage == 0 { jf.p0ss } else { jf.p2ss };
        (v as f64 * tab::RNDD[0]) as f32
    };
    let bsm = sm * jf.bsad;
    let sigc = tab::EPF[1] / jf.sigmod;
    if pads.len() < 3 || jrn.p.len() < 3 {
        return ERR_HDR;
    }
    let w0 = jrn.p[0].w;
    let n = r4(w0) as usize;
    let ps = (jrn.p[0].s + 2 * p) as usize; // (every plane is read with plane 0's padded stride)
    let rl = n + 2 * p as usize; // floats of a padded row from column -p
    let zero = vec![0f32; rl + 8];
    let minsig = tab::EPF[2];
    let jv = if jf.modular == 0 {
        match jf.vd.as_ref() {
            Some(v) => Some(v),
            None => return ERR_HDR,
        }
    } else {
        None
    };
    let h = jrn.p[0].h as usize;
    let strides = [jrn.p[0].s as usize, jrn.p[1].s as usize, jrn.p[2].s as usize];
    let [p0, p1, p2, ..] = &mut jrn.p[..] else { return ERR_HDR };
    // jxl-plus: bands of rows on the worker pool
    let planes = vec![(&mut p0.d[..], strides[0]), (&mut p1.d[..], strides[1]), (&mut p2.d[..], strides[2])];
    crate::rnd::par_bands(planes, h, |y0, nrows, b| {
        let [o0, o1, o2] = b else { return };
        let mut isg = vec![0f32; n + 8];
        let mut skip = vec![0i32; n + 8];
        for yy in 0..nrows {
            let y = y0 + yy;
            // inverse sigma row: sig( block ) * (row or column on a block border ? bsm : sm)
            let iy = y & 7;
            for x in 0..n {
                let mut sig = sigc;
                if let Some(jv) = jv {
                    let bi = (y >> 3) * jf.xb as usize + (x >> 3);
                    sig = jv.isig.get(bi).copied().unwrap_or(0.0);
                }
                skip[x] = if sig >= minsig { 0 } else { -1 };
                let ix = x & 7;
                let mul = if iy == 0 || iy == 7 || ix == 0 || ix == 7 { bsm } else { sm };
                isg[x] = sig * mul;
            }
            let mut rows: [[&[f32]; 7]; 3] = [[&zero[..]; 7]; 3];
            for c in 0..3 {
                for dy in -(p as isize)..=(p as isize) {
                    let st = (y as isize + p as isize + dy) as usize * ps;
                    rows[c][(dy + 3) as usize] = match pads[c].get(st..st + rl + 8) {
                        Some(r) => r,
                        None => match pads[c].get(st..) {
                            Some(r) if r.len() >= rl => r,
                            _ => &zero[..],
                        },
                    };
                }
            }
            let k = EpfRow {
                stage,
                p: p as isize,
                rows,
                out: [&mut o0[yy * strides[0]..], &mut o1[yy * strides[1]..], &mut o2[yy * strides[2]..]],
                isg: &isg,
                skip: &skip,
                sc: jf.epfcs,
                n,
            };
            simd::dispatch(k);
        }
    });
    0
}

/// the first EPF stage of the frame (0 with 3 iterations, else 1)
pub(crate) fn first_stage(jf: &Jf) -> u32 {
    if jf.epfit >= 3 { 0 } else { 1 }
}

/// jr_epf with the first stage reading pad0 (pads_into of the planes jrn held before, stage
/// first_stage) instead of padding jrn: the writer's reconstructions (Recon) pad the frame
/// once for every sharpness they try  [jxl-speed]
pub(crate) fn jr_epf_from(jx: &Jx, jf: &Jf, pad0: &[Vec<f32>], bufs: &mut [Vec<Vec<f32>>; 2], jrn: &mut Jrn) -> i32 {
    let _ = jx;
    let first = first_stage(jf);
    let r = run_with(jf, pad0, jrn, first);
    if r != 0 {
        return r;
    }
    // the later stages pad the planes again, into bufs (stage 1: bufs[0], stage 2: bufs[1])
    for stage in first + 1..3 {
        if stage == 2 && jf.epfit < 2 {
            break;
        }
        let b = &mut bufs[stage as usize - 1];
        let r = pads_into(jrn, stage, b);
        if r != 0 {
            return r;
        }
        let r = run_with(jf, b, jrn, stage);
        if r != 0 {
            return r;
        }
    }
    0
}

/// jr_epf: the frame's EPF iterations
pub fn jr_epf(jx: &Jx, jf: &Jf, jrn: &mut Jrn) -> i32 {
    let _ = jx;
    if jf.epfit >= 3 {
        let r = run(jf, jrn, 0);
        if r != 0 {
            return r;
        }
    }
    let r = run(jf, jrn, 1);
    if r != 0 {
        return r;
    }
    if jf.epfit >= 2 {
        return run(jf, jrn, 2);
    }
    0
}
