// ------------------------------------------------------------------ WebP encoder options (img.inc CE)
pub const IO_WEBPPRESET: usize = 36; // ImgOpt field (the IO_DDSFMT slot; ImgOpt::ddsfmt)
pub const IOM_PRESET: u32 = 1 << 19; // the preset is honoured
pub const WPP_DEFAULT: u32 = 0; // paint.net "Standard" (libwebp WEBP_PRESET_DEFAULT)
pub const WPP_PICTURE: u32 = 1;
pub const WPP_PHOTO: u32 = 2;
pub const WPP_DRAWING: u32 = 3;
pub const WPP_ICON: u32 = 4;
pub const WPP_TEXT: u32 = 5;
pub const IOF_WEBP_NOEXACT: u32 = 0x20000; // RGB under alpha 0 may change (default: kept exactly)
pub const IOF_WEBP_SHARPYUV: u32 = 0x40000; // lossy: sharp RGB -> YUV 4:2:0
pub const IOF_WEBP_1THREAD: u32 = 0x80000; // no worker threads (the output is the same either way)

// WEBPENC flags (Cfg::flags)
pub const WEF_NOEXACT: u32 = 1;
pub const WEF_NOHDR: u32 = 2; // VP8L: header-less stream (ALPH chunk)
pub const WEF_1THREAD: u32 = 4;
pub const WEF_SHARPYUV: u32 = 8;
// test-only flags (codectest ops 126..128): force a configuration / predictor mode, switch
// off stages
pub const WEF_T_CFG_SHIFT: u32 = 8; // 4 bits: VP8L configuration + 1 (0 = automatic)
pub const WEF_T_NOCROSS: u32 = 0x1000;
pub const WEF_T_DUMPM: u32 = 0x2000; // return the main image's match array (u32 dist | (len - 1) << 20)
pub const WEF_T_MODE_SHIFT: u32 = 16; // 4 bits: predictor mode + 1 for every tile
pub const WEF_T_NOCACHE: u32 = 0x10_0000;
pub const WEF_T_NOMETA: u32 = 0x20_0000;
pub const WEF_T_NODP: u32 = 0x40_0000;
pub const WEF_T_NOGREEDY: u32 = 0x80_0000;
pub const WEF_T_NORLE: u32 = 0x100_0000;
pub const WEF_T_KEEPDP: u32 = 0x200_0000;
pub const WEF_T_CACHE_SHIFT: u32 = 26; // 4 bits: colour cache bits + 1 (0 = estimate)
pub const WEF_T_REPORT: u32 = 0x4000_0000; // return 0x1000000 + (cache bits | groups << 8), no stream

/// the WEBPENC record (WE_*): effort 1..9 (0 = 5), lossy quality 0..100 (0 = 95), WEF_*
/// flags, WPP_* preset, cancel flag
#[derive(Clone, Copy, Default)]
pub struct Cfg<'a> {
    pub effort: u32,
    pub quality: u32,
    pub flags: u32,
    pub preset: u32,
    pub cancel: Option<&'a AtomicU32>,
}

impl Cfg<'_> {
    pub fn cancelled(&self) -> bool {
        self.cancel.is_some_and(|c| c.load(core::sync::atomic::Ordering::Relaxed) != 0)
    }
}

/// the codec descriptor  [webp_codec]
pub static CODEC: Codec = Codec {
    probe: Some(container::probe),
    decode: Some(container::decode),
    encode: Some(container::encode),
    caps: IFC_DECODE | IFC_ENCODE,
    iom: IOM_QUALITY | IOM_LOSSLESS | IOM_EFFORT | IOM_ICC | IOM_EXIF | IOM_XMP | IOM_PRESET,
    ..Codec::EMPTY
};
