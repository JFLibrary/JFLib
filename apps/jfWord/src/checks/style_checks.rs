// End-to-end style graphs, direct overrides, codecs, paste collisions and actual fonts.
use alloc::{format, string::String, vec, vec::Vec};
use doc_core::{Alignment, Document, Edit, Editor, FontFamily, Inline, ParagraphStyle, StyleDefinition, TextFormat};
use ui::Style;

pub(crate) fn run() -> (usize, usize) {
    let (mut passed, mut failed) = (0, 0);
    macro_rules! check { ($test:expr, $name:expr) => { if $test { passed += 1; } else { failed += 1; plat::write_stdout(format!("FAIL styles {}\n", $name).as_bytes()); } }; }
    let serif = FontFamily::new("DejaVu Serif").unwrap();
    let mono = FontFamily::new("DejaVu Sans Mono").unwrap();
    check!(FontFamily::new("").is_err() && FontFamily::new(" invalid").is_err() && FontFamily::new("a\0b").is_err() && FontFamily::new("Bad\u{ffff}font").is_err(), "font name validation");
    check!(FontFamily::new(&"ß".repeat(48)).is_ok() && FontFamily::new(&"ß".repeat(49)).is_err(), "UTF8 font name bound");
    let mut base = StyleDefinition::new(ParagraphStyle::Named(1), "Wissenschaft");
    base.text.font_family = Some(serif);
    base.text.size_half_points = Some(28);
    base.paragraph.after = 240;
    base.paragraph.alignment = Alignment::Center;
    let mut child = StyleDefinition::new(ParagraphStyle::Named(2), "Unterkapitel");
    child.based_on = Some(base.id);
    child.text.bold = Some(true);
    child.outline_level = Some(2);
    let mut d = Document::default();
    d.styles = vec![base.clone(), child.clone()];
    d.paragraphs[0].style = child.id;
    d.paragraphs[0].content = vec![Inline::Text(String::from("Alpha β"))];
    check!(d.validate().is_ok(), "valid chain");
    let effective = d.resolve_text(Default::default(), child.id);
    check!(effective.font_family == serif && effective.size_half_points == 28 && effective.bold, "inherited characters");
    check!(d.resolve_paragraph(&d.paragraphs[0]).after == 240 && d.outline_level(child.id) == Some(2), "paragraph inheritance and outline");
    let mut e = Editor::new(d).unwrap();
    e.apply(Edit::FormatStoryText { paragraph: 1, start: 0, end: 5, format: TextFormat { font_family: Some(mono), bold: Some(false), ..Default::default() } }).unwrap();
    base.text.size_half_points = Some(36);
    base.text.font_family = Some(FontFamily::default());
    base.paragraph.after = 400;
    let before = e.document().clone();
    e.apply(Edit::SetStyleDefinition(base.clone())).unwrap();
    check!(e.document().resolve_text(Default::default(), child.id).size_half_points == 36 && e.document().resolve_paragraph(&e.document().paragraphs[0]).after == 400, "parent edit propagates");
    let direct = e.document().resolve_text(e.document().paragraphs[0].content[0].format(), child.id);
    check!(direct.font_family == mono && !direct.bold && direct.size_half_points == 36, "direct overrides survive parent edits");
    check!(e.undo() && e.document() == &before && e.redo(), "style edit undo redo");
    let saved = e.document().clone();
    let revision = e.revision();
    let mut cycle = base.clone(); cycle.based_on = Some(child.id);
    check!(e.apply(Edit::SetStyleDefinition(cycle)).is_err() && e.document() == &saved && e.revision() == revision, "cycle rejected atomically");
    let mut missing = child.clone(); missing.based_on = Some(ParagraphStyle::Named(99));
    check!(e.apply(Edit::SetStyleDefinition(missing)).is_err() && e.revision() == revision, "missing base rejected");
    let mut duplicate = child.clone(); duplicate.name = base.name.clone();
    check!(e.apply(Edit::SetStyleDefinition(duplicate)).is_err(), "duplicate name rejected");
    let mut duplicate = child.clone(); duplicate.name = String::from("Standard");
    check!(e.apply(Edit::SetStyleDefinition(duplicate)).is_err(), "implicit builtin name remains reserved");
    let mut invalid_name = child.clone(); invalid_name.name = String::from("Bad\u{fffe}style");
    check!(e.apply(Edit::SetStyleDefinition(invalid_name)).is_err(), "style names remain XML representable");
    let mut geometry = Document::default();
    let mut outer = StyleDefinition::new(ParagraphStyle::Named(1), "Einzug"); outer.paragraph.left = 4000;
    let mut inner = StyleDefinition::new(ParagraphStyle::Named(2), "Hängend");
    inner.based_on = Some(outer.id); inner.paragraph.first_line = -3000;
    geometry.styles = vec![outer.clone(), inner.clone()];
    geometry.paragraphs[0].style = inner.id;
    check!(geometry.validate().is_ok(), "hanging indent uses inherited left edge");
    geometry.paragraphs[0].format.first_line = -3500;
    check!(geometry.validate().is_ok() && doc_io::decode_docx(&doc_io::encode_docx(&geometry).unwrap()) == Ok(geometry.clone()), "direct hanging indent and inherited left survive DOCX");
    geometry.paragraphs[0].style = ParagraphStyle::Normal; geometry.paragraphs[0].format = Default::default();
    inner.paragraph.first_line = 0; inner.paragraph.right = 6000; geometry.styles[1] = inner;
    check!(geometry.validate().is_err(), "unused inherited styles must retain a text area");
    let mut patch = Editor::new(e.document().clone()).unwrap();
    patch.apply(Edit::FormatStoryParagraphs { paragraph: 1, start: 0, end: 5, change: doc_core::ParagraphChange::Properties(doc_core::ParagraphFormat { left: 200, ..Default::default() }.select(16)) }).unwrap();
    let mut parent = base.clone(); parent.paragraph.after = 600;
    patch.apply(Edit::SetStyleDefinition(parent)).unwrap();
    let p = patch.document().resolve_paragraph(&patch.document().paragraphs[0]);
    check!(p.left == 200 && p.after == 600, "single-property changes retain other inheritance");
    check!(e.apply(Edit::SetStyle { paragraph: 1, style: ParagraphStyle::Named(99) }).is_err(), "dangling paragraph style rejected");
    e.apply(Edit::FormatStoryParagraphs { paragraph: 1, start: 0, end: 5, change: doc_core::ParagraphChange::Alignment(Alignment::Left) }).unwrap();
    check!(e.document().resolve_paragraph(&e.document().paragraphs[0]).alignment == Alignment::Left, "explicit default overrides inherited center");
    let bytes = doc_io::encode_docx(e.document()).unwrap();
    check!(doc_io::decode_docx(&bytes).as_ref() == Ok(e.document()), "DOCX styles fonts and masks roundtrip");
    let package = archive::read(&bytes, archive::Limits::default()).unwrap();
    let styles = package.iter().find(|p| p.name == "word/styles.xml").unwrap();
    let xml = core::str::from_utf8(&styles.data).unwrap();
    check!(xml.contains("w:basedOn w:val=\"jfStyle1\"") && xml.contains("w:outlineLvl w:val=\"2\""), "standard Word style links");
    let fragment = e.document().copy_story_range(1, 0, "Alpha β".len()).unwrap();
    let encoded = doc_io::encode_document_fragment(&fragment).unwrap();
    check!(doc_io::decode_document_fragment(&encoded).as_ref() == Ok(&fragment), "native rich clipboard retains graph");
    let mut destination = Document::default();
    let mut normal = destination.style_definition(ParagraphStyle::Normal).unwrap();
    normal.text.font_family = Some(serif);
    let mut conflict = StyleDefinition::new(base.id, "Zielvorlage"); conflict.text.italic = Some(true);
    destination.styles = vec![normal, conflict.clone()];
    let mut target = Editor::new(destination).unwrap();
    target.replace_story_fragment(1, 0, 0, fragment).unwrap();
    let pasted = &target.document().paragraphs[0];
    check!(pasted.style != child.id && target.document().style_definition(base.id) == Some(conflict), "paste preserves destination style identities");
    for (index, node) in pasted.content.iter().enumerate().take(2) {
        check!(target.document().resolve_text(node.format(), pasted.style) == e.document().resolve_text(e.document().paragraphs[0].content[index].format(), child.id), "paste retains effective formats");
    }
    let mut title = StyleDefinition::new(ParagraphStyle::Title, "Titel"); title.based_on = Some(base.id);
    let mut custom = e.document().clone(); custom.styles.push(title); custom.paragraphs[0].style = ParagraphStyle::Title;
    check!(custom.resolve_text(Default::default(), ParagraphStyle::Title).size_half_points == 36, "builtins can inherit custom styles");
    let mut unicode = e.document().clone();
    unicode.paragraphs[0].content = vec![Inline::with_format(String::from("Übertragung Ω"), TextFormat { font_family: Some(FontFamily::new("Schrift α 𝄞").unwrap()), ..Default::default() })];
    let rtf = doc_io::clipboard_rtf_encode(&unicode).unwrap();
    let rtf_doc = doc_io::clipboard_rtf_decode(&rtf).unwrap();
    check!(rtf_doc.paragraphs[0].content[0].format().font_family == unicode.paragraphs[0].content[0].format().font_family, "RTF Unicode family names");
    check!(rtf_doc.plain_text() == unicode.plain_text() && rtf_doc.paragraphs[0].content[0].format().size_half_points == Some(36), "RTF resolved inheritance");
    let html = String::from_utf8(doc_io::clipboard_html_encode(&unicode).unwrap()).unwrap();
    check!(html.contains("font-family:'Schrift \\3b1  \\1d11e '") && html.contains("font-size:18.00pt"), "HTML font CSS escapes and inherited size");
    let mut t = text::Text::new(style::STYLE.fonts(), style::STYLE.font_names());
    let fonts = doc_view::Fonts::new(&mut t).unwrap();
    let mut widths = Vec::new();
    for family in [FontFamily::default(), serif, mono] {
        let mut doc = Document::default();
        doc.paragraphs[0].content = vec![Inline::with_format(String::from("iiii WWWW"), TextFormat { font_family: Some(family), ..Default::default() })];
        let layout = doc_view::paginate(&doc, &mut t, &fonts).unwrap();
        widths.push(layout.pages[0].lines[0].fragments.iter().map(|f| f.width).sum::<i32>());
        check!(!fonts.substituted(family) && layout.pages[0].lines[0].fragments[0].format.font_family == family, "bundled font used by layout");
    }
    check!(widths[0] != widths[1] && widths[1] != widths[2], "different real font metrics");
    let unknown = FontFamily::new("jfWord nonexistent family 2468").unwrap();
    fonts.ensure(&mut t, unknown);
    check!(fonts.substituted(unknown), "missing font explicitly reported");
    let copy = fonts.clone();
    check!(copy.valid(&t), "shared font cache valid");
    (passed, failed)
}
