/// pn_cmd_set(id, flags) -- CF_DISABLED | CF_CHECKED | CF_HIDDEN of a command.  Call it from
/// MOD_states (start of the frame); a change requests another pass.
pub(crate) fn pn_cmd_set(ui: &mut Ui, id: u32, flags: u32) {
    if ui.cmd_flags(id) != flags {
        ui.cmd_state(id, flags);
    }
}

/// pn_cmd_flags(id) -> CF_* of a command (0 when unknown)
pub(crate) fn pn_cmd_flags(ui: &Ui, id: u32) -> u32 {
    ui.cmd_flags(id)
}

/// pn_cmd_ptr(id) -> the (first) command record of id: label, icon, key, mods may be changed
/// at run time (flags: use pn_cmd_set); the table is published after the callback
pub(crate) fn pn_cmd_ptr(p: &mut Pn, id: u32) -> Option<&mut Command> {
    if id == 0 {
        return None;
    }
    let c = p.cmds.iter_mut().find(|c| c.id == id)?;
    p.cmds_dirty = true;
    Some(c)
}

/// pn_cmd_label(id, str) -- replace the label of a command ('&' marks the mnemonic, "&&" is a
/// literal '&')
pub(crate) fn pn_cmd_label(p: &mut Pn, id: u32, s: &str) {
    let l: &'static str = String::from(s).leak();
    if let Some(c) = pn_cmd_ptr(p, id) {
        c.label = l;
        p.repass();
    }
}
