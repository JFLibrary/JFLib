// icons -- JFNetworker's pictures: the device symbols with their raster cache and the theme's
// palette per category, and the UI icons of tools and panels
//
//   Symbols::new()                 parse every symbol of symbols_data.rs once
//   syms.index(name)               a symbol by its name (Model::symbol)
//   syms.update(ui) -> changed     the palettes of the theme (once per frame)
//   syms.draw(g, i, x, y, w, tint, off)   a symbol w px wide (raster from the cache, above
//                                  256 px the vectors); off = without power (45 %)
//   syms.draw_as(g, i, x, y, w, &pal, opacity)   ... in any palette and opacity
//   syms.key()                     changes with the palettes (versions of canvases)
//   tint_of(category)              the palette slot of a catalog category
//   port_icon(media)               the JN_PORT_* icon of a kind of port
//   install(ui)                    the icon hook that draws the JN_* code points
//
// symbols_data.rs is generated by tools/vsym.py from icons/*.svg, icons_data.rs by mkicons.py
// (do not edit either).  Category colours (light values): end devices and notes neutral
// grey, network steel blue, security brick, wireless and WAN teal, servers slate violet,
// distributed systems olive.

mod icons_data;
mod symbols_data;

use alloc::rc::Rc;
use alloc::vec::Vec;
use core::cell::{Cell, RefCell};

use jfn_model::Category;
use ui::{Gfx, SymPalette, Symbol, SymbolCache, Ui};

pub(crate) use symbols_data::SYMBOL_GRID;

// the UI icons (private use code points, drawn by the hook in every style)
pub(crate) const JN_SELECT: u32 = 0x10_F100;
pub(crate) const JN_HAND: u32 = 0x10_F101;
pub(crate) const JN_CONNECT: u32 = 0x10_F102;
pub(crate) const JN_NOTE: u32 = 0x10_F103;
pub(crate) const JN_FIT: u32 = 0x10_F104;
pub(crate) const JN_GRID: u32 = 0x10_F105;
pub(crate) const JN_SNAP: u32 = 0x10_F106;
pub(crate) const JN_MINIMAP: u32 = 0x10_F107;
pub(crate) const JN_DEVICES: u32 = 0x10_F108;
pub(crate) const JN_TERMINAL: u32 = 0x10_F109;
pub(crate) const JN_PACKET: u32 = 0x10_F10A;
// the kinds of ports (the port choice when connecting, the interfaces of the inspector)
pub(crate) const JN_PORT_RJ45: u32 = 0x10_F10B;
pub(crate) const JN_PORT_SFP: u32 = 0x10_F10C;
pub(crate) const JN_PORT_SERIAL: u32 = 0x10_F10D;
pub(crate) const JN_PORT_CONSOLE: u32 = 0x10_F10E;
pub(crate) const JN_PORT_USB: u32 = 0x10_F10F;
pub(crate) const JN_PORT_RADIO: u32 = 0x10_F110;
pub(crate) const JN_PORT_WAN: u32 = 0x10_F111;
// the Metriken panel (U6a)
pub(crate) const JN_METRICS: u32 = 0x10_F112;

/// the icon of a kind of port
pub(crate) fn port_icon(m: jfn_model::Media) -> u32 {
    use jfn_model::Media::*;
    match m {
        Rj45 => JN_PORT_RJ45,
        Sfp | SfpPlus | Sfp28 | Qsfp28 => JN_PORT_SFP,
        Serial => JN_PORT_SERIAL,
        Console => JN_PORT_CONSOLE,
        Usb => JN_PORT_USB,
        RadioAp | RadioClient => JN_PORT_RADIO,
        Wan => JN_PORT_WAN,
    }
}

/// the category colours 0xRRGGBB (light values): the palette slots
pub(crate) const TINTS: [u32; 6] = [0x8A_929C, 0x4F_7396, 0xA6_5A4A, 0x3E_8A86, 0x6A_6390, 0x9E_9047];

/// the opacity of a device without power (45 %)
pub(crate) const OFF_OPACITY: u32 = 115;

/// the palette slot of a category
pub(crate) fn tint_of(c: Category) -> usize {
    match c {
        Category::EndDevices | Category::Annotations => 0,
        Category::Network => 1,
        Category::Security => 2,
        Category::WirelessWan => 3,
        Category::Servers => 4,
        Category::Distributed => 5,
    }
}

/// install the hook that draws the JN_* icons
pub(crate) fn install(ui: &mut Ui) {
    ui.icon_hook(Some(Rc::new(|g: &mut Gfx, cp: u32, x: i32, y: i32, size: i32, argb: u32| match icons_data::art(cp) {
        Some((art, stroke)) => ui::paint_svg_icon(g, art, x, y, size, argb, stroke),
        None => false,
    })));
}

/// the parsed device symbols, their rasters and the palettes of the theme (shared with the
/// render-time drawings of the canvas and the palette tiles)
pub(crate) struct Symbols {
    names: Vec<&'static str>,
    syms: Vec<Symbol>,
    cache: RefCell<SymbolCache>,
    pals: RefCell<[SymPalette; TINTS.len()]>,
    key: Cell<u32>,
}

impl Symbols {
    pub(crate) fn new() -> Symbols {
        let none = SymPalette { c: [0; ui::SYM_ROLES] };
        Symbols {
            names: symbols_data::SYMBOLS.iter().map(|s| s.0).collect(),
            syms: symbols_data::SYMBOLS.iter().map(|s| Symbol::parse(s.1, SYMBOL_GRID)).collect(),
            cache: RefCell::new(SymbolCache::new()),
            pals: RefCell::new([none; TINTS.len()]),
            key: Cell::new(0),
        }
    }

    /// the index of a symbol by its name (Model::symbol)
    pub(crate) fn index(&self, name: &str) -> Option<usize> {
        self.names.iter().position(|n| *n == name)
    }

    /// the palette of a slot
    pub(crate) fn pal(&self, tint: usize) -> SymPalette {
        self.pals.borrow()[tint.min(TINTS.len() - 1)]
    }

    /// changes whenever a palette changes
    pub(crate) fn key(&self) -> u32 {
        self.key.get()
    }

    /// the palettes of the current theme -> they changed
    pub(crate) fn update(&self, ui: &Ui) -> bool {
        let mut pals = self.pals.borrow_mut();
        let mut key: u32 = 0x811C_9DC5;
        for (k, &t) in TINTS.iter().enumerate() {
            pals[k] = SymPalette::from_theme(ui, t);
            key = (key ^ pals[k].hash()).wrapping_mul(0x0100_0193);
        }
        let changed = key != self.key.get();
        self.key.set(key);
        changed
    }

    /// symbol i w px wide with its top left at x, y (render time); off: no power
    #[allow(clippy::too_many_arguments)]
    pub(crate) fn draw(&self, g: &mut Gfx, i: usize, x: i32, y: i32, w: i32, tint: usize, off: bool) {
        if off {
            self.draw_as(g, i, x, y, w, &self.pal(tint).powered_off(), OFF_OPACITY);
        } else {
            self.draw_as(g, i, x, y, w, &self.pal(tint), 255);
        }
    }

    /// symbol i w px wide in a palette at an opacity 0..255 (render time)
    #[allow(clippy::too_many_arguments)]
    pub(crate) fn draw_as(&self, g: &mut Gfx, i: usize, x: i32, y: i32, w: i32, pal: &SymPalette, opacity: u32) {
        let Some(sym) = self.syms.get(i) else { return };
        let Ok(mut cache) = self.cache.try_borrow_mut() else { return };
        cache.draw(g, i as u32, sym, x, y, w, pal, opacity);
    }

    /// the height of symbol i drawn w px wide
    pub(crate) fn height(&self, i: usize, w: i32) -> i32 {
        self.syms.get(i).map_or(w * 3 / 4, |s| s.height(w))
    }
}
