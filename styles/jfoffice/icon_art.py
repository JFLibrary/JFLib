ART = {}


def line(*points, color=C): return ("Path", color, False, False, points)
def closed(*points, color=C): return ("Path", color, True, False, points)
def fill(*points, color=C): return ("Path", color, True, True, points)
def box(x, y, xx, yy, color=C, filled=False): return ("Box", color, filled, x, y, xx, yy)
def dot(x, y, radius, color=C, filled=False): return ("Circle", color, filled, x, y, radius)
def text(x, y, size, value, color=C, bold=False): return ("Text", color, bold, x, y, size, value)
def lines(x, xx, ys, color=C): return [line((x,y),(xx,y),color=color) for y in ys]
def page(x=4,y=2,xx=16,yy=18):
    return [closed((x,y),(xx-4,y),(xx,y+4),(xx,yy),(x,yy)),
            line((xx-4,y),(xx-4,y+4),(xx,y+4))]
def icon(name, *ops): ART[name] = list(ops)
def aliases(names, source):
    for name in names.split(): ART[name] = list(ART[source])
def page_text(name, value, size=8): icon(name,*page(),text(10,10,size,value,A,True))

