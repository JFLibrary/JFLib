// mem -- the C symbols core needs in a library without a C runtime: memcpy, memmove, memset,
// memcmp, bcmp; on Windows also _fltused, __chkstk and __CxxFrameHandler3
//                                               [the plugin counterpart of lib/rt/mem.rs]
//
// Written in assembly (global_asm) rather than as #[no_mangle] Rust functions: rustc exports
// every #[no_mangle] item of every crate from a cdylib, and a plugin must export exactly
// pn_plugin_query.  Assembly symbols are invisible to rustc's export list (Windows: not in the
// .def file; Linux: local through the version script).  rep movsb / stosb as in rt; the C
// calling convention of the platform (Windows x64: rcx, rdx, r8; System V: rdi, rsi, rdx).

#[cfg(windows)]
core::arch::global_asm!(
    ".text",
    // memcpy(dst, src, n) -> dst      (rdi / rsi are callee-saved: kept in r9 / r10)
    ".globl memcpy",
    "memcpy:",
    "    mov rax, rcx",
    "    mov r9, rdi",
    "    mov r10, rsi",
    "    mov rdi, rcx",
    "    mov rsi, rdx",
    "    mov rcx, r8",
    "    rep movsb",
    "    mov rdi, r9",
    "    mov rsi, r10",
    "    ret",
    // memmove(dst, src, n) -> dst     (backwards when dst starts inside src)
    ".globl memmove",
    "memmove:",
    "    mov rax, rcx",
    "    mov r9, rdi",
    "    mov r10, rsi",
    "    mov rdi, rcx",
    "    mov rsi, rdx",
    "    mov rcx, r8",
    "    cmp rdi, rsi",
    "    jbe 2f",
    "    lea r11, [rsi + rcx]",
    "    cmp rdi, r11",
    "    jae 2f",
    "    lea rdi, [rdi + rcx - 1]",
    "    lea rsi, [rsi + rcx - 1]",
    "    std",
    "    rep movsb",
    "    cld",
    "    jmp 3f",
    "2:",
    "    rep movsb",
    "3:",
    "    mov rdi, r9",
    "    mov rsi, r10",
    "    ret",
    // memset(dst, c, n) -> dst
    ".globl memset",
    "memset:",
    "    mov r9, rdi",
    "    mov r10, rcx",
    "    mov rdi, rcx",
    "    mov eax, edx",
    "    mov rcx, r8",
    "    rep stosb",
    "    mov rdi, r9",
    "    mov rax, r10",
    "    ret",
    // memcmp(a, b, n) -> <0 / 0 / >0 ; bcmp the same
    ".globl memcmp",
    ".globl bcmp",
    "memcmp:",
    "bcmp:",
    "    xor eax, eax",
    "4:",
    "    test r8, r8",
    "    jz 5f",
    "    movzx eax, byte ptr [rcx]",
    "    movzx r9d, byte ptr [rdx]",
    "    sub eax, r9d",
    "    jnz 5f",
    "    inc rcx",
    "    inc rdx",
    "    dec r8",
    "    jmp 4b",
    "5:",
    "    ret",
    // __chkstk: frames over 4 KB touch every page from the top down (rax = frame size)
    ".globl __chkstk",
    "__chkstk:",
    "    push rcx",
    "    push rax",
    "    cmp rax, 4096",
    "    lea rcx, [rsp + 24]",
    "    jb 7f",
    "6:",
    "    sub rcx, 4096",
    "    test [rcx], rcx",
    "    sub rax, 4096",
    "    cmp rax, 4096",
    "    ja 6b",
    "7:",
    "    sub rcx, rax",
    "    test [rcx], rcx",
    "    pop rax",
    "    pop rcx",
    "    ret",
    // __CxxFrameHandler3: the language handler of core's unwind data (panic=abort never
    // unwinds): ExceptionContinueSearch
    ".globl __CxxFrameHandler3",
    "__CxxFrameHandler3:",
    "    mov eax, 1",
    "    ret",
    ".data",
    ".globl _fltused",
    "_fltused:",
    "    .long 0",
    ".text",
);

#[cfg(not(windows))]
core::arch::global_asm!(
    ".text",
    // memcpy(dst, src, n) -> dst
    ".globl memcpy",
    ".type memcpy, @function",
    "memcpy:",
    "    mov rax, rdi",
    "    mov rcx, rdx",
    "    rep movsb",
    "    ret",
    // memmove(dst, src, n) -> dst     (backwards when dst starts inside src)
    ".globl memmove",
    ".type memmove, @function",
    "memmove:",
    "    mov rax, rdi",
    "    mov rcx, rdx",
    "    cmp rdi, rsi",
    "    jbe 2f",
    "    lea r8, [rsi + rcx]",
    "    cmp rdi, r8",
    "    jae 2f",
    "    lea rdi, [rdi + rcx - 1]",
    "    lea rsi, [rsi + rcx - 1]",
    "    std",
    "    rep movsb",
    "    cld",
    "    ret",
    "2:",
    "    rep movsb",
    "    ret",
    // memset(dst, c, n) -> dst
    ".globl memset",
    ".type memset, @function",
    "memset:",
    "    mov r8, rdi",
    "    mov eax, esi",
    "    mov rcx, rdx",
    "    rep stosb",
    "    mov rax, r8",
    "    ret",
    // memcmp(a, b, n) -> <0 / 0 / >0 ; bcmp the same
    ".globl memcmp",
    ".type memcmp, @function",
    ".globl bcmp",
    ".type bcmp, @function",
    "memcmp:",
    "bcmp:",
    "    xor eax, eax",
    "4:",
    "    test rdx, rdx",
    "    jz 5f",
    "    movzx eax, byte ptr [rdi]",
    "    movzx ecx, byte ptr [rsi]",
    "    sub eax, ecx",
    "    jnz 5f",
    "    inc rdi",
    "    inc rsi",
    "    dec rdx",
    "    jmp 4b",
    "5:",
    "    ret",
);
