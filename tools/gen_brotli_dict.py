#!/usr/bin/env python3
"""gen_brotli_dict.py -- the Brotli static dictionary (RFC 7932 appendix A) and transform list
(appendix B) for the Brotli decoder of lib/img_jxl (brotli.rs: JPEG reconstruction from
the jbrd box).  Read from the system's libbrotlicommon through ctypes (WSL on Windows):

  python tools/gen_brotli_dict.py        -> lib/img_jxl/brotli_dict.bin, brotli_tab.rs

The dictionary data is 122784 bytes (SHA-256 checked below); the tables are written as Rust.
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "lib/img_jxl"
DICT_SHA256 = "20e42eb1b511c21806d4d227d07e5dd06877d8ce7b3a817f378f313653f35c70"  # RFC 7932 appendix A

WSL_CODE = r'''
import ctypes as C, json, sys
lib = C.CDLL("libbrotlicommon.so.1")
class Dict(C.Structure):
    _fields_ = [("size_bits", C.c_uint8 * 32), ("offsets", C.c_uint32 * 32), ("data_size", C.c_size_t),
                ("data", C.POINTER(C.c_uint8))]
class Tr(C.Structure):
    _fields_ = [("ps_size", C.c_uint16), ("ps", C.POINTER(C.c_uint8)), ("ps_map", C.POINTER(C.c_uint16)),
                ("num", C.c_uint32), ("triplets", C.POINTER(C.c_uint8)), ("params", C.POINTER(C.c_uint8)),
                ("cutoff", C.c_int16 * 10)]
lib.BrotliGetDictionary.restype = C.POINTER(Dict)
lib.BrotliGetTransforms.restype = C.POINTER(Tr)
d = lib.BrotliGetDictionary().contents
t = lib.BrotliGetTransforms().contents
data = bytes(d.data[:d.data_size])
open(sys.argv[1], "wb").write(data)
ctx = bytes((C.c_uint8 * 2048).in_dll(lib, "_kBrotliContextLookupTable"))
pcr = bytes((C.c_uint8 * (26 * 4)).in_dll(lib, "_kBrotliPrefixCodeRanges"))
json.dump({"ctx": list(ctx), "blocklen": [[pcr[4 * i] | pcr[4 * i + 1] << 8, pcr[4 * i + 2]] for i in range(26)],
           "size_bits": list(d.size_bits), "offsets": list(d.offsets), "num": t.num,
           "triplets": [t.triplets[i] for i in range(3 * t.num)], "ps": [t.ps[i] for i in range(t.ps_size)],
           "ps_map": [t.ps_map[i] for i in range(50)]}, open(sys.argv[2], "w"))
'''


def main():
    tmp = ROOT / "build" / "gen_brotli"
    tmp.mkdir(parents=True, exist_ok=True)
    script = tmp / "dump.py"
    script.write_text(WSL_CODE, encoding="utf-8", newline="\n")
    rel = lambda p: str(p.resolve().relative_to(ROOT)).replace("\\", "/")  # noqa: E731
    dbin, djs = tmp / "dict.bin", tmp / "tab.json"
    cmd = ["python3", rel(script), rel(dbin), rel(djs)]
    if sys.platform == "win32":
        cmd = ["wsl.exe", "-d", "Ubuntu-24.04", "--cd", str(ROOT), "-e"] + cmd
    subprocess.run(cmd, cwd=ROOT, check=True)
    data = dbin.read_bytes()
    tab = json.loads(djs.read_text())
    assert len(data) == 122784, len(data)
    sha = hashlib.sha256(data).hexdigest()
    print("dictionary", len(data), "bytes, sha256", sha)
    if DICT_SHA256:
        assert sha == DICT_SHA256
    (OUT / "brotli_dict.bin").write_bytes(data)
    trip = tab["triplets"]

    def arr(name, ty, vals, per):
        out = ["pub static %s: [%s; %d] = [" % (name, ty, len(vals))]
        for i in range(0, len(vals), per):
            out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
        return out + ["];"]
    lines = ["// brotli_tab -- Brotli static dictionary layout and the 121 word transforms (RFC 7932",
             "// appendices A and B); generated by tools/gen_brotli_dict.py, do not edit",
             "",
             "/// bits of the word index per word length"]
    lines += arr("SIZE_BITS", "u8", tab["size_bits"], 16)
    lines += ["/// offset of the words of each length in the dictionary data"]
    lines += arr("OFFSETS", "u32", tab["offsets"], 12)
    lines += ["/// the transforms: (prefix id, type, suffix id)", "pub static TRANSFORMS: [[u8; 3]; %d] = [" % tab["num"]]
    for i in range(tab["num"]):
        lines.append("    [%d, %d, %d]," % tuple(trip[3 * i:3 * i + 3]))
    lines.append("];")
    lines.append("/// prefix / suffix strings: length byte, then the bytes")
    lines.append("pub static PREFIX_SUFFIX: [u8; %d] = [" % len(tab["ps"]))
    ps = tab["ps"]
    for i in range(0, len(ps), 24):
        lines.append("    " + ", ".join(str(v) for v in ps[i:i + 24]) + ",")
    lines.append("];")
    lines.append("/// start of each prefix / suffix id in PREFIX_SUFFIX")
    lines.append("pub static PREFIX_SUFFIX_MAP: [u16; 50] = [")
    pm = tab["ps_map"]
    for i in range(0, 50, 16):
        lines.append("    " + ", ".join(str(v) for v in pm[i:i + 16]) + ",")
    lines.append("];")
    lines.append("/// context lookup: mode * 512 + (p1 table, p2 table)")
    lines += arr("CONTEXT_LUT", "u8", tab["ctx"], 32)
    lines.append("/// block length codes: (offset, extra bits)")
    lines.append("pub static BLOCK_LEN: [(u16, u8); 26] = [")
    for i in range(0, 26, 6):
        lines.append("    " + ", ".join("(%d, %d)" % tuple(v) for v in tab["blocklen"][i:i + 6]) + ",")
    lines.append("];")
    (OUT / "brotli_tab.rs").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote", OUT / "brotli_dict.bin", OUT / "brotli_tab.rs")


if __name__ == "__main__":
    main()
