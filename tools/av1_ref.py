def decode(data, apply_grain=True):
    """decode an AV1 OBU stream; returns the first shown Frame"""
    frames = Decoder(apply_grain).decode(data)
    if not frames:
        raise AV1Error("no frame")
    return frames[0]


def write_yuv(fr, path):
    """planar output: 8 bit samples as bytes, higher bit depths as 16 bit little endian"""
    out = bytearray()
    for p in fr.planes:
        for row in p:
            if fr.bitdepth == 8:
                out += bytes(row)
            else:
                for v in row:
                    out += v.to_bytes(2, "little")
    Path(path).write_bytes(bytes(out))


def main():
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
