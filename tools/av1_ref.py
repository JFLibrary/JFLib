class Bits:
    """f(n) reader over a byte string; reads past the end return zero bits"""

    def __init__(self, data, pos=0, end=None):
        self.d = data
        self.p = pos * 8
        self.end = len(data) if end is None else end

    def f(self, n):
        x = 0
        for _ in range(n):
            byte = self.p >> 3
            b = (self.d[byte] >> (7 - (self.p & 7))) & 1 if byte < self.end else 0
            x = (x << 1) | b
            self.p += 1
        return x

    def pos(self):
        return self.p

    def byte_pos(self):
        return (self.p + 7) >> 3

    def byte_alignment(self):
        while self.p & 7:
            self.f(1)

    def uvlc(self):
        lz = 0
        while not self.f(1):
            lz += 1
            if lz > 40:
                raise AV1Error("uvlc")
        if lz >= 32:
            return (1 << 32) - 1
        return self.f(lz) + (1 << lz) - 1

    def le(self, n):
        t = 0
        for i in range(n):
            t += self.f(8) << (i * 8)
        return t

    def leb128(self):
        v = 0
        for i in range(8):
            b = self.f(8)
            v |= (b & 0x7F) << (i * 7)
            if not b & 0x80:
                break
        return v

    def su(self, n):
        v = self.f(n)
        m = 1 << (n - 1)
        if v & m:
            v -= 2 * m
        return v

    def ns(self, n):
        w = FloorLog2(n) + 1
        m = (1 << w) - n
        v = self.f(w - 1)
        if v < m:
            return v
        return (v << 1) - m + self.f(1)


class Frame:
    """one decoded (shown) frame: planes[p][y][x] (p = 0..NumPlanes-1), sizes in samples"""

    def __init__(self):
        self.planes = []
        self.w = self.h = 0
        self.subx = self.suby = 0
        self.bitdepth = 8
        self.mono = 0
        self.cicp = (2, 2, 2, 0)        # primaries, transfer, matrix, full range
