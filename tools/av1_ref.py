    # ------------------------------------------------------------------ symbol decoder
    def init_symbol(self, data, start, sz):
        self.sb = Bits(data, start, start + sz)
        numBits = min(sz * 8, 15)
        buf = self.sb.f(numBits)
        paddedBuf = buf << (15 - numBits)
        self.SymbolValue = ((1 << 15) - 1) ^ paddedBuf
        self.SymbolRange = 1 << 15
        self.SymbolMaxBits = 8 * sz - 15
        self.cdf = {k: cdf_copy(v) for k, v in self.fcdf.items()}
        self.cdf["IntraFrameYMode"] = cdf_copy(Default_Intra_Frame_Y_Mode_Cdf)

    def read_symbol(self, cdf):
        N = len(cdf) - 1
        cur = self.SymbolRange
        symbol = -1
        while True:
            symbol += 1
            prev = cur
            f = (1 << 15) - cdf[symbol]
            cur = ((self.SymbolRange >> 8) * (f >> EC_PROB_SHIFT)) >> (7 - EC_PROB_SHIFT)
            cur += EC_MIN_PROB * (N - symbol - 1)
            if not (self.SymbolValue < cur):
                break
        self.SymbolRange = prev - cur
        self.SymbolValue -= cur
        bits = 15 - FloorLog2(self.SymbolRange)
        self.SymbolRange <<= bits
        numBits = min(bits, max(0, self.SymbolMaxBits))
        newData = self.sb.f(numBits)
        paddedData = newData << (bits - numBits)
        self.SymbolValue = paddedData ^ (((self.SymbolValue + 1) << bits) - 1)
        self.SymbolMaxBits -= bits
        if not self.disable_cdf_update:
            rate = 3 + (cdf[N] > 15) + (cdf[N] > 31) + min(FloorLog2(N), 2)
            tmp = 0
            for i in range(N - 1):
                if i == symbol:
                    tmp = 1 << 15
                if tmp < cdf[i]:
                    cdf[i] -= (cdf[i] - tmp) >> rate
                else:
                    cdf[i] += (tmp - cdf[i]) >> rate
            cdf[N] += cdf[N] < 32
        return symbol

    def read_bool(self):
        return self.read_symbol([1 << 14, 1 << 15, 0])

    def L(self, n):
        x = 0
        for _ in range(n):
            x = 2 * x + self.read_bool()
        return x

    def NS(self, n):
        w = FloorLog2(n) + 1
        m = (1 << w) - n
        v = self.L(w - 1)
        if v < m:
            return v
        return (v << 1) - m + self.L(1)

    # ------------------------------------------------------------------ tile group
    def tile_group_obu(self, data, b, end):
        NumTiles = self.TileCols * self.TileRows
        tile_start_and_end_present_flag = 0
        if NumTiles > 1:
            tile_start_and_end_present_flag = b.f(1)
        if NumTiles == 1 or not tile_start_and_end_present_flag:
            tg_start, tg_end = 0, NumTiles - 1
        else:
            tileBits = self.TileColsLog2 + self.TileRowsLog2
            tg_start = b.f(tileBits)
            tg_end = b.f(tileBits)
        b.byte_alignment()
        pos = b.p >> 3
        for TileNum in range(tg_start, tg_end + 1):
            self.TileNum = TileNum
            tileRow = TileNum // self.TileCols
            tileCol = TileNum % self.TileCols
            if TileNum == tg_end:
                tileSize = end - pos
            else:
                tb = Bits(data, pos, end)
                tileSize = tb.le(self.TileSizeBytes) + 1
                pos += self.TileSizeBytes
            if tileSize <= 0 or pos + tileSize > end:
                raise AV1Error("tile size")
            self.MiRowStart = self.MiRowStarts[tileRow]
            self.MiRowEnd = self.MiRowStarts[tileRow + 1]
            self.MiColStart = self.MiColStarts[tileCol]
            self.MiColEnd = self.MiColStarts[tileCol + 1]
            self.CurrentQIndex = self.base_q_idx
            self.init_symbol(data, pos, tileSize)
            self.decode_tile()
            pos += tileSize
        if tg_end == NumTiles - 1:
            self.decode_frame_wrapup()
            self.SeenFrameHeader = 0

    def decode_tile(self):
        np_ = self.NumPlanes
        W = (self.MiCols + 40)
        H = (self.MiRows + 40)
        # clear_above_context
        self.AboveLevelContext = [[0] * W for _ in range(3)]
        self.AboveDcContext = [[0] * W for _ in range(3)]
        self.AboveSegPredContext = [0] * W
        self.DeltaLF = [0] * FRAME_LF_COUNT
        self.RefSgrXqd = [list(Sgrproj_Xqd_Mid) for _ in range(np_)]
        self.RefLrWiener = [[list(Wiener_Taps_Mid) for _ in range(2)] for _ in range(np_)]
        sbSize = BLOCK_128X128 if self.use_128x128_superblock else BLOCK_64X64
        sbSize4 = Num_4x4_Blocks_Wide[sbSize]
        for r in range(self.MiRowStart, self.MiRowEnd, sbSize4):
            # clear_left_context
            self.LeftLevelContext = [[0] * H for _ in range(3)]
            self.LeftDcContext = [[0] * H for _ in range(3)]
            self.LeftSegPredContext = [0] * H
            for c in range(self.MiColStart, self.MiColEnd, sbSize4):
                self.ReadDeltas = self.delta_q_present
                self.clear_cdef(r, c)
                self.clear_block_decoded_flags(r, c, sbSize4)
                self.read_lr(r, c, sbSize)
                self.decode_partition(r, c, sbSize)

    def clear_cdef(self, r, c):
        self.cdef_idx[r][c] = -1
        if self.use_128x128_superblock:
            s = Num_4x4_Blocks_Wide[BLOCK_64X64]
            self.cdef_idx[r][c + s] = -1
            self.cdef_idx[r + s][c] = -1
            self.cdef_idx[r + s][c + s] = -1

    def clear_block_decoded_flags(self, r, c, sbSize4):
        # BlockDecoded[plane][y][x] stored at [y + 1][x + 1]
        self.BlockDecoded = []
        for plane in range(self.NumPlanes):
            subX = self.subsampling_x if plane else 0
            subY = self.subsampling_y if plane else 0
            sbWidth4 = (self.MiColEnd - c) >> subX
            sbHeight4 = (self.MiRowEnd - r) >> subY
            bd = grid(34, 34)
            for y in range(-1, (sbSize4 >> subY) + 1):
                for x in range(-1, (sbSize4 >> subX) + 1):
                    if y < 0 and x < sbWidth4:
                        v = 1
                    elif x < 0 and y < sbHeight4:
                        v = 1
                    else:
                        v = 0
                    bd[y + 1][x + 1] = v
            bd[(sbSize4 >> subY) + 1][0] = 0
            self.BlockDecoded.append(bd)

    def bdec(self, plane, y, x):
        return self.BlockDecoded[plane][y + 1][x + 1]

    def is_inside(self, r, c):
        return self.MiColStart <= c < self.MiColEnd and self.MiRowStart <= r < self.MiRowEnd

    # ------------------------------------------------------------------ loop restoration syntax
    def read_lr(self, r, c, bSize):
        w = Num_4x4_Blocks_Wide[bSize]
        h = Num_4x4_Blocks_High[bSize]
        for plane in range(self.NumPlanes):
            if self.FrameRestorationType[plane] != RESTORE_NONE:
                subX = self.subsampling_x if plane else 0
                subY = self.subsampling_y if plane else 0
                unitSize = self.LoopRestorationSize[plane]
                unitRows = self.count_units_in_frame(unitSize, Round2(self.FrameHeight, subY))
                unitCols = self.count_units_in_frame(unitSize, Round2(self.UpscaledWidth, subX))
                unitRowStart = (r * (MI_SIZE >> subY) + unitSize - 1) // unitSize
                unitRowEnd = min(unitRows, ((r + h) * (MI_SIZE >> subY) + unitSize - 1) // unitSize)
                if self.use_superres:
                    numerator = (MI_SIZE >> subX) * self.SuperresDenom
                    denominator = unitSize * SUPERRES_NUM
                else:
                    numerator = MI_SIZE >> subX
                    denominator = unitSize
                unitColStart = (c * numerator + denominator - 1) // denominator
                unitColEnd = min(unitCols, ((c + w) * numerator + denominator - 1) // denominator)
                for unitRow in range(unitRowStart, unitRowEnd):
                    for unitCol in range(unitColStart, unitColEnd):
                        self.read_lr_unit(plane, unitRow, unitCol)

    def read_lr_unit(self, plane, unitRow, unitCol):
        frt = self.FrameRestorationType[plane]
        if frt == RESTORE_WIENER:
            restoration_type = RESTORE_WIENER if self.read_symbol(self.cdf["UseWiener"]) else RESTORE_NONE
        elif frt == RESTORE_SGRPROJ:
            restoration_type = RESTORE_SGRPROJ if self.read_symbol(self.cdf["UseSgrproj"]) else RESTORE_NONE
        else:
            restoration_type = self.read_symbol(self.cdf["RestorationType"])
        self.LrType[plane][unitRow][unitCol] = restoration_type
        self.st("lr%d" % restoration_type)
        if restoration_type == RESTORE_WIENER:
            for pss in range(2):
                if plane:
                    firstCoeff = 1
                    self.LrWiener[plane][unitRow][unitCol][pss][0] = 0
                else:
                    firstCoeff = 0
                for j in range(firstCoeff, 3):
                    mn = Wiener_Taps_Min[j]
                    mx = Wiener_Taps_Max[j]
                    k = Wiener_Taps_K[j]
                    v = self.decode_signed_subexp_with_ref_bool(mn, mx + 1, k, self.RefLrWiener[plane][pss][j])
                    self.LrWiener[plane][unitRow][unitCol][pss][j] = v
                    self.RefLrWiener[plane][pss][j] = v
        elif restoration_type == RESTORE_SGRPROJ:
            s = self.L(SGRPROJ_PARAMS_BITS)
            self.LrSgrSet[plane][unitRow][unitCol] = s
            for i in range(2):
                radius = Sgr_Params[s][i * 2]
                mn = Sgrproj_Xqd_Min[i]
                mx = Sgrproj_Xqd_Max[i]
                if radius:
                    v = self.decode_signed_subexp_with_ref_bool(mn, mx + 1, SGRPROJ_PRJ_SUBEXP_K,
                                                                self.RefSgrXqd[plane][i])
                else:
                    v = 0
                    if i == 1:
                        v = Clip3(mn, mx, (1 << SGRPROJ_PRJ_BITS) - self.RefSgrXqd[plane][0])
                self.LrSgrXqd[plane][unitRow][unitCol][i] = v
                self.RefSgrXqd[plane][i] = v

    def decode_signed_subexp_with_ref_bool(self, low, high, k, r):
        return self.decode_unsigned_subexp_with_ref_bool(high - low, k, r - low) + low

    def decode_unsigned_subexp_with_ref_bool(self, mx, k, r):
        v = self.decode_subexp_bool(mx, k)
        if (r << 1) <= mx:
            return inverse_recenter(r, v)
        return mx - 1 - inverse_recenter(mx - 1 - r, v)

    def decode_subexp_bool(self, numSyms, k):
        i = 0
        mk = 0
        while True:
            b2 = k + i - 1 if i else k
            a = 1 << b2
            if numSyms <= mk + 3 * a:
                return self.NS(numSyms - mk) + mk
            if self.L(1):
                i += 1
                mk += a
            else:
                return self.L(b2) + mk

    # ------------------------------------------------------------------ partition / block
    def decode_partition(self, r, c, bSize):
        if r >= self.MiRows or c >= self.MiCols:
            return
        AvailU = self.is_inside(r - 1, c)
        AvailL = self.is_inside(r, c - 1)
        num4x4 = Num_4x4_Blocks_Wide[bSize]
        halfBlock4x4 = num4x4 >> 1
        quarterBlock4x4 = halfBlock4x4 >> 1
        hasRows = (r + halfBlock4x4) < self.MiRows
        hasCols = (c + halfBlock4x4) < self.MiCols
        if bSize < BLOCK_8X8:
            partition = PARTITION_NONE
        elif hasRows and hasCols:
            partition = self.read_symbol(self.partition_cdf(r, c, bSize, AvailU, AvailL))
        elif hasCols:
            pc = self.partition_cdf(r, c, bSize, AvailU, AvailL)
            psum = (pc[PARTITION_VERT] - pc[PARTITION_VERT - 1] + pc[PARTITION_SPLIT] - pc[PARTITION_SPLIT - 1]
                    + pc[PARTITION_HORZ_A] - pc[PARTITION_HORZ_A - 1] + pc[PARTITION_VERT_A] - pc[PARTITION_VERT_A - 1]
                    + pc[PARTITION_VERT_B] - pc[PARTITION_VERT_B - 1])
            if bSize != BLOCK_128X128:
                psum += pc[PARTITION_VERT_4] - pc[PARTITION_VERT_4 - 1]
            split_or_horz = self.read_symbol([(1 << 15) - psum, 1 << 15, 0])
            partition = PARTITION_SPLIT if split_or_horz else PARTITION_HORZ
        elif hasRows:
            pc = self.partition_cdf(r, c, bSize, AvailU, AvailL)
            psum = (pc[PARTITION_HORZ] - pc[PARTITION_HORZ - 1] + pc[PARTITION_SPLIT] - pc[PARTITION_SPLIT - 1]
                    + pc[PARTITION_HORZ_A] - pc[PARTITION_HORZ_A - 1] + pc[PARTITION_HORZ_B] - pc[PARTITION_HORZ_B - 1]
                    + pc[PARTITION_VERT_A] - pc[PARTITION_VERT_A - 1])
            if bSize != BLOCK_128X128:
                psum += pc[PARTITION_HORZ_4] - pc[PARTITION_HORZ_4 - 1]
            split_or_vert = self.read_symbol([(1 << 15) - psum, 1 << 15, 0])
            partition = PARTITION_SPLIT if split_or_vert else PARTITION_VERT
        else:
            partition = PARTITION_SPLIT
        subSize = Partition_Subsize[partition][bSize]
        splitSize = Partition_Subsize[PARTITION_SPLIT][bSize]
        db = self.decode_block
        if partition == PARTITION_NONE:
            db(r, c, subSize)
        elif partition == PARTITION_HORZ:
            db(r, c, subSize)
            if hasRows:
                db(r + halfBlock4x4, c, subSize)
        elif partition == PARTITION_VERT:
            db(r, c, subSize)
            if hasCols:
                db(r, c + halfBlock4x4, subSize)
        elif partition == PARTITION_SPLIT:
            self.decode_partition(r, c, subSize)
            self.decode_partition(r, c + halfBlock4x4, subSize)
            self.decode_partition(r + halfBlock4x4, c, subSize)
            self.decode_partition(r + halfBlock4x4, c + halfBlock4x4, subSize)
        elif partition == PARTITION_HORZ_A:
            db(r, c, splitSize)
            db(r, c + halfBlock4x4, splitSize)
            db(r + halfBlock4x4, c, subSize)
        elif partition == PARTITION_HORZ_B:
            db(r, c, subSize)
            db(r + halfBlock4x4, c, splitSize)
            db(r + halfBlock4x4, c + halfBlock4x4, splitSize)
        elif partition == PARTITION_VERT_A:
            db(r, c, splitSize)
            db(r + halfBlock4x4, c, splitSize)
            db(r, c + halfBlock4x4, subSize)
        elif partition == PARTITION_VERT_B:
            db(r, c, subSize)
            db(r, c + halfBlock4x4, splitSize)
            db(r + halfBlock4x4, c + halfBlock4x4, splitSize)
        elif partition == PARTITION_HORZ_4:
            for i in range(4):
                if i < 3 or r + quarterBlock4x4 * 3 < self.MiRows:
                    db(r + quarterBlock4x4 * i, c, subSize)
        else:
            for i in range(4):
                if i < 3 or c + quarterBlock4x4 * 3 < self.MiCols:
                    db(r, c + quarterBlock4x4 * i, subSize)

    def partition_cdf(self, r, c, bSize, AvailU, AvailL):
        bsl = Mi_Width_Log2[bSize]
        above = AvailU and (Mi_Width_Log2[self.MiSizes[r - 1][c]] < bsl)
        left = AvailL and (Mi_Height_Log2[self.MiSizes[r][c - 1]] < bsl)
        ctx = int(left) * 2 + int(above)
        name = {1: "PartitionW8", 2: "PartitionW16", 3: "PartitionW32", 4: "PartitionW64", 5: "PartitionW128"}[bsl]
        return self.cdf[name][ctx]

    def decode_block(self, r, c, subSize):
        self.MiRow = r
        self.MiCol = c
        self.MiSize = subSize
        bw4 = Num_4x4_Blocks_Wide[subSize]
        bh4 = Num_4x4_Blocks_High[subSize]
        ssx, ssy = self.subsampling_x, self.subsampling_y
        if bh4 == 1 and ssy and (r & 1) == 0:
            self.HasChroma = 0
        elif bw4 == 1 and ssx and (c & 1) == 0:
            self.HasChroma = 0
        else:
            self.HasChroma = int(self.NumPlanes > 1)
        self.AvailU = self.is_inside(r - 1, c)
        self.AvailL = self.is_inside(r, c - 1)
        self.AvailUChroma = self.AvailU
        self.AvailLChroma = self.AvailL
        if self.HasChroma:
            if ssy and bh4 == 1:
                self.AvailUChroma = self.is_inside(r - 2, c)
            if ssx and bw4 == 1:
                self.AvailLChroma = self.is_inside(r, c - 2)
        else:
            self.AvailUChroma = self.AvailLChroma = 0
        self.intra_frame_mode_info()
        self.palette_tokens()
        self.read_block_tx_size()
        if self.skip:
            self.reset_block_context(bw4, bh4)
        for y in range(bh4):
            ym = self.YModes[r + y]
            uvm = self.UVModes[r + y]
            for x in range(bw4):
                ym[c + x] = self.YMode
                if self.HasChroma:
                    uvm[c + x] = self.UVMode
        self.compute_prediction()
        self.residual()
        for y in range(bh4):
            for x in range(bw4):
                self.Skips[r + y][c + x] = self.skip
                self.TxSizes[r + y][c + x] = self.TxSize
                self.MiSizes[r + y][c + x] = self.MiSize
                self.SegmentIds[r + y][c + x] = self.segment_id
                self.PaletteSizes[0][r + y][c + x] = self.PaletteSizeY
                self.PaletteSizes[1][r + y][c + x] = self.PaletteSizeUV
                self.PaletteColors[0][r + y][c + x] = self.palette_colors_y
                self.PaletteColors[1][r + y][c + x] = self.palette_colors_u
                self.DeltaLFs[r + y][c + x] = list(self.DeltaLF)
        self.stats["blocks"] = self.stats.get("blocks", 0) + 1

    def reset_block_context(self, bw4, bh4):
        for plane in range(1 + 2 * self.HasChroma):
            subX = self.subsampling_x if plane else 0
            subY = self.subsampling_y if plane else 0
            for i in range(self.MiCol >> subX, (self.MiCol + bw4) >> subX):
                self.AboveLevelContext[plane][i] = 0
                self.AboveDcContext[plane][i] = 0
            for i in range(self.MiRow >> subY, (self.MiRow + bh4) >> subY):
                self.LeftLevelContext[plane][i] = 0
                self.LeftDcContext[plane][i] = 0

    def intra_frame_mode_info(self):
        self.skip = 0
        if self.SegIdPreSkip:
            self.intra_segment_id()
        self.read_skip()
        if not self.SegIdPreSkip:
            self.intra_segment_id()
        self.read_cdef()
        self.read_delta_qindex()
        self.read_delta_lf()
        self.ReadDeltas = 0
        self.use_intrabc = 0
        self.is_inter = 0
        abovemode = Intra_Mode_Context[self.YModes[self.MiRow - 1][self.MiCol] if self.AvailU else DC_PRED]
        leftmode = Intra_Mode_Context[self.YModes[self.MiRow][self.MiCol - 1] if self.AvailL else DC_PRED]
        self.YMode = self.read_symbol(self.cdf["IntraFrameYMode"][abovemode][leftmode])
        self.intra_angle_info_y()
        self.UVMode = DC_PRED
        self.AngleDeltaUV = 0
        self.CflAlphaU = self.CflAlphaV = 0
        if self.HasChroma:
            self.UVMode = self.read_symbol(self.uv_mode_cdf())
            if self.UVMode == UV_CFL_PRED:
                self.read_cfl_alphas()
                self.st("cfl")
            self.intra_angle_info_uv()
        self.PaletteSizeY = 0
        self.PaletteSizeUV = 0
        self.palette_colors_y = None
        self.palette_colors_u = None
        self.palette_colors_v = None
        if (self.MiSize >= BLOCK_8X8 and Block_Width[self.MiSize] <= 64 and Block_Height[self.MiSize] <= 64
                and self.allow_screen_content_tools):
            self.palette_mode_info()
        self.filter_intra_mode_info()

    def uv_mode_cdf(self):
        if self.Lossless and self.get_plane_residual_size(self.MiSize, 1) == BLOCK_4X4:
            return self.cdf["UVModeCflAllowed"][self.YMode]
        if not self.Lossless and max(Block_Width[self.MiSize], Block_Height[self.MiSize]) <= 32:
            return self.cdf["UVModeCflAllowed"][self.YMode]
        return self.cdf["UVModeCflNotAllowed"][self.YMode]

    def intra_segment_id(self):
        if self.segmentation_enabled:
            self.read_segment_id()
        else:
            self.segment_id = 0
        self.Lossless = self.LosslessArray[self.segment_id]

    def read_segment_id(self):
        r, c = self.MiRow, self.MiCol
        prevUL = self.SegmentIds[r - 1][c - 1] if (self.AvailU and self.AvailL) else -1
        prevU = self.SegmentIds[r - 1][c] if self.AvailU else -1
        prevL = self.SegmentIds[r][c - 1] if self.AvailL else -1
        if prevU == -1:
            pred = 0 if prevL == -1 else prevL
        elif prevL == -1:
            pred = prevU
        else:
            pred = prevU if prevUL == prevU else prevL
        if self.skip:
            self.segment_id = pred
        else:
            if prevUL < 0:
                ctx = 0
            elif prevUL == prevU and prevUL == prevL:
                ctx = 2
            elif prevUL == prevU or prevUL == prevL or prevU == prevL:
                ctx = 1
            else:
                ctx = 0
            s = self.read_symbol(self.cdf["SegmentId"][ctx])
            self.segment_id = neg_deinterleave(s, pred, self.LastActiveSegId + 1)

    def seg_feature_active(self, feature):
        return self.seg_feature_active_idx(self.segment_id, feature)

    def read_skip(self):
        if self.SegIdPreSkip and self.seg_feature_active(SEG_LVL_SKIP):
            self.skip = 1
        else:
            ctx = 0
            if self.AvailU:
                ctx += self.Skips[self.MiRow - 1][self.MiCol]
            if self.AvailL:
                ctx += self.Skips[self.MiRow][self.MiCol - 1]
            self.skip = self.read_symbol(self.cdf["Skip"][ctx])

    def read_cdef(self):
        if self.skip or self.CodedLossless or not self.enable_cdef or self.allow_intrabc:
            return
        cdefSize4 = Num_4x4_Blocks_Wide[BLOCK_64X64]
        cdefMask4 = ~(cdefSize4 - 1)
        r = self.MiRow & cdefMask4
        c = self.MiCol & cdefMask4
        if self.cdef_idx[r][c] == -1:
            self.cdef_idx[r][c] = self.L(self.cdef_bits)
            w4 = Num_4x4_Blocks_Wide[self.MiSize]
            h4 = Num_4x4_Blocks_High[self.MiSize]
            for i in range(r, r + h4, cdefSize4):
                for j in range(c, c + w4, cdefSize4):
                    self.cdef_idx[i][j] = self.cdef_idx[r][c]

    def read_delta_qindex(self):
        sbSize = BLOCK_128X128 if self.use_128x128_superblock else BLOCK_64X64
        if self.MiSize == sbSize and self.skip:
            return
        if self.ReadDeltas:
            delta_q_abs = self.read_symbol(self.cdf["DeltaQ"])
            if delta_q_abs == DELTA_Q_SMALL:
                rem = self.L(3) + 1
                delta_q_abs = self.L(rem) + (1 << rem) + 1
            if delta_q_abs:
                sign = self.L(1)
                red = -delta_q_abs if sign else delta_q_abs
                self.CurrentQIndex = Clip3(1, 255, self.CurrentQIndex + (red << self.delta_q_res))

    def read_delta_lf(self):
        sbSize = BLOCK_128X128 if self.use_128x128_superblock else BLOCK_64X64
        if self.MiSize == sbSize and self.skip:
            return
        if self.ReadDeltas and self.delta_lf_present:
            frameLfCount = 1
            if self.delta_lf_multi:
                frameLfCount = FRAME_LF_COUNT if self.NumPlanes > 1 else FRAME_LF_COUNT - 2
            for i in range(frameLfCount):
                cdf = self.cdf["DeltaLFMulti"][i] if self.delta_lf_multi else self.cdf["DeltaLF"]
                delta_lf_abs = self.read_symbol(cdf)
                if delta_lf_abs == DELTA_LF_SMALL:
                    n = self.L(3) + 1
                    deltaLfAbs = self.L(n) + (1 << n) + 1
                else:
                    deltaLfAbs = delta_lf_abs
                if deltaLfAbs:
                    sign = self.L(1)
                    red = -deltaLfAbs if sign else deltaLfAbs
                    self.DeltaLF[i] = Clip3(-MAX_LOOP_FILTER, MAX_LOOP_FILTER,
                                            self.DeltaLF[i] + (red << self.delta_lf_res))

    def intra_angle_info_y(self):
        self.AngleDeltaY = 0
        if self.MiSize >= BLOCK_8X8 and V_PRED <= self.YMode <= D67_PRED:
            self.AngleDeltaY = self.read_symbol(self.cdf["AngleDelta"][self.YMode - V_PRED]) - MAX_ANGLE_DELTA

    def intra_angle_info_uv(self):
        self.AngleDeltaUV = 0
        if self.MiSize >= BLOCK_8X8 and V_PRED <= self.UVMode <= D67_PRED:
            self.AngleDeltaUV = self.read_symbol(self.cdf["AngleDelta"][self.UVMode - V_PRED]) - MAX_ANGLE_DELTA

    def read_cfl_alphas(self):
        signs = self.read_symbol(self.cdf["CflSign"])
        signU = (signs + 1) // 3
        signV = (signs + 1) % 3
        if signU != CFL_SIGN_ZERO:
            ctx = (signU - 1) * 3 + signV
            self.CflAlphaU = 1 + self.read_symbol(self.cdf["CflAlpha"][ctx])
            if signU == CFL_SIGN_NEG:
                self.CflAlphaU = -self.CflAlphaU
        else:
            self.CflAlphaU = 0
        if signV != CFL_SIGN_ZERO:
            ctx = (signV - 1) * 3 + signU
            self.CflAlphaV = 1 + self.read_symbol(self.cdf["CflAlpha"][ctx])
            if signV == CFL_SIGN_NEG:
                self.CflAlphaV = -self.CflAlphaV
        else:
            self.CflAlphaV = 0

    def filter_intra_mode_info(self):
        self.use_filter_intra = 0
        if (self.enable_filter_intra and self.YMode == DC_PRED and self.PaletteSizeY == 0
                and max(Block_Width[self.MiSize], Block_Height[self.MiSize]) <= 32):
            self.use_filter_intra = self.read_symbol(self.cdf["FilterIntra"][self.MiSize])
            if self.use_filter_intra:
                self.filter_intra_mode = self.read_symbol(self.cdf["FilterIntraMode"])
                self.st("filter_intra")

    # ------------------------------------------------------------------ palette syntax
    def Clip1(self, x):
        return Clip3(0, (1 << self.BitDepth) - 1, x)

    def palette_mode_info(self):
        bsizeCtx = Mi_Width_Log2[self.MiSize] + Mi_Height_Log2[self.MiSize] - 2
        bd = self.BitDepth
        if self.YMode == DC_PRED:
            ctx = 0
            if self.AvailU and self.PaletteSizes[0][self.MiRow - 1][self.MiCol] > 0:
                ctx += 1
            if self.AvailL and self.PaletteSizes[0][self.MiRow][self.MiCol - 1] > 0:
                ctx += 1
            if self.read_symbol(self.cdf["PaletteYMode"][bsizeCtx][ctx]):
                self.PaletteSizeY = self.read_symbol(self.cdf["PaletteYSize"][bsizeCtx]) + 2
                cache = self.get_palette_cache(0)
                colors = []
                for i in range(len(cache)):
                    if len(colors) >= self.PaletteSizeY:
                        break
                    if self.L(1):
                        colors.append(cache[i])
                if len(colors) < self.PaletteSizeY:
                    colors.append(self.L(bd))
                if len(colors) < self.PaletteSizeY:
                    minBits = bd - 3
                    paletteBits = minBits + self.L(2)
                while len(colors) < self.PaletteSizeY:
                    delta = self.L(paletteBits) + 1
                    v = self.Clip1(colors[-1] + delta)
                    colors.append(v)
                    rng = (1 << bd) - v - 1
                    paletteBits = min(paletteBits, CeilLog2(rng))
                self.palette_colors_y = sorted(colors)
                self.st("palette_y")
        if self.HasChroma and self.UVMode == DC_PRED:
            ctx = 1 if self.PaletteSizeY > 0 else 0
            if self.read_symbol(self.cdf["PaletteUVMode"][ctx]):
                self.PaletteSizeUV = self.read_symbol(self.cdf["PaletteUVSize"][bsizeCtx]) + 2
                cache = self.get_palette_cache(1)
                colors = []
                for i in range(len(cache)):
                    if len(colors) >= self.PaletteSizeUV:
                        break
                    if self.L(1):
                        colors.append(cache[i])
                if len(colors) < self.PaletteSizeUV:
                    colors.append(self.L(bd))
                if len(colors) < self.PaletteSizeUV:
                    minBits = bd - 3
                    paletteBits = minBits + self.L(2)
                while len(colors) < self.PaletteSizeUV:
                    delta = self.L(paletteBits)
                    v = self.Clip1(colors[-1] + delta)
                    colors.append(v)
                    rng = (1 << bd) - v
                    paletteBits = min(paletteBits, CeilLog2(rng))
                self.palette_colors_u = sorted(colors)
                vcol = [0] * self.PaletteSizeUV
                if self.L(1):   # delta_encode_palette_colors_v
                    minBits = bd - 4
                    maxVal = 1 << bd
                    paletteBits = minBits + self.L(2)
                    vcol[0] = self.L(bd)
                    for idx in range(1, self.PaletteSizeUV):
                        d = self.L(paletteBits)
                        if d:
                            if self.L(1):
                                d = -d
                        val = vcol[idx - 1] + d
                        if val < 0:
                            val += maxVal
                        if val >= maxVal:
                            val -= maxVal
                        vcol[idx] = self.Clip1(val)
                else:
                    for idx in range(self.PaletteSizeUV):
                        vcol[idx] = self.L(bd)
                self.palette_colors_v = vcol
                self.st("palette_uv")

    def get_palette_cache(self, plane):
        r, c = self.MiRow, self.MiCol
        aboveN = 0
        if (r * MI_SIZE) % 64:
            aboveN = self.PaletteSizes[plane][r - 1][c]
        leftN = 0
        if self.AvailL:
            leftN = self.PaletteSizes[plane][r][c - 1]
        above = self.PaletteColors[plane][r - 1][c] if aboveN else []
        left = self.PaletteColors[plane][r][c - 1] if leftN else []
        ai = li = 0
        cache = []
        while ai < aboveN and li < leftN:
            aboveC = above[ai]
            leftC = left[li]
            if leftC < aboveC:
                if not cache or leftC != cache[-1]:
                    cache.append(leftC)
                li += 1
            else:
                if not cache or aboveC != cache[-1]:
                    cache.append(aboveC)
                ai += 1
                if leftC == aboveC:
                    li += 1
        while ai < aboveN:
            val = above[ai]
            ai += 1
            if not cache or val != cache[-1]:
                cache.append(val)
        while li < leftN:
            val = left[li]
            li += 1
            if not cache or val != cache[-1]:
                cache.append(val)
        return cache

    def palette_tokens(self):
        blockHeight = Block_Height[self.MiSize]
        blockWidth = Block_Width[self.MiSize]
        onscreenHeight = min(blockHeight, (self.MiRows - self.MiRow) * MI_SIZE)
        onscreenWidth = min(blockWidth, (self.MiCols - self.MiCol) * MI_SIZE)
        if self.PaletteSizeY:
            self.ColorMapY = self.read_color_map(self.PaletteSizeY, "Y", blockWidth, blockHeight,
                                                 onscreenWidth, onscreenHeight)
        if self.PaletteSizeUV:
            blockHeight >>= self.subsampling_y
            blockWidth >>= self.subsampling_x
            onscreenHeight >>= self.subsampling_y
            onscreenWidth >>= self.subsampling_x
            if blockWidth < 4:
                blockWidth += 2
                onscreenWidth += 2
            if blockHeight < 4:
                blockHeight += 2
                onscreenHeight += 2
            self.ColorMapUV = self.read_color_map(self.PaletteSizeUV, "UV", blockWidth, blockHeight,
                                                  onscreenWidth, onscreenHeight)

    def read_color_map(self, n, pl, blockWidth, blockHeight, onscreenWidth, onscreenHeight):
        cm = grid(blockHeight, blockWidth)
        cm[0][0] = self.NS(n)
        cdfs = self.cdf["PaletteSize%d%sColor" % (n, pl)]
        for i in range(1, onscreenHeight + onscreenWidth - 1):
            for j in range(min(i, onscreenWidth - 1), max(0, i - onscreenHeight + 1) - 1, -1):
                order, h = self.get_palette_color_context(cm, i - j, j, n)
                ctx = Palette_Color_Context[h]
                cm[i - j][j] = order[self.read_symbol(cdfs[ctx])]
        for i in range(onscreenHeight):
            for j in range(onscreenWidth, blockWidth):
                cm[i][j] = cm[i][onscreenWidth - 1]
        for i in range(onscreenHeight, blockHeight):
            cm[i] = list(cm[onscreenHeight - 1])
        return cm

    @staticmethod
    def get_palette_color_context(colorMap, r, c, n):
        scores = [0] * PALETTE_COLORS
        order = list(range(PALETTE_COLORS))
        if c > 0:
            scores[colorMap[r][c - 1]] += 2
        if r > 0 and c > 0:
            scores[colorMap[r - 1][c - 1]] += 1
        if r > 0:
            scores[colorMap[r - 1][c]] += 2
        for i in range(PALETTE_NUM_NEIGHBORS):
            maxScore = scores[i]
            maxIdx = i
            for j in range(i + 1, n):
                if scores[j] > maxScore:
                    maxScore = scores[j]
                    maxIdx = j
            if maxIdx != i:
                maxScore = scores[maxIdx]
                maxColorOrder = order[maxIdx]
                for k in range(maxIdx, i, -1):
                    scores[k] = scores[k - 1]
                    order[k] = order[k - 1]
                scores[i] = maxScore
                order[i] = maxColorOrder
        h = 0
        for i in range(PALETTE_NUM_NEIGHBORS):
            h += scores[i] * Palette_Color_Hash_Multipliers[i]
        return order, h

