def Round2(x, n):
    if n == 0:
        return x
    return (x + (1 << (n - 1))) >> n


def Round2Signed(x, n):
    return Round2(x, n) if x >= 0 else -Round2(-x, n)


def Clip3(lo, hi, x):
    return lo if x < lo else hi if x > hi else x


def FloorLog2(x):
    return x.bit_length() - 1


def CeilLog2(x):
    return 0 if x < 2 else (x - 1).bit_length()


def tile_log2(blkSize, target):
    k = 0
    while (blkSize << k) < target:
        k += 1
    return k


def inverse_recenter(r, v):
    if v > 2 * r:
        return v
    if v & 1:
        return r - ((v + 1) >> 1)
    return r + (v >> 1)


def neg_deinterleave(diff, ref, mx):
    if not ref:
        return diff
    if ref >= mx - 1:
        return mx - diff - 1
    if 2 * ref < mx:
        if diff <= 2 * ref:
            if diff & 1:
                return ref + ((diff + 1) >> 1)
            return ref - (diff >> 1)
        return diff
    if diff <= 2 * (mx - ref - 1):
        if diff & 1:
            return ref + ((diff + 1) >> 1)
        return ref - (diff >> 1)
    return mx - (diff + 1)


def get_tx_class(txType):
    if txType in (V_DCT, V_ADST, V_FLIPADST):
        return TX_CLASS_VERT
    if txType in (H_DCT, H_ADST, H_FLIPADST):
        return TX_CLASS_HORIZ
    return TX_CLASS_2D


def find_tx_size(w, h):
    for txSz in range(TX_SIZES_ALL):
        if Tx_Width[txSz] == w and Tx_Height[txSz] == h:
            return txSz
    return TX_SIZES_ALL


def cdf_copy(v):
    if isinstance(v[0], list):
        return [cdf_copy(x) for x in v]
    return list(v)


def grid(h, w, v=0):
    return [[v] * w for _ in range(h)]


