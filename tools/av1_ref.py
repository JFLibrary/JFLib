def adst_in_perm(T_, n):
    n0 = 1 << n
    copyT = list(T_)
    for i in range(n0):
        idx = (i - 1) if (i & 1) else (n0 - i - 1)
        T_[i] = copyT[idx]


def adst_out_perm(T_, n):
    n0 = 1 << n
    copyT = list(T_)
    for i in range(n0):
        a = (i >> 3) & 1
        b = ((i >> 2) & 1) ^ ((i >> 3) & 1)
        c = ((i >> 1) & 1) ^ ((i >> 2) & 1)
        d = (i & 1) ^ ((i >> 1) & 1)
        idx = ((d << 3) | (c << 2) | (b << 1) | a) >> (4 - n)
        T_[i] = -copyT[idx] if (i & 1) else copyT[idx]


def iadst4(T_):
    s = [0] * 7
    s[0] = SINPI_1_9 * T_[0]
    s[1] = SINPI_2_9 * T_[0]
    s[2] = SINPI_3_9 * T_[1]
    s[3] = SINPI_4_9 * T_[2]
    s[4] = SINPI_1_9 * T_[2]
    s[5] = SINPI_2_9 * T_[3]
    s[6] = SINPI_4_9 * T_[3]
    a7 = T_[0] - T_[2]
    b7 = a7 + T_[3]
    s[0] = s[0] + s[3]
    s[1] = s[1] - s[4]
    s[3] = s[2]
    s[2] = SINPI_3_9 * b7
    s[0] = s[0] + s[5]
    s[1] = s[1] - s[6]
    x0 = s[0] + s[3]
    x1 = s[1] + s[3]
    x2 = s[2]
    x3 = s[0] + s[1]
    x3 = x3 - s[3]
    T_[0] = Round2(x0, 12)
    T_[1] = Round2(x1, 12)
    T_[2] = Round2(x2, 12)
    T_[3] = Round2(x3, 12)


def iadst8(T_, r):
    adst_in_perm(T_, 3)
    for i in range(4):
        _B(T_, 2 * i, 2 * i + 1, 60 - 16 * i, 1)
    for i in range(4):
        _H(T_, i, 4 + i, 0, r)
    for i in range(2):
        _B(T_, 4 + 3 * i, 5 + i, 48 - 32 * i, 1)
    for i in range(2):
        for j in range(2):
            _H(T_, 4 * j + i, 2 + 4 * j + i, 0, r)
    for i in range(2):
        _B(T_, 2 + 4 * i, 3 + 4 * i, 32, 1)
    adst_out_perm(T_, 3)


def iadst16(T_, r):
    adst_in_perm(T_, 4)
    for i in range(8):
        _B(T_, 2 * i, 2 * i + 1, 62 - 8 * i, 1)
    for i in range(8):
        _H(T_, i, 8 + i, 0, r)
    for i in range(2):
        _B(T_, 8 + 2 * i, 9 + 2 * i, 56 - 32 * i, 1)
        _B(T_, 13 + 2 * i, 12 + 2 * i, 8 + 32 * i, 1)
    for i in range(4):
        for j in range(2):
            _H(T_, 8 * j + i, 4 + 8 * j + i, 0, r)
    for i in range(2):
        for j in range(2):
            _B(T_, 4 + 8 * j + 3 * i, 5 + 8 * j + i, 48 - 32 * i, 1)
    for i in range(2):
        for j in range(4):
            _H(T_, 4 * j + i, 2 + 4 * j + i, 0, r)
    for i in range(4):
        _B(T_, 2 + 4 * i, 3 + 4 * i, 32, 1)
    adst_out_perm(T_, 4)


def iadst(T_, n, r):
    if n == 2:
        iadst4(T_)
    elif n == 3:
        iadst8(T_, r)
    else:
        iadst16(T_, r)


def iwht(T_, shift):
    a = T_[0] >> shift
    c = T_[1] >> shift
    d = T_[2] >> shift
    b = T_[3] >> shift
    a += c
    d -= b
    e = (a - d) >> 1
    b = e - b
    c = e - c
    a -= b
    d += c
    T_[0] = a
    T_[1] = b
    T_[2] = c
    T_[3] = d


def iidentity(T_, n):
    if n == 2:
        for i in range(4):
            T_[i] = Round2(T_[i] * 5793, 12)
    elif n == 3:
        for i in range(8):
            T_[i] = T_[i] * 2
    elif n == 4:
        for i in range(16):
            T_[i] = Round2(T_[i] * 11586, 12)
    else:
        for i in range(32):
            T_[i] = T_[i] * 4


