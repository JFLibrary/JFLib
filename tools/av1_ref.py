    def tile_info(self, b):
        sb128 = self.use_128x128_superblock
        sbCols = ((self.MiCols + 31) >> 5) if sb128 else ((self.MiCols + 15) >> 4)
        sbRows = ((self.MiRows + 31) >> 5) if sb128 else ((self.MiRows + 15) >> 4)
        sbShift = 5 if sb128 else 4
        sbSize = sbShift + 2
        maxTileWidthSb = MAX_TILE_WIDTH >> sbSize
        maxTileAreaSb = MAX_TILE_AREA >> (2 * sbSize)
        minLog2TileCols = tile_log2(maxTileWidthSb, sbCols)
        maxLog2TileCols = tile_log2(1, min(sbCols, MAX_TILE_COLS))
        maxLog2TileRows = tile_log2(1, min(sbRows, MAX_TILE_ROWS))
        minLog2Tiles = max(minLog2TileCols, tile_log2(maxTileAreaSb, sbRows * sbCols))
        self.MiColStarts = []
        self.MiRowStarts = []
        if b.f(1):      # uniform_tile_spacing_flag
            self.TileColsLog2 = minLog2TileCols
            while self.TileColsLog2 < maxLog2TileCols:
                if b.f(1):
                    self.TileColsLog2 += 1
                else:
                    break
            tileWidthSb = (sbCols + (1 << self.TileColsLog2) - 1) >> self.TileColsLog2
            for startSb in range(0, sbCols, tileWidthSb):
                self.MiColStarts.append(startSb << sbShift)
            self.TileCols = len(self.MiColStarts)
            self.MiColStarts.append(self.MiCols)
            minLog2TileRows = max(minLog2Tiles - self.TileColsLog2, 0)
            self.TileRowsLog2 = minLog2TileRows
            while self.TileRowsLog2 < maxLog2TileRows:
                if b.f(1):
                    self.TileRowsLog2 += 1
                else:
                    break
            tileHeightSb = (sbRows + (1 << self.TileRowsLog2) - 1) >> self.TileRowsLog2
            for startSb in range(0, sbRows, tileHeightSb):
                self.MiRowStarts.append(startSb << sbShift)
            self.TileRows = len(self.MiRowStarts)
            self.MiRowStarts.append(self.MiRows)
        else:
            widestTileSb = 0
            startSb = 0
            while startSb < sbCols:
                self.MiColStarts.append(startSb << sbShift)
                maxWidth = min(sbCols - startSb, maxTileWidthSb)
                sizeSb = b.ns(maxWidth) + 1
                widestTileSb = max(sizeSb, widestTileSb)
                startSb += sizeSb
            self.TileCols = len(self.MiColStarts)
            self.MiColStarts.append(self.MiCols)
            self.TileColsLog2 = tile_log2(1, self.TileCols)
            if minLog2Tiles > 0:
                maxTileAreaSb = (sbRows * sbCols) >> (minLog2Tiles + 1)
            else:
                maxTileAreaSb = sbRows * sbCols
            maxTileHeightSb = max(maxTileAreaSb // widestTileSb, 1)
            startSb = 0
            while startSb < sbRows:
                self.MiRowStarts.append(startSb << sbShift)
                maxHeight = min(sbRows - startSb, maxTileHeightSb)
                startSb += b.ns(maxHeight) + 1
            self.TileRows = len(self.MiRowStarts)
            self.MiRowStarts.append(self.MiRows)
            self.TileRowsLog2 = tile_log2(1, self.TileRows)
        self.st("tiles", self.TileCols * self.TileRows)
        if self.TileColsLog2 > 0 or self.TileRowsLog2 > 0:
            self.context_update_tile_id = b.f(self.TileRowsLog2 + self.TileColsLog2)
            self.TileSizeBytes = b.f(2) + 1
        else:
            self.context_update_tile_id = 0

