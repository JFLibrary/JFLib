SUPERRES_SCALE_MASK = (1 << SUPERRES_SCALE_BITS) - 1


def cdiv(a, b):
    """C integer division (truncation toward zero)"""
    q = abs(a) // abs(b)
    return q if (a >= 0) == (b > 0) else -q


def constrain(diff, threshold, damping):
    if not threshold:
        return 0
    dampingAdj = max(0, damping - FloorLog2(threshold))
    sign = -1 if diff < 0 else 1
    return sign * Clip3(0, abs(diff), threshold - (abs(diff) >> dampingAdj))


def wiener_coeff(coeff):
    f = [0] * 7
    f[3] = 128
    for i in range(3):
        c = coeff[i]
        f[i] = c
        f[6 - i] = c
        f[3] -= 2 * c
    return f


def cos128(angle):
    a2 = angle & 255
    if a2 <= 64:
        return Cos128_Lookup[a2]
    if a2 <= 128:
        return -Cos128_Lookup[128 - a2]
    if a2 <= 192:
        return -Cos128_Lookup[a2 - 128]
    return Cos128_Lookup[256 - a2]


def sin128(angle):
    return cos128(angle - 64)


def brev(numBits, x):
    t = 0
    for i in range(numBits):
        t |= ((x >> i) & 1) << (numBits - 1 - i)
    return t


def _B(T_, a, b, angle, flip):
    c = cos128(angle)
    s = sin128(angle)
    x = T_[a] * c - T_[b] * s
    y = T_[a] * s + T_[b] * c
    T_[a] = (x + 2048) >> 12
    T_[b] = (y + 2048) >> 12
    if flip:
        T_[a], T_[b] = T_[b], T_[a]


def _H(T_, a, b, flip, r):
    if flip:
        a, b = b, a
    x = T_[a]
    y = T_[b]
    lo = -(1 << (r - 1))
    hi = (1 << (r - 1)) - 1
    T_[a] = Clip3(lo, hi, x + y)
    T_[b] = Clip3(lo, hi, x - y)


