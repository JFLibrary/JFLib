    def residual(self):
        sbMask = 31 if self.use_128x128_superblock else 15
        widthChunks = max(1, Block_Width[self.MiSize] >> 6)
        heightChunks = max(1, Block_Height[self.MiSize] >> 6)
        miSizeChunk = BLOCK_64X64 if (widthChunks > 1 or heightChunks > 1) else self.MiSize
        for chunkY in range(heightChunks):
            for chunkX in range(widthChunks):
                miRowChunk = self.MiRow + (chunkY << 4)
                miColChunk = self.MiCol + (chunkX << 4)
                for plane in range(1 + self.HasChroma * 2):
                    txSz = TX_4X4 if self.Lossless else self.get_tx_size(plane, self.TxSize)
                    stepX = Tx_Width[txSz] >> 2
                    stepY = Tx_Height[txSz] >> 2
                    planeSz = self.get_plane_residual_size(miSizeChunk, plane)
                    num4x4W = Num_4x4_Blocks_Wide[planeSz]
                    num4x4H = Num_4x4_Blocks_High[planeSz]
                    subX = self.subsampling_x if plane else 0
                    subY = self.subsampling_y if plane else 0
                    baseXBlock = (self.MiCol >> subX) * MI_SIZE
                    baseYBlock = (self.MiRow >> subY) * MI_SIZE
                    for y in range(0, num4x4H, stepY):
                        for x in range(0, num4x4W, stepX):
                            self.transform_block(plane, baseXBlock, baseYBlock, txSz,
                                                 x + ((chunkX << 4) >> subX), y + ((chunkY << 4) >> subY))

    def get_tx_size(self, plane, txSz):
        if plane == 0:
            return txSz
        uvTx = Max_Tx_Size_Rect[self.get_plane_residual_size(self.MiSize, plane)]
        if Tx_Width[uvTx] == 64 or Tx_Height[uvTx] == 64:
            if Tx_Width[uvTx] == 16:
                return TX_16X32
            if Tx_Height[uvTx] == 16:
                return TX_32X16
            return TX_32X32
        return uvTx

    def transform_block(self, plane, baseX, baseY, txSz, x, y):
        startX = baseX + 4 * x
        startY = baseY + 4 * y
        subX = self.subsampling_x if plane else 0
        subY = self.subsampling_y if plane else 0
        row = (startY << subY) >> MI_SIZE_LOG2
        col = (startX << subX) >> MI_SIZE_LOG2
        sbMask = 31 if self.use_128x128_superblock else 15
        subBlockMiRow = row & sbMask
        subBlockMiCol = col & sbMask
        stepX = Tx_Width[txSz] >> MI_SIZE_LOG2
        stepY = Tx_Height[txSz] >> MI_SIZE_LOG2
        maxX = (self.MiCols * MI_SIZE) >> subX
        maxY = (self.MiRows * MI_SIZE) >> subY
        if startX >= maxX or startY >= maxY:
            return
        if (plane == 0 and self.PaletteSizeY) or (plane != 0 and self.PaletteSizeUV):
            self.predict_palette(plane, startX, startY, x, y, txSz)
        else:
            isCfl = plane > 0 and self.UVMode == UV_CFL_PRED
            if plane == 0:
                mode = self.YMode
            else:
                mode = DC_PRED if isCfl else self.UVMode
            log2W = Tx_Width_Log2[txSz]
            log2H = Tx_Height_Log2[txSz]
            self.predict_intra(plane, startX, startY,
                               (self.AvailL if plane == 0 else self.AvailLChroma) or x > 0,
                               (self.AvailU if plane == 0 else self.AvailUChroma) or y > 0,
                               self.bdec(plane, (subBlockMiRow >> subY) - 1, (subBlockMiCol >> subX) + stepX),
                               self.bdec(plane, (subBlockMiRow >> subY) + stepY, (subBlockMiCol >> subX) - 1),
                               mode, log2W, log2H)
            if isCfl:
                self.predict_chroma_from_luma(plane, startX, startY, txSz)
        if plane == 0:
            self.MaxLumaW = startX + stepX * 4
            self.MaxLumaH = startY + stepY * 4
        if not self.skip:
            eob = self.coeffs(plane, startX, startY, txSz)
            if eob > 0:
                self.reconstruct(plane, startX, startY, txSz)
        lts = self.LoopfilterTxSizes[plane]
        bd = self.BlockDecoded[plane]
        for i in range(stepY):
            for j in range(stepX):
                lts[(row >> subY) + i][(col >> subX) + j] = txSz
                bd[(subBlockMiRow >> subY) + i + 1][(subBlockMiCol >> subX) + j + 1] = 1

    # ------------------------------------------------------------------ coefficients
    def get_tx_set(self, txSz):
        txSzSqr = Tx_Size_Sqr[txSz]
        txSzSqrUp = Tx_Size_Sqr_Up[txSz]
        if txSzSqrUp > TX_32X32:
            return TX_SET_DCTONLY
        if txSzSqrUp == TX_32X32:
            return TX_SET_DCTONLY
        if self.reduced_tx_set:
            return TX_SET_INTRA_2
        if txSzSqr == TX_16X16:
            return TX_SET_INTRA_2
        return TX_SET_INTRA_1

    def compute_tx_type(self, plane, txSz, blockX, blockY):
        txSzSqrUp = Tx_Size_Sqr_Up[txSz]
        if self.Lossless or txSzSqrUp > TX_32X32:
            return DCT_DCT
        txSet = self.get_tx_set(txSz)
        if plane == 0:
            return self.TxTypes[blockY][blockX]
        txType = Mode_To_Txfm[self.UVMode]
        if not Tx_Type_In_Set_Intra[txSet][txType]:
            return DCT_DCT
        return txType

    def transform_type(self, x4, y4, txSz):
        s = self.get_tx_set(txSz)
        q = self.get_qindex(1, self.segment_id) if self.segmentation_enabled else self.base_q_idx
        if s > 0 and q > 0:
            intraDir = Filter_Intra_Mode_To_Intra_Dir[self.filter_intra_mode] if self.use_filter_intra else self.YMode
            if s == TX_SET_INTRA_1:
                t = self.read_symbol(self.cdf["IntraTxTypeSet1"][Tx_Size_Sqr[txSz]][intraDir])
                TxType = Tx_Type_Intra_Inv_Set1[t]
            else:
                t = self.read_symbol(self.cdf["IntraTxTypeSet2"][Tx_Size_Sqr[txSz]][intraDir])
                TxType = Tx_Type_Intra_Inv_Set2[t]
        else:
            TxType = DCT_DCT
        for i in range(Tx_Width[txSz] >> 2):
            for j in range(Tx_Height[txSz] >> 2):
                self.TxTypes[y4 + j][x4 + i] = TxType

    def get_scan(self, txSz):
        if txSz == TX_16X64:
            return Default_Scan_16x32
        if txSz == TX_64X16:
            return Default_Scan_32x16
        if Tx_Size_Sqr_Up[txSz] == TX_64X64:
            return Default_Scan_32x32
        t = self.PlaneTxType
        name = "%dx%d" % (Tx_Width[txSz], Tx_Height[txSz])
        if t == IDTX:
            return globals()["Default_Scan_" + name]
        if t in (V_DCT, V_ADST, V_FLIPADST):
            return globals()["Mrow_Scan_" + name]
        if t in (H_DCT, H_ADST, H_FLIPADST):
            return globals()["Mcol_Scan_" + name]
        return globals()["Default_Scan_" + name]

    def coeffs(self, plane, startX, startY, txSz):
        x4 = startX >> 2
        y4 = startY >> 2
        w4 = Tx_Width[txSz] >> 2
        h4 = Tx_Height[txSz] >> 2
        txSzCtx = (Tx_Size_Sqr[txSz] + Tx_Size_Sqr_Up[txSz] + 1) >> 1
        ptype = int(plane > 0)
        segEob = 512 if txSz in (TX_16X64, TX_64X16) else min(1024, Tx_Width[txSz] * Tx_Height[txSz])
        Quant = [0] * segEob
        self.Quant = Quant
        eob = 0
        culLevel = 0
        dcCategory = 0
        all_zero = self.read_symbol(self.cdf["TxbSkip"][txSzCtx][self.all_zero_ctx(plane, txSz, x4, y4, w4, h4)])
        if all_zero:
            if plane == 0:
                for i in range(w4):
                    for j in range(h4):
                        self.TxTypes[y4 + j][x4 + i] = DCT_DCT
        else:
            if plane == 0:
                self.transform_type(x4, y4, txSz)
            self.PlaneTxType = self.compute_tx_type(plane, txSz, x4, y4)
            self.st("txtype%d" % self.PlaneTxType)
            self.st("txsize%d" % txSz)
            txClass = get_tx_class(self.PlaneTxType)
            scan = self.get_scan(txSz)
            eobMultisize = min(Tx_Width_Log2[txSz], 5) + min(Tx_Height_Log2[txSz], 5) - 4
            ctx = 0 if txClass == TX_CLASS_2D else 1
            if eobMultisize <= 4:
                name = "EobPt%d" % (16 << eobMultisize)
                eobPt = self.read_symbol(self.cdf[name][ptype][ctx]) + 1
            else:
                name = "EobPt%d" % (16 << eobMultisize)
                eobPt = self.read_symbol(self.cdf[name][ptype]) + 1
            eob = eobPt if eobPt < 2 else ((1 << (eobPt - 2)) + 1)
            eobShift = max(-1, eobPt - 3)
            if eobShift >= 0:
                if self.read_symbol(self.cdf["EobExtra"][txSzCtx][ptype][eobPt - 3]):
                    eob += 1 << eobShift
                for i in range(1, max(0, eobPt - 2)):
                    eobShift = max(0, eobPt - 2) - 1 - i
                    if self.L(1):
                        eob += 1 << eobShift
            # context parameters
            adjTxSz = Adjusted_Tx_Size[txSz]
            bwl = Tx_Width_Log2[adjTxSz]
            width = 1 << bwl
            height = Tx_Height[adjTxSz]
            cbase = self.cdf["CoeffBase"][txSzCtx][ptype]
            cbr = self.cdf["CoeffBr"][min(txSzCtx, TX_32X32)][ptype]
            for c in range(eob - 1, -1, -1):
                pos = scan[c]
                if c == eob - 1:
                    if c == 0:
                        ctx = SIG_COEF_CONTEXTS - 4
                    elif c <= (height << bwl) // 8:
                        ctx = SIG_COEF_CONTEXTS - 3
                    elif c <= (height << bwl) // 4:
                        ctx = SIG_COEF_CONTEXTS - 2
                    else:
                        ctx = SIG_COEF_CONTEXTS - 1
                    ctx = ctx - SIG_COEF_CONTEXTS + SIG_COEF_CONTEXTS_EOB
                    level = self.read_symbol(self.cdf["CoeffBaseEob"][txSzCtx][ptype][ctx]) + 1
                else:
                    ctx = self.coeff_base_ctx(txSz, txClass, bwl, width, height, pos, Quant)
                    level = self.read_symbol(cbase[ctx])
                if level > NUM_BASE_LEVELS:
                    ctx = self.coeff_br_ctx(txSz, txClass, pos, Quant)
                    for idx in range(COEFF_BASE_RANGE // (BR_CDF_SIZE - 1)):
                        coeff_br = self.read_symbol(cbr[ctx])
                        level += coeff_br
                        if coeff_br < BR_CDF_SIZE - 1:
                            break
                Quant[pos] = level
            for c in range(eob):
                pos = scan[c]
                if Quant[pos] != 0:
                    if c == 0:
                        sign = self.read_symbol(self.cdf["DcSign"][ptype][self.dc_sign_ctx(plane, x4, y4, w4, h4)])
                    else:
                        sign = self.L(1)
                else:
                    sign = 0
                if Quant[pos] > NUM_BASE_LEVELS + COEFF_BASE_RANGE:
                    length = 0
                    while True:
                        length += 1
                        if self.L(1):
                            break
                        if length > 32:
                            raise AV1Error("golomb")
                    x = 1
                    for i in range(length - 2, -1, -1):
                        x = (x << 1) | self.L(1)
                    Quant[pos] = x + COEFF_BASE_RANGE + NUM_BASE_LEVELS
                if pos == 0 and Quant[pos] > 0:
                    dcCategory = 1 if sign else 2
                Quant[pos] &= 0xFFFFF
                culLevel += Quant[pos]
                if sign:
                    Quant[pos] = -Quant[pos]
            culLevel = min(63, culLevel)
        for i in range(w4):
            self.AboveLevelContext[plane][x4 + i] = culLevel
            self.AboveDcContext[plane][x4 + i] = dcCategory
        for i in range(h4):
            self.LeftLevelContext[plane][y4 + i] = culLevel
            self.LeftDcContext[plane][y4 + i] = dcCategory
        self.eob = eob
        return eob

    def all_zero_ctx(self, plane, txSz, x4, y4, w4, h4):
        maxX4 = self.MiCols
        maxY4 = self.MiRows
        if plane > 0:
            maxX4 >>= self.subsampling_x
            maxY4 >>= self.subsampling_y
        w = Tx_Width[txSz]
        h = Tx_Height[txSz]
        bsize = self.get_plane_residual_size(self.MiSize, plane)
        bw = Block_Width[bsize]
        bh = Block_Height[bsize]
        alc = self.AboveLevelContext[plane]
        llc = self.LeftLevelContext[plane]
        if plane == 0:
            top = 0
            left = 0
            for k in range(w4):
                if x4 + k < maxX4:
                    top = max(top, alc[x4 + k])
            for k in range(h4):
                if y4 + k < maxY4:
                    left = max(left, llc[y4 + k])
            top = min(top, 255)
            left = min(left, 255)
            if bw == w and bh == h:
                ctx = 0
            elif top == 0 and left == 0:
                ctx = 1
            elif top == 0 or left == 0:
                ctx = 2 + int(max(top, left) > 3)
            elif max(top, left) <= 3:
                ctx = 4
            elif min(top, left) <= 3:
                ctx = 5
            else:
                ctx = 6
        else:
            adc = self.AboveDcContext[plane]
            ldc = self.LeftDcContext[plane]
            above = 0
            left = 0
            for i in range(w4):
                if x4 + i < maxX4:
                    above |= alc[x4 + i]
                    above |= adc[x4 + i]
            for i in range(h4):
                if y4 + i < maxY4:
                    left |= llc[y4 + i]
                    left |= ldc[y4 + i]
            ctx = int(above != 0) + int(left != 0)
            ctx += 7
            if bw * bh > w * h:
                ctx += 3
        return ctx

    @staticmethod
    def coeff_base_ctx(txSz, txClass, bwl, width, height, pos, Quant):
        row = pos >> bwl
        col = pos - (row << bwl)
        mag = 0
        for idx in range(SIG_REF_DIFF_OFFSET_NUM):
            refRow = row + Sig_Ref_Diff_Offset[txClass][idx][0]
            refCol = col + Sig_Ref_Diff_Offset[txClass][idx][1]
            if 0 <= refRow < height and 0 <= refCol < width:
                mag += min(abs(Quant[(refRow << bwl) + refCol]), 3)
        ctx = min((mag + 1) >> 1, 4)
        if txClass == TX_CLASS_2D:
            if row == 0 and col == 0:
                return 0
            return ctx + Coeff_Base_Ctx_Offset[txSz][min(row, 4)][min(col, 4)]
        idx = row if txClass == TX_CLASS_VERT else col
        return ctx + Coeff_Base_Pos_Ctx_Offset[min(idx, 2)]

    @staticmethod
    def coeff_br_ctx(txSz, txClass, pos, Quant):
        adjTxSz = Adjusted_Tx_Size[txSz]
        bwl = Tx_Width_Log2[adjTxSz]
        txw = Tx_Width[adjTxSz]
        txh = Tx_Height[adjTxSz]
        row = pos >> bwl
        col = pos - (row << bwl)
        mag = 0
        for idx in range(3):
            refRow = row + Mag_Ref_Offset_With_Tx_Class[txClass][idx][0]
            refCol = col + Mag_Ref_Offset_With_Tx_Class[txClass][idx][1]
            if 0 <= refRow < txh and 0 <= refCol < (1 << bwl):
                mag += min(Quant[refRow * txw + refCol], COEFF_BASE_RANGE + NUM_BASE_LEVELS + 1)
        mag = min((mag + 1) >> 1, 6)
        if pos == 0:
            return mag
        if txClass == 0:
            if row < 2 and col < 2:
                return mag + 7
            return mag + 14
        if txClass == 1:
            return mag + 7 if col == 0 else mag + 14
        return mag + 7 if row == 0 else mag + 14

    def dc_sign_ctx(self, plane, x4, y4, w4, h4):
        maxX4 = self.MiCols
        maxY4 = self.MiRows
        if plane > 0:
            maxX4 >>= self.subsampling_x
            maxY4 >>= self.subsampling_y
        dcSign = 0
        for k in range(w4):
            if x4 + k < maxX4:
                s = self.AboveDcContext[plane][x4 + k]
                if s == 1:
                    dcSign -= 1
                elif s == 2:
                    dcSign += 1
        for k in range(h4):
            if y4 + k < maxY4:
                s = self.LeftDcContext[plane][y4 + k]
                if s == 1:
                    dcSign -= 1
                elif s == 2:
                    dcSign += 1
        return 1 if dcSign < 0 else 2 if dcSign > 0 else 0

    # ================================================================== prediction processes
    def predict_intra(self, plane, x, y, haveLeft, haveAbove, haveAboveRight, haveBelowLeft, mode, log2W, log2H):
        F = self.CurrFrame[plane]
        w = 1 << log2W
        h = 1 << log2H
        if plane:
            maxX = ((self.MiCols * MI_SIZE) >> self.subsampling_x) - 1
            maxY = ((self.MiRows * MI_SIZE) >> self.subsampling_y) - 1
        else:
            maxX = self.MiCols * MI_SIZE - 1
            maxY = self.MiRows * MI_SIZE - 1
        bd = self.BitDepth
        n = w + h
        O = 16                          # AboveRow[i] = A[O + i], LeftCol[i] = Lc[O + i]
        A = [0] * (2 * n + 2 * O)
        Lc = [0] * (2 * n + 2 * O)
        if not haveAbove and haveLeft:
            v = F[y][x - 1]
            for i in range(n):
                A[O + i] = v
        elif not haveAbove and not haveLeft:
            v = (1 << (bd - 1)) - 1
            for i in range(n):
                A[O + i] = v
        else:
            aboveLimit = min(maxX, x + (2 * w if haveAboveRight else w) - 1)
            row = F[y - 1]
            for i in range(n):
                A[O + i] = row[min(aboveLimit, x + i)]
        if not haveLeft and haveAbove:
            v = F[y - 1][x]
            for i in range(n):
                Lc[O + i] = v
        elif not haveLeft and not haveAbove:
            v = (1 << (bd - 1)) + 1
            for i in range(n):
                Lc[O + i] = v
        else:
            leftLimit = min(maxY, y + (2 * h if haveBelowLeft else h) - 1)
            for i in range(n):
                Lc[O + i] = F[min(leftLimit, y + i)][x - 1]
        if haveAbove and haveLeft:
            corner = F[y - 1][x - 1]
        elif haveAbove:
            corner = F[y - 1][x]
        elif haveLeft:
            corner = F[y][x - 1]
        else:
            corner = 1 << (bd - 1)
        A[O - 1] = corner
        Lc[O - 1] = corner
        if plane == 0 and self.use_filter_intra:
            pred = self.recursive_intra(A, Lc, O, w, h)
        elif V_PRED <= mode <= D67_PRED:
            pred = self.directional_intra(plane, x, y, haveLeft, haveAbove, mode, w, h, maxX, maxY, A, Lc, O)
        elif mode in (SMOOTH_PRED, SMOOTH_V_PRED, SMOOTH_H_PRED):
            pred = self.smooth_intra(mode, log2W, log2H, w, h, A, Lc, O)
        elif mode == DC_PRED:
            pred = self.dc_intra(haveLeft, haveAbove, log2W, log2H, w, h, A, Lc, O)
        else:
            pred = self.paeth_intra(w, h, A, Lc, O)
        for i in range(h):
            F[y + i][x:x + w] = pred[i]

    @staticmethod
    def paeth_intra(w, h, A, Lc, O):
        tl = A[O - 1]
        pred = []
        for i in range(h):
            L_ = Lc[O + i]
            row = []
            for j in range(w):
                base = A[O + j] + L_ - tl
                pLeft = abs(base - L_)
                pTop = abs(base - A[O + j])
                pTopLeft = abs(base - tl)
                if pLeft <= pTop and pLeft <= pTopLeft:
                    row.append(L_)
                elif pTop <= pTopLeft:
                    row.append(A[O + j])
                else:
                    row.append(tl)
            pred.append(row)
        return pred

    def recursive_intra(self, A, Lc, O, w, h):
        w4 = w >> 2
        h2 = h >> 1
        pred = grid(h, w)
        taps = Intra_Filter_Taps[self.filter_intra_mode]
        for i2 in range(h2):
            for j4 in range(w4):
                p = [0] * 7
                for i in range(7):
                    if i < 5:
                        if i2 == 0:
                            p[i] = A[O + (j4 << 2) + i - 1]
                        elif j4 == 0 and i == 0:
                            p[i] = Lc[O + (i2 << 1) - 1]
                        else:
                            p[i] = pred[(i2 << 1) - 1][(j4 << 2) + i - 1]
                    else:
                        if j4 == 0:
                            p[i] = Lc[O + (i2 << 1) + i - 5]
                        else:
                            p[i] = pred[(i2 << 1) + i - 5][(j4 << 2) - 1]
                for i1 in range(2):
                    for j1 in range(4):
                        t = taps[(i1 << 2) + j1]
                        pr = 0
                        for i in range(7):
                            pr += t[i] * p[i]
                        pred[(i2 << 1) + i1][(j4 << 2) + j1] = self.Clip1(Round2Signed(pr, INTRA_FILTER_SCALE_BITS))
        return pred

    def directional_intra(self, plane, x, y, haveLeft, haveAbove, mode, w, h, maxX, maxY, A, Lc, O):
        angleDelta = self.AngleDeltaY if plane == 0 else self.AngleDeltaUV
        pAngle = Mode_To_Angle[mode] + angleDelta * ANGLE_STEP
        upsampleAbove = upsampleLeft = 0
        filterType = 0      # (only read by the upsample selection when pAngle is 90 / 180: result 0 anyway)
        if self.enable_intra_edge_filter:
            if pAngle != 90 and pAngle != 180:
                if 90 < pAngle < 180 and (w + h) >= 24:
                    s = Lc[O] * 5 + A[O - 1] * 6 + A[O] * 5
                    A[O - 1] = Lc[O - 1] = Round2(s, 4)
                filterType = self.get_filter_type(plane)
                if haveAbove:
                    strength = self.edge_filter_strength(w, h, filterType, pAngle - 90)
                    numPx = min(w, maxX - x + 1) + (h if pAngle < 90 else 0) + 1
                    self.edge_filter(A, O, numPx, strength)
                if haveLeft:
                    strength = self.edge_filter_strength(w, h, filterType, pAngle - 180)
                    numPx = min(h, maxY - y + 1) + (w if pAngle > 180 else 0) + 1
                    self.edge_filter(Lc, O, numPx, strength)
            upsampleAbove = self.use_upsample(w, h, filterType, pAngle - 90)
            numPx = w + (h if pAngle < 90 else 0)
            if upsampleAbove:
                self.edge_upsample(A, O, numPx)
                self.st("upsample")
            upsampleLeft = self.use_upsample(w, h, filterType, pAngle - 180)
            numPx = h + (w if pAngle > 180 else 0)
            if upsampleLeft:
                self.edge_upsample(Lc, O, numPx)
        if pAngle < 90:
            dx = Dr_Intra_Derivative[pAngle]
        elif 90 < pAngle < 180:
            dx = Dr_Intra_Derivative[180 - pAngle]
        if 90 < pAngle < 180:
            dy = Dr_Intra_Derivative[pAngle - 90]
        elif pAngle > 180:
            dy = Dr_Intra_Derivative[270 - pAngle]
        pred = grid(h, w)
        if pAngle < 90:
            maxBaseX = (w + h - 1) << upsampleAbove
            for i in range(h):
                idx = (i + 1) * dx
                shift = ((idx << upsampleAbove) >> 1) & 0x1F
                for j in range(w):
                    base = (idx >> (6 - upsampleAbove)) + (j << upsampleAbove)
                    if base < maxBaseX:
                        pred[i][j] = Round2(A[O + base] * (32 - shift) + A[O + base + 1] * shift, 5)
                    else:
                        pred[i][j] = A[O + maxBaseX]
        elif 90 < pAngle < 180:
            for i in range(h):
                for j in range(w):
                    idx = (j << 6) - (i + 1) * dx
                    base = idx >> (6 - upsampleAbove)
                    if base >= -(1 << upsampleAbove):
                        shift = ((idx << upsampleAbove) >> 1) & 0x1F
                        pred[i][j] = Round2(A[O + base] * (32 - shift) + A[O + base + 1] * shift, 5)
                    else:
                        idx = (i << 6) - (j + 1) * dy
                        base = idx >> (6 - upsampleLeft)
                        shift = ((idx << upsampleLeft) >> 1) & 0x1F
                        pred[i][j] = Round2(Lc[O + base] * (32 - shift) + Lc[O + base + 1] * shift, 5)
        elif pAngle > 180:
            for j in range(w):
                idx = (j + 1) * dy
                shift = ((idx << upsampleLeft) >> 1) & 0x1F
                for i in range(h):
                    base = (idx >> (6 - upsampleLeft)) + (i << upsampleLeft)
                    pred[i][j] = Round2(Lc[O + base] * (32 - shift) + Lc[O + base + 1] * shift, 5)
        elif pAngle == 90:
            for i in range(h):
                pred[i] = A[O:O + w]
        else:
            for i in range(h):
                pred[i] = [Lc[O + i]] * w
        return pred

    def get_filter_type(self, plane):
        aboveSmooth = leftSmooth = 0
        ssx, ssy = self.subsampling_x, self.subsampling_y
        if self.AvailU if plane == 0 else self.AvailUChroma:
            r = self.MiRow - 1
            c = self.MiCol
            if plane > 0:
                if ssx and not (self.MiCol & 1):
                    c += 1
                if ssy and (self.MiRow & 1):
                    r -= 1
            aboveSmooth = self.is_smooth(r, c, plane)
        if self.AvailL if plane == 0 else self.AvailLChroma:
            r = self.MiRow
            c = self.MiCol - 1
            if plane > 0:
                if ssx and (self.MiCol & 1):
                    c -= 1
                if ssy and not (self.MiRow & 1):
                    r += 1
            leftSmooth = self.is_smooth(r, c, plane)
        return int(aboveSmooth or leftSmooth)

    def is_smooth(self, row, col, plane):
        mode = self.YModes[row][col] if plane == 0 else self.UVModes[row][col]
        return mode in (SMOOTH_PRED, SMOOTH_V_PRED, SMOOTH_H_PRED)

    @staticmethod
    def edge_filter_strength(w, h, filterType, delta):
        d = abs(delta)
        blkWh = w + h
        strength = 0
        if filterType == 0:
            if blkWh <= 8:
                if d >= 56:
                    strength = 1
            elif blkWh <= 12:
                if d >= 40:
                    strength = 1
            elif blkWh <= 16:
                if d >= 40:
                    strength = 1
            elif blkWh <= 24:
                if d >= 8:
                    strength = 1
                if d >= 16:
                    strength = 2
                if d >= 32:
                    strength = 3
            elif blkWh <= 32:
                strength = 1
                if d >= 4:
                    strength = 2
                if d >= 32:
                    strength = 3
            else:
                strength = 3
        else:
            if blkWh <= 8:
                if d >= 40:
                    strength = 1
                if d >= 64:
                    strength = 2
            elif blkWh <= 16:
                if d >= 20:
                    strength = 1
                if d >= 48:
                    strength = 2
            elif blkWh <= 24:
                if d >= 4:
                    strength = 3
            else:
                strength = 3
        return strength

    @staticmethod
    def use_upsample(w, h, filterType, delta):
        d = abs(delta)
        blkWh = w + h
        if d <= 0 or d >= 40:
            return 0
        if filterType == 0:
            return int(blkWh <= 16)
        return int(blkWh <= 8)

    def edge_upsample(self, buf, O, numPx):
        dup = [0] * (numPx + 3)
        dup[0] = buf[O - 1]
        for i in range(-1, numPx):
            dup[i + 2] = buf[O + i]
        dup[numPx + 2] = buf[O + numPx - 1]
        buf[O - 2] = dup[0]
        for i in range(numPx):
            s = -dup[i] + 9 * dup[i + 1] + 9 * dup[i + 2] - dup[i + 3]
            s = self.Clip1(Round2(s, 4))
            buf[O + 2 * i - 1] = s
            buf[O + 2 * i] = dup[i + 2]

    @staticmethod
    def edge_filter(buf, O, sz, strength):
        if strength == 0:
            return
        edge = [buf[O + i - 1] for i in range(sz)]
        k_ = Intra_Edge_Kernel[strength - 1]
        for i in range(1, sz):
            s = 0
            for j in range(INTRA_EDGE_TAPS):
                k = Clip3(0, sz - 1, i - 2 + j)
                s += k_[j] * edge[k]
            buf[O + i - 1] = (s + 8) >> 4

    @staticmethod
    def smooth_intra(mode, log2W, log2H, w, h, A, Lc, O):
        wts = {2: Sm_Weights_Tx_4x4, 3: Sm_Weights_Tx_8x8, 4: Sm_Weights_Tx_16x16, 5: Sm_Weights_Tx_32x32,
               6: Sm_Weights_Tx_64x64}
        pred = grid(h, w)
        if mode == SMOOTH_PRED:
            wx = wts[log2W]
            wy = wts[log2H]
            for i in range(h):
                for j in range(w):
                    s = (wy[i] * A[O + j] + (256 - wy[i]) * Lc[O + h - 1] + wx[j] * Lc[O + i]
                         + (256 - wx[j]) * A[O + w - 1])
                    pred[i][j] = Round2(s, 9)
        elif mode == SMOOTH_V_PRED:
            wy = wts[log2H]
            for i in range(h):
                for j in range(w):
                    pred[i][j] = Round2(wy[i] * A[O + j] + (256 - wy[i]) * Lc[O + h - 1], 8)
        else:
            wx = wts[log2W]
            for i in range(h):
                for j in range(w):
                    pred[i][j] = Round2(wx[j] * Lc[O + i] + (256 - wx[j]) * A[O + w - 1], 8)
        return pred

    def dc_intra(self, haveLeft, haveAbove, log2W, log2H, w, h, A, Lc, O):
        if haveLeft and haveAbove:
            s = sum(Lc[O:O + h]) + sum(A[O:O + w])
            s += (w + h) >> 1
            v = s // (w + h)
        elif haveLeft:
            v = self.Clip1((sum(Lc[O:O + h]) + (h >> 1)) >> log2H)
        elif haveAbove:
            v = self.Clip1((sum(A[O:O + w]) + (w >> 1)) >> log2W)
        else:
            v = 1 << (self.BitDepth - 1)
        return [[v] * w for _ in range(h)]

    def predict_palette(self, plane, startX, startY, x, y, txSz):
        w = Tx_Width[txSz]
        h = Tx_Height[txSz]
        palette = (self.palette_colors_y, self.palette_colors_u, self.palette_colors_v)[plane]
        m = self.ColorMapY if plane == 0 else self.ColorMapUV
        F = self.CurrFrame[plane]
        for i in range(h):
            mr = m[y * 4 + i]
            row = F[startY + i]
            for j in range(w):
                row[startX + j] = palette[mr[x * 4 + j]]

    def predict_chroma_from_luma(self, plane, startX, startY, txSz):
        w = Tx_Width[txSz]
        h = Tx_Height[txSz]
        subX = self.subsampling_x
        subY = self.subsampling_y
        alpha = self.CflAlphaU if plane == 1 else self.CflAlphaV
        Y = self.CurrFrame[0]
        Lm = grid(h, w)
        lumaAvg = 0
        for i in range(h):
            lumaY = (startY + i) << subY
            lumaY = min(lumaY, self.MaxLumaH - (1 << subY))
            for j in range(w):
                lumaX = (startX + j) << subX
                lumaX = min(lumaX, self.MaxLumaW - (1 << subX))
                t = 0
                for dy in range(subY + 1):
                    for dx in range(subX + 1):
                        t += Y[lumaY + dy][lumaX + dx]
                v = t << (3 - subX - subY)
                Lm[i][j] = v
                lumaAvg += v
        lumaAvg = Round2(lumaAvg, Tx_Width_Log2[txSz] + Tx_Height_Log2[txSz])
        F = self.CurrFrame[plane]
        for i in range(h):
            row = F[startY + i]
            for j in range(w):
                dc = row[startX + j]
                scaledLuma = Round2Signed(alpha * (Lm[i][j] - lumaAvg), 6)
                row[startX + j] = self.Clip1(dc + scaledLuma)

    # ================================================================== reconstruction
    def dc_q(self, b):
        return Dc_Qlookup[(self.BitDepth - 8) >> 1][Clip3(0, 255, b)]

    def ac_q(self, b):
        return Ac_Qlookup[(self.BitDepth - 8) >> 1][Clip3(0, 255, b)]

    def get_dc_quant(self, plane):
        q = self.get_qindex(0, self.segment_id)
        return self.dc_q(q + (self.DeltaQYDc, self.DeltaQUDc, self.DeltaQVDc)[plane])

    def get_ac_quant(self, plane):
        q = self.get_qindex(0, self.segment_id)
        return self.ac_q(q + (0, self.DeltaQUAc, self.DeltaQVAc)[plane])

    def reconstruct(self, plane, x, y, txSz):
        if txSz in (TX_32X32, TX_16X32, TX_32X16, TX_16X64, TX_64X16):
            dqDenom = 2
        elif txSz in (TX_64X64, TX_32X64, TX_64X32):
            dqDenom = 4
        else:
            dqDenom = 1
        log2W = Tx_Width_Log2[txSz]
        log2H = Tx_Height_Log2[txSz]
        w = 1 << log2W
        h = 1 << log2H
        tw = min(32, w)
        th = min(32, h)
        t = self.PlaneTxType
        flipUD = t in (FLIPADST_DCT, FLIPADST_ADST, V_FLIPADST, FLIPADST_FLIPADST)
        flipLR = t in (DCT_FLIPADST, ADST_FLIPADST, H_FLIPADST, FLIPADST_FLIPADST)
        dcq = self.get_dc_quant(plane)
        acq = self.get_ac_quant(plane)
        useqm = self.using_qmatrix and t < IDTX and self.SegQMLevel[plane][self.segment_id] < 15
        if useqm:
            qm = Quantizer_Matrix[self.SegQMLevel[plane][self.segment_id]][int(plane > 0)]
            qmo = Qm_Offset[txSz]
        lim = 1 << (7 + self.BitDepth)
        Q = self.Quant
        Dq = grid(h, w)
        for i in range(th):
            for j in range(tw):
                qv = Q[i * tw + j]
                if qv == 0:
                    continue
                q = dcq if (i == 0 and j == 0) else acq
                if useqm:
                    q = Round2(q * qm[qmo + i * tw + j], 5)
                dq = qv * q
                dq2 = (abs(dq) & 0xFFFFFF) // dqDenom
                if dq < 0:
                    dq2 = -dq2
                Dq[i][j] = Clip3(-lim, lim - 1, dq2)
        R = self.inverse_transform_2d(Dq, txSz, log2W, log2H, w, h)
        F = self.CurrFrame[plane]
        mx = (1 << self.BitDepth) - 1
        for i in range(h):
            yy = h - i - 1 if flipUD else i
            row = F[y + yy]
            Ri = R[i]
            for j in range(w):
                xx = w - j - 1 if flipLR else j
                v = row[x + xx] + Ri[j]
                row[x + xx] = 0 if v < 0 else mx if v > mx else v

    # ------------------------------------------------------------------ inverse transforms
    def inverse_transform_2d(self, Dq, txSz, log2W, log2H, w, h):
        ll = self.Lossless
        rowShift = 0 if ll else Transform_Row_Shift[txSz]
        colShift = 0 if ll else 4
        rowClamp = self.BitDepth + 8
        colClamp = max(self.BitDepth + 6, 16)
        t = self.PlaneTxType
        rowDct = t in (DCT_DCT, ADST_DCT, FLIPADST_DCT, H_DCT)
        rowAdst = t in (DCT_ADST, ADST_ADST, DCT_FLIPADST, FLIPADST_FLIPADST, ADST_FLIPADST, FLIPADST_ADST,
                        H_ADST, H_FLIPADST)
        colDct = t in (DCT_DCT, DCT_ADST, DCT_FLIPADST, V_DCT)
        colAdst = t in (ADST_DCT, ADST_ADST, FLIPADST_DCT, FLIPADST_FLIPADST, ADST_FLIPADST, FLIPADST_ADST,
                        V_ADST, V_FLIPADST)
        R = grid(h, w)
        cmin = -(1 << (colClamp - 1))
        cmax = (1 << (colClamp - 1)) - 1
        rect = abs(log2W - log2H) == 1
        for i in range(h):
            if i < 32:
                T_ = [Dq[i][j] if j < 32 else 0 for j in range(w)]
            else:
                T_ = [0] * w
            if not any(T_) and not ll:
                continue        # (all transforms map zero to zero)
            if rect:
                T_ = [Round2(v * 2896, 12) for v in T_]
            if ll:
                iwht(T_, 2)
            elif rowDct:
                idct(T_, log2W, rowClamp)
            elif rowAdst:
                iadst(T_, log2W, rowClamp)
            else:
                iidentity(T_, log2W)
            R[i] = [Clip3(cmin, cmax, Round2(v, rowShift)) for v in T_]
        for j in range(w):
            T_ = [R[i][j] for i in range(h)]
            if ll:
                iwht(T_, 0)
            elif colDct:
                idct(T_, log2H, colClamp)
            elif colAdst:
                iadst(T_, log2H, colClamp)
            else:
                iidentity(T_, log2H)
            for i in range(h):
                R[i][j] = Round2(T_[i], colShift)
        return R

    # ================================================================== frame wrapup
    def decode_frame_wrapup(self):
        st = self.stage
        if st == "recon":
            return self.output_process(self.CurrFrame, self.FrameWidth)
        if self.loop_filter_level[0] or self.loop_filter_level[1]:
            self.loop_filter_process()
        if st == "lf":
            return self.output_process(self.CurrFrame, self.FrameWidth)
        self.cdef_process()
        if st == "cdef":
            return self.output_process(self.CdefFrame, self.FrameWidth)
        self.UpscaledCdefFrame = self.upscaling_process(self.CdefFrame)
        self.UpscaledCurrFrame = self.upscaling_process(self.CurrFrame)
        if st == "sr":
            return self.output_process(self.UpscaledCdefFrame)
        self.loop_restoration_process()
        if self.show_frame:
            self.output_process()

    # ------------------------------------------------------------------ loop filter
    def loop_filter_process(self):
        for plane in range(self.NumPlanes):
            if plane == 0 or self.loop_filter_level[1 + plane]:
                for pss in range(2):
                    rowStep = 1 if plane == 0 else (1 << self.subsampling_y)
                    colStep = 1 if plane == 0 else (1 << self.subsampling_x)
                    for row in range(0, self.MiRows, rowStep):
                        for col in range(0, self.MiCols, colStep):
                            self.loop_filter_edge(plane, pss, row, col)

    def loop_filter_edge(self, plane, pss, row, col):
        subX = self.subsampling_x if plane else 0
        subY = self.subsampling_y if plane else 0
        dx, dy = (1, 0) if pss == 0 else (0, 1)
        x = col * MI_SIZE
        y = row * MI_SIZE
        row |= subY
        col |= subX
        if x >= self.FrameWidth or y >= self.FrameHeight:
            return
        if pss == 0 and x == 0:
            return
        if pss == 1 and y == 0:
            return
        xP = x >> subX
        yP = y >> subY
        prevRow = row - (dy << subY)
        prevCol = col - (dx << subX)
        MiSize = self.MiSizes[row][col]
        txSz = self.LoopfilterTxSizes[plane][row >> subY][col >> subX]
        planeSize = self.get_plane_residual_size(MiSize, plane)
        skip = self.Skips[row][col]
        isIntra = 1
        prevTxSz = self.LoopfilterTxSizes[plane][prevRow >> subY][prevCol >> subX]
        if pss == 0 and xP % Block_Width[planeSize] == 0:
            isBlockEdge = 1
        elif pss == 1 and yP % Block_Height[planeSize] == 0:
            isBlockEdge = 1
        else:
            isBlockEdge = 0
        if pss == 0 and xP % Tx_Width[txSz] == 0:
            isTxEdge = 1
        elif pss == 1 and yP % Tx_Height[txSz] == 0:
            isTxEdge = 1
        else:
            isTxEdge = 0
        if not isTxEdge:
            applyFilter = 0
        elif isBlockEdge or not skip or isIntra:
            applyFilter = 1
        else:
            applyFilter = 0
        if pss == 0:
            baseSize = min(Tx_Width[prevTxSz], Tx_Width[txSz])
        else:
            baseSize = min(Tx_Height[prevTxSz], Tx_Height[txSz])
        filterSize = min(16, baseSize) if plane == 0 else min(8, baseSize)
        lvl, limit, blimit, thresh = self.filter_strength(row, col, plane, pss)
        if lvl == 0:
            lvl, limit, blimit, thresh = self.filter_strength(prevRow, prevCol, plane, pss)
        for i in range(MI_SIZE):
            if applyFilter and lvl > 0:
                self.sample_filter(xP + dy * i, yP + dx * i, plane, limit, blimit, thresh, dx, dy, filterSize)

    def filter_strength(self, row, col, plane, pss):
        segment = self.SegmentIds[row][col]
        if self.delta_lf_multi == 0:
            deltaLF = self.DeltaLFs[row][col][0]
        else:
            deltaLF = self.DeltaLFs[row][col][pss if plane == 0 else plane + 1]
        i = pss if plane == 0 else plane + 1
        baseFilterLevel = Clip3(0, MAX_LOOP_FILTER, deltaLF + self.loop_filter_level[i])
        lvlSeg = baseFilterLevel
        feature = SEG_LVL_ALT_LF_Y_V + i
        if self.seg_feature_active_idx(segment, feature):
            lvlSeg = Clip3(0, MAX_LOOP_FILTER, self.FeatureData[segment][feature] + lvlSeg)
        if self.loop_filter_delta_enabled:
            nShift = lvlSeg >> 5
            lvlSeg = lvlSeg + (self.loop_filter_ref_deltas[INTRA_FRAME] << nShift)
            lvlSeg = Clip3(0, MAX_LOOP_FILTER, lvlSeg)
        lvl = lvlSeg
        sh = self.loop_filter_sharpness
        shift = 2 if sh > 4 else 1 if sh > 0 else 0
        if sh > 0:
            limit = Clip3(1, 9 - sh, lvl >> shift)
        else:
            limit = max(1, lvl >> shift)
        blimit = 2 * (lvl + 2) + limit
        thresh = lvl >> 4
        return lvl, limit, blimit, thresh

    def sample_filter(self, x, y, plane, limit, blimit, thresh, dx, dy, filterSize):
        F = self.CurrFrame[plane]
        bd8 = self.BitDepth - 8

        def s(k):
            return F[y + dy * k][x + dx * k]
        q0, q1, q2, q3 = s(0), s(1), s(2), s(3)
        p0, p1, p2, p3 = s(-1), s(-2), s(-3), s(-4)
        threshBd = thresh << bd8
        hevMask = int(abs(p1 - p0) > threshBd) | int(abs(q1 - q0) > threshBd)
        if filterSize == 4:
            filterLen = 4
        elif plane != 0:
            filterLen = 6
        elif filterSize == 8:
            filterLen = 8
        else:
            filterLen = 16
        limitBd = limit << bd8
        blimitBd = blimit << bd8
        mask = int(abs(p1 - p0) > limitBd) | int(abs(q1 - q0) > limitBd)
        mask |= int(abs(p0 - q0) * 2 + abs(p1 - q1) // 2 > blimitBd)
        if filterLen >= 6:
            mask |= int(abs(p2 - p1) > limitBd) | int(abs(q2 - q1) > limitBd)
        if filterLen >= 8:
            mask |= int(abs(p3 - p2) > limitBd) | int(abs(q3 - q2) > limitBd)
        if mask:
            return
        thresholdBd = 1 << bd8
        flatMask = flatMask2 = 0
        if filterSize >= 8:
            m = (abs(p1 - p0) > thresholdBd or abs(q1 - q0) > thresholdBd or abs(p2 - p0) > thresholdBd
                 or abs(q2 - q0) > thresholdBd)
            if filterLen >= 8:
                m = m or abs(p3 - p0) > thresholdBd or abs(q3 - q0) > thresholdBd
            flatMask = int(not m)
        if filterSize >= 16:
            q4, q5, q6 = s(4), s(5), s(6)
            p4, p5, p6 = s(-5), s(-6), s(-7)
            m = (abs(p6 - p0) > thresholdBd or abs(q6 - q0) > thresholdBd or abs(p5 - p0) > thresholdBd
                 or abs(q5 - q0) > thresholdBd or abs(p4 - p0) > thresholdBd or abs(q4 - q0) > thresholdBd)
            flatMask2 = int(not m)
        if filterSize == 4 or not flatMask:
            self.narrow_filter(F, hevMask, x, y, dx, dy)
        elif filterSize == 8 or not flatMask2:
            self.wide_filter(F, x, y, plane, dx, dy, 3)
        else:
            self.wide_filter(F, x, y, plane, dx, dy, 4)

    def narrow_filter(self, F, hevMask, x, y, dx, dy):
        bd = self.BitDepth
        lo = -(1 << (bd - 1))
        hi = (1 << (bd - 1)) - 1

        def c4(v):
            return lo if v < lo else hi if v > hi else v
        off = 0x80 << (bd - 8)
        q0 = F[y][x]
        q1 = F[y + dy][x + dx]
        p0 = F[y - dy][x - dx]
        p1 = F[y - dy * 2][x - dx * 2]
        ps1 = p1 - off
        ps0 = p0 - off
        qs0 = q0 - off
        qs1 = q1 - off
        filt = c4(ps1 - qs1) if hevMask else 0
        filt = c4(filt + 3 * (qs0 - ps0))
        filter1 = c4(filt + 4) >> 3
        filter2 = c4(filt + 3) >> 3
        F[y][x] = c4(qs0 - filter1) + off
        F[y - dy][x - dx] = c4(ps0 + filter2) + off
        if not hevMask:
            filt = Round2(filter1, 1)
            F[y + dy][x + dx] = c4(qs1 - filt) + off
            F[y - dy * 2][x - dx * 2] = c4(ps1 + filt) + off

    @staticmethod
    def wide_filter(F, x, y, plane, dx, dy, log2Size):
        if log2Size == 4:
            n = 6
        elif plane == 0:
            n = 3
        else:
            n = 2
        n2 = 0 if (log2Size == 3 and plane == 0) else 1
        src = {k: F[y + k * dy][x + k * dx] for k in range(-(n + 1), n + 1)}
        out = {}
        for i in range(-n, n):
            t = 0
            for j in range(-n, n + 1):
                p = Clip3(-(n + 1), n, i + j)
                tap = 2 if abs(j) <= n2 else 1
                t += src[p] * tap
            out[i] = Round2(t, log2Size)
        for i in range(-n, n):
            F[y + i * dy][x + i * dx] = out[i]

    # ------------------------------------------------------------------ CDEF
    def cdef_process(self):
        self.CdefFrame = [[list(r) for r in p] for p in self.CurrFrame]
        step4 = Num_4x4_Blocks_Wide[BLOCK_8X8]
        cdefSize4 = Num_4x4_Blocks_Wide[BLOCK_64X64]
        cdefMask4 = ~(cdefSize4 - 1)
        for r in range(0, self.MiRows, step4):
            for c in range(0, self.MiCols, step4):
                baseR = r & cdefMask4
                baseC = c & cdefMask4
                idx = self.cdef_idx[baseR][baseC]
                self.cdef_block(r, c, idx)

    def cdef_block(self, r, c, idx):
        # (the copy into CdefFrame was done for the whole frame)
        if idx == -1:
            return
        coeffShift = self.BitDepth - 8
        skip = (self.Skips[r][c] and self.Skips[r + 1][c] and self.Skips[r][c + 1] and self.Skips[r + 1][c + 1])
        if skip:
            return
        self.st("cdef_blocks")
        yDir, var = self.cdef_direction(r, c)
        priStr = self.cdef_y_pri_strength[idx] << coeffShift
        secStr = self.cdef_y_sec_strength[idx] << coeffShift
        d = 0 if priStr == 0 else yDir
        varStr = min(FloorLog2(var >> 6), 12) if (var >> 6) else 0
        priStr = ((priStr * (4 + varStr) + 8) >> 4) if var else 0
        damping = self.CdefDamping + coeffShift
        self.cdef_filter(0, r, c, priStr, secStr, damping, d)
        if self.NumPlanes == 1:
            return
        priStr = self.cdef_uv_pri_strength[idx] << coeffShift
        secStr = self.cdef_uv_sec_strength[idx] << coeffShift
        d = 0 if priStr == 0 else Cdef_Uv_Dir[self.subsampling_x][self.subsampling_y][yDir]
        damping = self.CdefDamping + coeffShift - 1
        self.cdef_filter(1, r, c, priStr, secStr, damping, d)
        self.cdef_filter(2, r, c, priStr, secStr, damping, d)

    def cdef_direction(self, r, c):
        cost = [0] * 8
        partial = [[0] * 15 for _ in range(8)]
        bestCost = 0
        yDir = 0
        x0 = c << MI_SIZE_LOG2
        y0 = r << MI_SIZE_LOG2
        F = self.CurrFrame[0]
        sh = self.BitDepth - 8
        for i in range(8):
            for j in range(8):
                x = (F[y0 + i][x0 + j] >> sh) - 128
                partial[0][i + j] += x
                partial[1][i + j // 2] += x
                partial[2][i] += x
                partial[3][3 + i - j // 2] += x
                partial[4][7 + i - j] += x
                partial[5][3 - i // 2 + j] += x
                partial[6][j] += x
                partial[7][i // 2 + j] += x
        for i in range(8):
            cost[2] += partial[2][i] * partial[2][i]
            cost[6] += partial[6][i] * partial[6][i]
        cost[2] *= Div_Table[8]
        cost[6] *= Div_Table[8]
        for i in range(7):
            cost[0] += (partial[0][i] * partial[0][i] + partial[0][14 - i] * partial[0][14 - i]) * Div_Table[i + 1]
            cost[4] += (partial[4][i] * partial[4][i] + partial[4][14 - i] * partial[4][14 - i]) * Div_Table[i + 1]
        cost[0] += partial[0][7] * partial[0][7] * Div_Table[8]
        cost[4] += partial[4][7] * partial[4][7] * Div_Table[8]
        for i in range(1, 8, 2):
            for j in range(4 + 1):
                cost[i] += partial[i][3 + j] * partial[i][3 + j]
            cost[i] *= Div_Table[8]
            for j in range(4 - 1):
                cost[i] += (partial[i][j] * partial[i][j] + partial[i][10 - j] * partial[i][10 - j]) * Div_Table[2 * j + 2]
        for i in range(8):
            if cost[i] > bestCost:
                bestCost = cost[i]
                yDir = i
        var = (bestCost - cost[(yDir + 4) & 7]) >> 10
        return yDir, var

    def cdef_filter(self, plane, r, c, priStr, secStr, damping, d):
        coeffShift = self.BitDepth - 8
        subX = self.subsampling_x if plane else 0
        subY = self.subsampling_y if plane else 0
        x0 = (c * MI_SIZE) >> subX
        y0 = (r * MI_SIZE) >> subY
        w = 8 >> subX
        h = 8 >> subY
        F = self.CurrFrame[plane]
        D = self.CdefFrame[plane]
        pt = Cdef_Pri_Taps[(priStr >> coeffShift) & 1]
        st = Cdef_Sec_Taps[(priStr >> coeffShift) & 1]
        MiRows, MiCols = self.MiRows, self.MiCols

        def get(i, j, dr, k, sign):
            yy = y0 + i + sign * Cdef_Directions[dr][k][0]
            xx = x0 + j + sign * Cdef_Directions[dr][k][1]
            cr = (yy << subY) >> MI_SIZE_LOG2
            cc = (xx << subX) >> MI_SIZE_LOG2
            if 0 <= cc < MiCols and 0 <= cr < MiRows:
                return F[yy][xx]
            return None
        for i in range(h):
            for j in range(w):
                s = 0
                x = F[y0 + i][x0 + j]
                mx = mn = x
                for k in range(2):
                    for sign in (-1, 1):
                        p = get(i, j, d, k, sign)
                        if p is not None:
                            s += pt[k] * constrain(p - x, priStr, damping)
                            mx = max(p, mx)
                            mn = min(p, mn)
                        for dirOff in (-2, 2):
                            sv = get(i, j, (d + dirOff) & 7, k, sign)
                            if sv is not None:
                                s += st[k] * constrain(sv - x, secStr, damping)
                                mx = max(sv, mx)
                                mn = min(sv, mn)
                D[y0 + i][x0 + j] = Clip3(mn, mx, x + ((8 + s - (s < 0)) >> 4))

    # ------------------------------------------------------------------ superres
    def upscaling_process(self, inputFrame):
        if not self.use_superres:
            return inputFrame
        out = []
        for plane in range(self.NumPlanes):
            subX = self.subsampling_x if plane else 0
            subY = self.subsampling_y if plane else 0
            downscaledPlaneW = Round2(self.FrameWidth, subX)
            upscaledPlaneW = Round2(self.UpscaledWidth, subX)
            planeH = Round2(self.FrameHeight, subY)
            stepX = ((downscaledPlaneW << SUPERRES_SCALE_BITS) + (upscaledPlaneW // 2)) // upscaledPlaneW
            err = upscaledPlaneW * stepX - (downscaledPlaneW << SUPERRES_SCALE_BITS)
            initialSubpelX = (cdiv(-((upscaledPlaneW - downscaledPlaneW) << (SUPERRES_SCALE_BITS - 1))
                                   + upscaledPlaneW // 2, upscaledPlaneW)
                              + (1 << (SUPERRES_EXTRA_BITS - 1)) - cdiv(err, 2))
            initialSubpelX &= SUPERRES_SCALE_MASK
            miW = self.MiCols >> subX
            minX = 0
            maxX = miW * MI_SIZE - 1
            src = inputFrame[plane]
            dst = grid(len(src), upscaledPlaneW + 160)
            mxv = (1 << self.BitDepth) - 1
            for y in range(planeH):
                srow = src[y]
                drow = dst[y]
                for x in range(upscaledPlaneW):
                    srcX = -(1 << SUPERRES_SCALE_BITS) + initialSubpelX + x * stepX
                    srcXPx = srcX >> SUPERRES_SCALE_BITS
                    srcXSubpel = (srcX & SUPERRES_SCALE_MASK) >> SUPERRES_EXTRA_BITS
                    s = 0
                    flt = Upscale_Filter[srcXSubpel]
                    for k in range(SUPERRES_FILTER_TAPS):
                        sampleX = Clip3(minX, maxX, srcXPx + (k - SUPERRES_FILTER_OFFSET))
                        s += srow[sampleX] * flt[k]
                    drow[x] = Clip3(0, mxv, Round2(s, FILTER_BITS))
            out.append(dst)
        return out

    # ------------------------------------------------------------------ loop restoration
    def loop_restoration_process(self):
        self.LrFrame = [[list(r) for r in p] for p in self.UpscaledCdefFrame]
        if not self.UsesLr:
            return
        for y in range(0, self.FrameHeight, MI_SIZE):
            for x in range(0, self.UpscaledWidth, MI_SIZE):
                for plane in range(self.NumPlanes):
                    if self.FrameRestorationType[plane] != RESTORE_NONE:
                        self.loop_restore_block(plane, y >> MI_SIZE_LOG2, x >> MI_SIZE_LOG2)

    def loop_restore_block(self, plane, row, col):
        lumaY = row * MI_SIZE
        stripeNum = (lumaY + 8) // 64
        subX = self.subsampling_x if plane else 0
        subY = self.subsampling_y if plane else 0
        self.StripeStartY = (-8 + stripeNum * 64) >> subY
        self.StripeEndY = self.StripeStartY + (64 >> subY) - 1
        unitSize = self.LoopRestorationSize[plane]
        unitRows = self.count_units_in_frame(unitSize, Round2(self.FrameHeight, subY))
        unitCols = self.count_units_in_frame(unitSize, Round2(self.UpscaledWidth, subX))
        unitRow = min(unitRows - 1, ((row * MI_SIZE + 8) >> subY) // unitSize)
        unitCol = min(unitCols - 1, ((col * MI_SIZE) >> subX) // unitSize)
        self.PlaneEndX = Round2(self.UpscaledWidth, subX) - 1
        self.PlaneEndY = Round2(self.FrameHeight, subY) - 1
        x = (col * MI_SIZE) >> subX
        y = (row * MI_SIZE) >> subY
        w = min(MI_SIZE >> subX, self.PlaneEndX - x + 1)
        h = min(MI_SIZE >> subY, self.PlaneEndY - y + 1)
        if w <= 0 or h <= 0:
            return
        rType = self.LrType[plane][unitRow][unitCol]
        if rType == RESTORE_WIENER:
            self.wiener_filter(plane, unitRow, unitCol, x, y, w, h)
        elif rType == RESTORE_SGRPROJ:
            self.self_guided_filter(plane, unitRow, unitCol, x, y, w, h)

    def get_source_sample(self, plane, x, y):
        x = max(0, min(self.PlaneEndX, x))
        y = max(0, min(self.PlaneEndY, y))
        if y < self.StripeStartY:
            y = max(self.StripeStartY - 2, y)
            return self.UpscaledCurrFrame[plane][y][x]
        if y > self.StripeEndY:
            y = min(self.StripeEndY + 2, y)
            return self.UpscaledCurrFrame[plane][y][x]
        return self.UpscaledCdefFrame[plane][y][x]

    def self_guided_filter(self, plane, unitRow, unitCol, x, y, w, h):
        s = self.LrSgrSet[plane][unitRow][unitCol]
        flt0 = self.box_filter(plane, x, y, w, h, s, 0)
        flt1 = self.box_filter(plane, x, y, w, h, s, 1)
        w0 = self.LrSgrXqd[plane][unitRow][unitCol][0]
        w1 = self.LrSgrXqd[plane][unitRow][unitCol][1]
        w2 = (1 << SGRPROJ_PRJ_BITS) - w0 - w1
        r0 = Sgr_Params[s][0]
        r1 = Sgr_Params[s][2]
        C = self.UpscaledCdefFrame[plane]
        for i in range(h):
            for j in range(w):
                u = C[y + i][x + j] << SGRPROJ_RST_BITS
                v = w1 * u
                v += w0 * flt0[i][j] if r0 else w0 * u
                v += w2 * flt1[i][j] if r1 else w2 * u
                sv = Round2(v, SGRPROJ_RST_BITS + SGRPROJ_PRJ_BITS)
                self.LrFrame[plane][y + i][x + j] = self.Clip1(sv)

    def box_filter(self, plane, x, y, w, h, s, pss):
        r = Sgr_Params[s][pss * 2]
        if r == 0:
            return None
        eps = Sgr_Params[s][pss * 2 + 1]
        bd = self.BitDepth
        n = (2 * r + 1) * (2 * r + 1)
        n2e = n * n * eps
        sc = ((1 << SGRPROJ_MTABLE_BITS) + n2e // 2) // n2e
        oneOverN = ((1 << SGRPROJ_RECIP_BITS) + n // 2) // n
        A = {}
        B = {}
        for i in range(-1, h + 1):
            for j in range(-1, w + 1):
                a = 0
                b = 0
                for dy in range(-r, r + 1):
                    for dx in range(-r, r + 1):
                        c = self.get_source_sample(plane, x + j + dx, y + i + dy)
                        a += c * c
                        b += c
                a = Round2(a, 2 * (bd - 8))
                d = Round2(b, bd - 8)
                p = max(0, a * n - d * d)
                z = Round2(p * sc, SGRPROJ_MTABLE_BITS)
                if z >= 255:
                    a2 = 256
                elif z == 0:
                    a2 = 1
                else:
                    a2 = ((z << SGRPROJ_SGR_BITS) + (z // 2)) // (z + 1)
                b2 = ((1 << SGRPROJ_SGR_BITS) - a2) * b * oneOverN
                A[i, j] = a2
                B[i, j] = Round2(b2, SGRPROJ_RECIP_BITS)
        Fo = grid(h, w)
        C = self.UpscaledCdefFrame[plane]
        for i in range(h):
            shift = 5
            if pss == 0 and (i & 1):
                shift = 4
            for j in range(w):
                a = 0
                b = 0
                for dy in range(-1, 2):
                    for dx in range(-1, 2):
                        if pss == 0:
                            if (i + dy) & 1:
                                weight = 6 if dx == 0 else 5
                            else:
                                weight = 0
                        else:
                            weight = 4 if (dx == 0 or dy == 0) else 3
                        a += weight * A[i + dy, j + dx]
                        b += weight * B[i + dy, j + dx]
                v = a * C[y + i][x + j] + b
                Fo[i][j] = Round2(v, SGRPROJ_SGR_BITS + shift - SGRPROJ_RST_BITS)
        return Fo

    def wiener_filter(self, plane, unitRow, unitCol, x, y, w, h):
        bd = self.BitDepth
        InterRound0 = 3
        InterRound1 = 11
        if bd == 12:
            InterRound0 += 2
            InterRound1 -= 2
        vfilter = wiener_coeff(self.LrWiener[plane][unitRow][unitCol][0])
        hfilter = wiener_coeff(self.LrWiener[plane][unitRow][unitCol][1])
        offset = 1 << (bd + FILTER_BITS - InterRound0 - 1)
        limit = (1 << (bd + 1 + FILTER_BITS - InterRound0)) - 1
        inter = grid(h + 6, w)
        for r in range(h + 6):
            for c in range(w):
                s = 0
                for t in range(7):
                    s += hfilter[t] * self.get_source_sample(plane, x + c + t - 3, y + r - 3)
                v = Round2(s, InterRound0)
                inter[r][c] = Clip3(-offset, limit - offset, v)
        for r in range(h):
            for c in range(w):
                s = 0
                for t in range(7):
                    s += vfilter[t] * inter[r + t][c]
                v = Round2(s, InterRound1)
                self.LrFrame[plane][y + r][x + c] = self.Clip1(v)

    # ------------------------------------------------------------------ output (+ film grain)
    def output_process(self, src=None, w=None):
        fr = Frame()
        if src is None:
            src = self.LrFrame
        if w is None:
            w = self.UpscaledWidth
        h = self.FrameHeight
        subX, subY = self.subsampling_x, self.subsampling_y
        fr.w, fr.h = w, h
        fr.subx, fr.suby = subX, subY
        fr.bitdepth = self.BitDepth
        fr.mono = self.mono_chrome
        fr.cicp = (self.color_primaries, self.transfer_characteristics, self.matrix_coefficients,
                   self.color_range)
        fr.csp = self.chroma_sample_position
        fr.render = (self.RenderWidth, self.RenderHeight)
        fr.planes.append([list(src[0][yy][:w]) for yy in range(h)])
        if self.NumPlanes > 1:
            cw = (w + subX) >> subX
            ch = (h + subY) >> subY
            for p in (1, 2):
                fr.planes.append([list(src[p][yy][:cw]) for yy in range(ch)])
        fr.grain_applied = 0
        if (self.film_grain_params_present and self.apply_grain and self.apply_grain_out
                and self.stage is None):
            self.film_grain(fr, w, h, subX, subY)
            fr.grain_applied = 1
        self.frames.append(fr)

    def film_grain(self, fr, w, h, subX, subY):
        g = self.grain
        bd = self.BitDepth
        self.RandomRegister = g["grain_seed"]
        GrainCenter = 128 << (bd - 8)
        GrainMin = -GrainCenter
        GrainMax = (256 << (bd - 8)) - 1 - GrainCenter
        # generate grain
        shift = 12 - bd + g["grain_scale_shift"]
        LumaGrain = grid(73, 82)
        for y in range(73):
            for x in range(82):
                gv = Gaussian_Sequence[self.get_random_number(11)] if g["num_y_points"] > 0 else 0
                LumaGrain[y][x] = Round2(gv, shift)
        lag = g["ar_coeff_lag"]
        ashift = g["ar_coeff_shift_minus_6"] + 6
        for y in range(3, 73):
            for x in range(3, 82 - 3):
                s = 0
                pos = 0
                done = False
                for deltaRow in range(-lag, 1):
                    for deltaCol in range(-lag, lag + 1):
                        if deltaRow == 0 and deltaCol == 0:
                            done = True
                            break
                        c = g["ar_coeffs_y_plus_128"][pos] - 128
                        s += LumaGrain[y + deltaRow][x + deltaCol] * c
                        pos += 1
                    if done:
                        break
                LumaGrain[y][x] = Clip3(GrainMin, GrainMax, LumaGrain[y][x] + Round2(s, ashift))
        mono = self.mono_chrome
        if not mono:
            chromaW = 44 if subX else 82
            chromaH = 38 if subY else 73
            CbGrain = grid(chromaH, chromaW)
            CrGrain = grid(chromaH, chromaW)
            csl = g["chroma_scaling_from_luma"]
            self.RandomRegister = g["grain_seed"] ^ 0xB524
            for y in range(chromaH):
                for x in range(chromaW):
                    gv = Gaussian_Sequence[self.get_random_number(11)] if (g["num_cb_points"] > 0 or csl) else 0
                    CbGrain[y][x] = Round2(gv, shift)
            self.RandomRegister = g["grain_seed"] ^ 0x49D8
            for y in range(chromaH):
                for x in range(chromaW):
                    gv = Gaussian_Sequence[self.get_random_number(11)] if (g["num_cr_points"] > 0 or csl) else 0
                    CrGrain[y][x] = Round2(gv, shift)
            for y in range(3, chromaH):
                for x in range(3, chromaW - 3):
                    s0 = s1 = 0
                    pos = 0
                    done = False
                    for deltaRow in range(-lag, 1):
                        for deltaCol in range(-lag, lag + 1):
                            c0 = g["ar_coeffs_cb_plus_128"][pos] - 128
                            c1 = g["ar_coeffs_cr_plus_128"][pos] - 128
                            if deltaRow == 0 and deltaCol == 0:
                                if g["num_y_points"] > 0:
                                    luma = 0
                                    lumaX = ((x - 3) << subX) + 3
                                    lumaY = ((y - 3) << subY) + 3
                                    for i in range(subY + 1):
                                        for j in range(subX + 1):
                                            luma += LumaGrain[lumaY + i][lumaX + j]
                                    luma = Round2(luma, subX + subY)
                                    s0 += luma * c0
                                    s1 += luma * c1
                                done = True
                                break
                            s0 += CbGrain[y + deltaRow][x + deltaCol] * c0
                            s1 += CrGrain[y + deltaRow][x + deltaCol] * c1
                            pos += 1
                        if done:
                            break
                    CbGrain[y][x] = Clip3(GrainMin, GrainMax, CbGrain[y][x] + Round2(s0, ashift))
                    CrGrain[y][x] = Clip3(GrainMin, GrainMax, CrGrain[y][x] + Round2(s1, ashift))
        # scaling lookup
        ScalingLut = []
        for plane in range(self.NumPlanes):
            if plane == 0 or g["chroma_scaling_from_luma"]:
                xs, ys = g["point_y_value"], g["point_y_scaling"]
            elif plane == 1:
                xs, ys = g["point_cb_value"], g["point_cb_scaling"]
            else:
                xs, ys = g["point_cr_value"], g["point_cr_scaling"]
            numPoints = len(xs)
            lut = [0] * 256
            if numPoints:
                for x in range(xs[0]):
                    lut[x] = ys[0]
                for i in range(numPoints - 1):
                    deltaY = ys[i + 1] - ys[i]
                    deltaX = xs[i + 1] - xs[i]
                    delta = deltaY * ((65536 + (deltaX >> 1)) // deltaX)
                    for x in range(deltaX):
                        lut[xs[i] + x] = ys[i] + ((x * delta + 32768) >> 16)
                for x in range(xs[numPoints - 1], 256):
                    lut[x] = ys[numPoints - 1]
            ScalingLut.append(lut)

        def scale_lut(plane, index):
            sh = bd - 8
            x = index >> sh
            rem = index - (x << sh)
            if bd == 8 or x == 255:
                return ScalingLut[plane][x]
            start = ScalingLut[plane][x]
            end = ScalingLut[plane][x + 1]
            return start + Round2((end - start) * rem, sh)
        # noise stripes
        ov = g["overlap_flag"]
        noiseStripe = []
        lumaNum = 0
        for y in range(0, (h + 1) // 2, 16):
            self.RandomRegister = g["grain_seed"]
            self.RandomRegister ^= ((lumaNum * 37 + 178) & 255) << 8
            self.RandomRegister ^= ((lumaNum * 173 + 105) & 255)
            stripe = [grid(34, w + 64) for _ in range(self.NumPlanes)]
            for x in range(0, (w + 1) // 2, 16):
                rand = self.get_random_number(8)
                offsetX = rand >> 4
                offsetY = rand & 15
                for plane in range(self.NumPlanes):
                    psx = subX if plane > 0 else 0
                    psy = subY if plane > 0 else 0
                    planeOffsetX = 6 + offsetX if psx else 9 + offsetX * 2
                    planeOffsetY = 6 + offsetY if psy else 9 + offsetY * 2
                    G = (LumaGrain, CbGrain if not mono else None, CrGrain if not mono else None)[plane]
                    S = stripe[plane]
                    for i in range(34 >> psy):
                        for j in range(34 >> psx):
                            gv = G[planeOffsetY + i][planeOffsetX + j]
                            if psx == 0:
                                if j < 2 and ov and x > 0:
                                    old = S[i][x * 2 + j]
                                    if j == 0:
                                        gv = old * 27 + gv * 17
                                    else:
                                        gv = old * 17 + gv * 27
                                    gv = Clip3(GrainMin, GrainMax, Round2(gv, 5))
                                S[i][x * 2 + j] = gv
                            else:
                                if j == 0 and ov and x > 0:
                                    old = S[i][x + j]
                                    gv = old * 23 + gv * 22
                                    gv = Clip3(GrainMin, GrainMax, Round2(gv, 5))
                                S[i][x + j] = gv
            noiseStripe.append(stripe)
            lumaNum += 1
        noiseImage = []
        for plane in range(self.NumPlanes):
            psx = subX if plane > 0 else 0
            psy = subY if plane > 0 else 0
            img = grid((h + psy) >> psy, (w + psx) >> psx)
            for y in range((h + psy) >> psy):
                ln = y >> (5 - psy)
                i = y - (ln << (5 - psy))
                for x in range((w + psx) >> psx):
                    gv = noiseStripe[ln][plane][i][x]
                    if psy == 0:
                        if i < 2 and ln > 0 and ov:
                            old = noiseStripe[ln - 1][plane][i + 32][x]
                            if i == 0:
                                gv = old * 27 + gv * 17
                            else:
                                gv = old * 17 + gv * 27
                            gv = Clip3(GrainMin, GrainMax, Round2(gv, 5))
                    else:
                        if i < 1 and ln > 0 and ov:
                            old = noiseStripe[ln - 1][plane][i + 16][x]
                            gv = old * 23 + gv * 22
                            gv = Clip3(GrainMin, GrainMax, Round2(gv, 5))
                    img[y][x] = gv
            noiseImage.append(img)
        if g["clip_to_restricted_range"]:
            minValue = 16 << (bd - 8)
            maxLuma = 235 << (bd - 8)
            maxChroma = maxLuma if self.matrix_coefficients == MC_IDENTITY else (240 << (bd - 8))
        else:
            minValue = 0
            maxLuma = (256 << (bd - 8)) - 1
            maxChroma = maxLuma
        ScalingShift = g["grain_scaling_minus_8"] + 8
        OutY = fr.planes[0]
        if self.NumPlanes > 1:
            OutU, OutV = fr.planes[1], fr.planes[2]
            for y in range((h + subY) >> subY):
                for x in range((w + subX) >> subX):
                    lumaX = x << subX
                    lumaY = y << subY
                    lumaNextX = min(lumaX + 1, w - 1)
                    if subX:
                        averageLuma = Round2(OutY[lumaY][lumaX] + OutY[lumaY][lumaNextX], 1)
                    else:
                        averageLuma = OutY[lumaY][lumaX]
                    for p, Out, npts, mult, lmult, offs in (
                            (1, OutU, g["num_cb_points"], g["cb_mult"], g["cb_luma_mult"], g["cb_offset"]),
                            (2, OutV, g["num_cr_points"], g["cr_mult"], g["cr_luma_mult"], g["cr_offset"])):
                        if npts > 0 or g["chroma_scaling_from_luma"]:
                            orig = Out[y][x]
                            if g["chroma_scaling_from_luma"]:
                                merged = averageLuma
                            else:
                                combined = averageLuma * (lmult - 128) + orig * (mult - 128)
                                merged = self.Clip1((combined >> 6) + ((offs - 256) << (bd - 8)))
                            noise = noiseImage[p][y][x]
                            noise = Round2(scale_lut(p, merged) * noise, ScalingShift)
                            Out[y][x] = Clip3(minValue, maxChroma, orig + noise)
        for y in range(h):
            for x in range(w):
                orig = OutY[y][x]
                noise = noiseImage[0][y][x]
                noise = Round2(scale_lut(0, orig) * noise, ScalingShift)
                if g["num_y_points"] > 0:
                    OutY[y][x] = Clip3(minValue, maxLuma, orig + noise)

    def get_random_number(self, bits):
        r = self.RandomRegister
        bit = ((r >> 0) ^ (r >> 1) ^ (r >> 3) ^ (r >> 12)) & 1
        r = (r >> 1) | (bit << 15)
        self.RandomRegister = r
        return (r >> (16 - bits)) & ((1 << bits) - 1)


