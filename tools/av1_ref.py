    def read_block_tx_size(self):
        bw4 = Num_4x4_Blocks_Wide[self.MiSize]
        bh4 = Num_4x4_Blocks_High[self.MiSize]
        self.read_tx_size(True)      # !skip || !is_inter (intra)
