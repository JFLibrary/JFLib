    d = Decoder(not a.no_grain, a.stage)
    frames = d.decode(Path(a.file).read_bytes())
    if not frames:
        raise AV1Error("no frame")
    fr = frames[0]
    print("%dx%d %d bit, sub %d,%d, mono %d, cicp %s" % (fr.w, fr.h, fr.bitdepth, fr.subx, fr.suby, fr.mono,
                                                          fr.cicp))
    if a.stats:
        print(" ".join("%s=%d" % kv for kv in sorted(d.stats.items())))
    if a.out:
        write_yuv(fr, a.out)


