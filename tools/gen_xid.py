#!/usr/bin/env python3
"""gen_xid.py -- the identifier table of lib/wgsl (lib/wgsl/xid.rs)

WGSL identifiers are XID_Start (or _) followed by XID_Continue code points (UAX #31).  Python's
str.isidentifier() is exactly that test (PEP 3131: XID_Start + "_", then XID_Continue), so the
table comes from Python's own copy of the Unicode database:

    python tools/gen_xid.py [--out lib/wgsl/xid.rs]

The output is one array of runs: every entry is (first code point << 2) | class, class 0 = no
identifier character, 1 = XID_Continue only, 2 = XID_Start (and XID_Continue); a code point
belongs to the last run starting at or before it.
"""
import argparse
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def cls(cp):
    if 0xD800 <= cp <= 0xDFFF:
        return 0
    c = chr(cp)
    if c.isidentifier() and c != "_":
        return 2
    if ("a" + c).isidentifier():
        return 1
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "lib" / "wgsl" / "xid.rs"))
    a = ap.parse_args()
    runs = []
    prev = -1
    for cp in range(0x110000):
        k = cls(cp)
        if k != prev:
            runs.append((cp << 2) | k)
            prev = k
    lines = [
        "// xid -- XID_Start / XID_Continue for WGSL identifiers (UAX #31), generated by",
        f"// tools/gen_xid.py from Python's Unicode {unicodedata.unidata_version} database; do not edit",
        "//",
        "//   class(c) -> 0 (no identifier character), 1 (XID_Continue only), 2 (XID_Start)",
        "",
        "/// the Unicode version of the table",
        f"pub const UNICODE_VERSION: &str = \"{unicodedata.unidata_version}\";",
        "",
        "/// runs of equal class: (first code point << 2) | class, ascending",
        f"static RUNS: [u32; {len(runs)}] = [",
    ]
    row = []
    for r in runs:
        row.append(f"0x{r:x},")
        if len(row) == 10:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines += [
        "];",
        "",
        "/// the identifier class of a character (see the module comment)",
        "pub fn class(c: char) -> u8 {",
        "    let c = c as u32;",
        "    if c < 0x80 {",
        "        return match c as u8 {",
        "            b'a'..=b'z' | b'A'..=b'Z' => 2,",
        "            b'0'..=b'9' | b'_' => 1,",
        "            _ => 0,",
        "        };",
        "    }",
        "    let key = (c << 2) | 3;",
        "    let i = RUNS.partition_point(|&r| r <= key);",
        "    if i == 0 { 0 } else { (RUNS[i - 1] & 3) as u8 }",
        "}",
        "",
        "/// XID_Start",
        "pub fn is_start(c: char) -> bool {",
        "    class(c) == 2",
        "}",
        "",
        "/// XID_Continue",
        "pub fn is_continue(c: char) -> bool {",
        "    class(c) != 0",
        "}",
        "",
    ]
    Path(a.out).write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{a.out}: {len(runs)} runs (Unicode {unicodedata.unidata_version})")


if __name__ == "__main__":
    sys.exit(main())
