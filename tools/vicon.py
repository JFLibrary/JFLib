"""vicon.py -- helpers for vector icon sets drawn by ui::paint_svg_icon.

An icon is SVG path data on a 24 x 24 grid.  Layers are joined with '|'; a layer that
starts with 'F' is filled, 'A' draws in the accent colour ('AF' filled accent), the others
are stroked with round caps and joins.  An icon set is a list of
(names, art, stroke) where names are the IC_* / app constants that share the art.

    from vicon import *
    ICONS = [(["IC_ADD"], line(12, 5, 12, 19) + line(5, 12, 19, 12), 1.75), ...]
    emit_rust(ICONS, "icons_data.rs", header="...", const_path="ui::keys")

The generated file defines `pub(crate) fn art(cp: u32) -> Option<(&'static str, f32)>`.
"""
import math
from pathlib import Path


def f(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def pt(x, y):
    return f"{f(x)} {f(y)}"


def line(x0, y0, x1, y1):
    return f"M{pt(x0, y0)}L{pt(x1, y1)}"


def poly(points, closed=False):
    s = "M" + "L".join(pt(x, y) for x, y in points)
    return s + ("Z" if closed else "")


def circle(cx, cy, r):
    """a full circle as two arcs (closed)"""
    return f"M{pt(cx + r, cy)}A{f(r)} {f(r)} 0 1 1 {pt(cx - r, cy)}A{f(r)} {f(r)} 0 1 1 {pt(cx + r, cy)}Z"


def apoint(cx, cy, r, deg):
    a = math.radians(deg)
    return cx + r * math.cos(a), cy + r * math.sin(a)


def arc(cx, cy, r, a0, a1):
    """an open arc from angle a0 to a1 in degrees, clockwise on screen (0 = right, 90 = down)"""
    x0, y0 = apoint(cx, cy, r, a0)
    x1, y1 = apoint(cx, cy, r, a1)
    span = (a1 - a0) % 360
    large = 1 if span > 180 else 0
    return f"M{pt(x0, y0)}A{f(r)} {f(r)} 0 {large} 1 {pt(x1, y1)}"


def arrowhead(tip, direction, length=4.0, spread=40.0):
    """two wings behind a tip pointing along `direction` (degrees, screen coordinates)"""
    back = direction + 180
    w1 = apoint(tip[0], tip[1], length, back - spread)
    w2 = apoint(tip[0], tip[1], length, back + spread)
    return f"M{pt(*w1)}L{pt(*tip)}L{pt(*w2)}"


def arc_arrow(cx, cy, r, a0, a1, length=3.6):
    """a clockwise arc with an arrow head at its end"""
    tip = apoint(cx, cy, r, a1)
    return arc(cx, cy, r, a0, a1) + arrowhead(tip, a1 + 90, length)


def arc_arrow_ccw(cx, cy, r, a0, a1, length=3.6):
    """an arc drawn clockwise from a0 to a1 with the arrow head at its start (pointing back)"""
    tip = apoint(cx, cy, r, a0)
    return arc(cx, cy, r, a0, a1) + arrowhead(tip, a0 - 90, length)


def rrect(x, y, w, h, r):
    """a closed rounded rectangle"""
    if r <= 0:
        return f"M{pt(x, y)}H{f(x + w)}V{f(y + h)}H{f(x)}Z"
    r = min(r, w / 2, h / 2)
    return (f"M{pt(x + r, y)}H{f(x + w - r)}A{f(r)} {f(r)} 0 0 1 {pt(x + w, y + r)}"
            f"V{f(y + h - r)}A{f(r)} {f(r)} 0 0 1 {pt(x + w - r, y + h)}"
            f"H{f(x + r)}A{f(r)} {f(r)} 0 0 1 {pt(x, y + h - r)}"
            f"V{f(y + r)}A{f(r)} {f(r)} 0 0 1 {pt(x + r, y)}Z")


def dot(cx, cy, r=1.15):
    """a small filled dot (its own filled layer)"""
    return "|F" + circle(cx, cy, r) + "|"


def fill(art):
    return "|F" + art + "|"


def evenodd(art):
    """a layer filled with the even-odd rule (inner shapes cut holes)"""
    return "|E" + art + "|"


def cross_poly(cx, cy, arm, half, deg=45.0):
    """a closed cross (plus) outline rotated by deg: arms `arm` long from the centre, `half` wide"""
    pts = [(-half, -arm), (half, -arm), (half, -half), (arm, -half), (arm, half), (half, half),
           (half, arm), (-half, arm), (-half, half), (-arm, half), (-arm, -half), (-half, -half)]
    a = math.radians(deg)
    ca, sa = math.cos(a), math.sin(a)
    return poly([(cx + x * ca - y * sa, cy + x * sa + y * ca) for x, y in pts], True)


def accent(art):
    return "|A" + art + "|"


def accent_fill(art):
    return "|AF" + art + "|"


def clean(art):
    parts = [p for p in art.split("|") if p.strip()]
    return "|".join(parts)


def emit_rust(icons, path, header, const_path):
    """write the art table: icons = [(names, art, stroke)]"""
    out = [f"// {line}" if line else "//" for line in header.strip().splitlines()]
    out.append("// Generated by the icon script next to this file (tools/vicon.py helpers).")
    out.append(f"use {const_path}::*;")
    out.append("")
    out.append("/// the art (24-grid SVG path layers) and stroke width of an icon")
    out.append("#[allow(clippy::match_same_arms)]")
    out.append("pub(crate) fn art(cp: u32) -> Option<(&'static str, f32)> {")
    out.append("    Some(match cp {")
    for names, art, stroke in icons:
        out.append(f"        {' | '.join(names)} => (\"{clean(art)}\", {stroke:.2f}),")
    out.append("        _ => return None,")
    out.append("    })")
    out.append("}")
    Path(path).write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"{path}: {len(icons)} icons")
