#!/usr/bin/env python3
"""gen_dxf_codepages.py -- lib/dxf/src/codepages.rs: the single-byte code pages of DXF's $DWGCODEPAGE

    python tools/gen_dxf_codepages.py            write lib/dxf/src/codepages.rs
    python tools/gen_dxf_codepages.py --check    exit 1 when the file is not what this script writes

A DXF before AutoCAD 2007 (AC1021) stores its strings in the code page its header names ($DWGCODEPAGE:
ANSI_1252, DOS850, ...); from AC1021 on they are UTF-8.  Each table maps the bytes 0x80..0xFF of one code
page to Unicode (0xFFFD: unassigned), taken from Python's codecs.  The multi-byte pages of East Asia
(ANSI_932, 936, 949, 950, 1361) are not here: lib/dxf reads their bytes above 0x7F as U+FFFD and says so.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lib" / "dxf" / "src" / "codepages.rs"

# ($DWGCODEPAGE names, upper case, and the Python codec)
PAGES = [
    (["ANSI_874", "DOS874"], "cp874"),
    (["ANSI_1250"], "cp1250"),
    (["ANSI_1251"], "cp1251"),
    (["ANSI_1252", "ISO8859-1", "ISO8859_1"], "cp1252"),
    (["ANSI_1253"], "cp1253"),
    (["ANSI_1254"], "cp1254"),
    (["ANSI_1255"], "cp1255"),
    (["ANSI_1256"], "cp1256"),
    (["ANSI_1257"], "cp1257"),
    (["ANSI_1258"], "cp1258"),
    (["DOS437"], "cp437"),
    (["DOS850"], "cp850"),
    (["DOS852"], "cp852"),
    (["DOS855"], "cp855"),
    (["DOS857"], "cp857"),
    (["DOS860"], "cp860"),
    (["DOS861"], "cp861"),
    (["DOS863"], "cp863"),
    (["DOS864"], "cp864"),
    (["DOS865"], "cp865"),
    (["DOS866"], "cp866"),
    (["DOS869"], "cp869"),
    (["MACINTOSH", "MAC_ROMAN"], "mac-roman"),
    (["ISO8859-2", "ISO8859_2"], "iso8859-2"),
    (["ISO8859-5", "ISO8859_5"], "iso8859-5"),
    (["ISO8859-7", "ISO8859_7"], "iso8859-7"),
    (["ISO8859-9", "ISO8859_9"], "iso8859-9"),
    (["KOI8-R", "KOI8_R"], "koi8-r"),
]


def table(codec):
    out = []
    for b in range(0x80, 0x100):
        try:
            out.append(ord(bytes([b]).decode(codec)))
        except UnicodeDecodeError:
            out.append(0xFFFD)
    return out


def render():
    lines = [
        "// codepages -- the single-byte code pages of DXF's $DWGCODEPAGE (generated by tools/gen_dxf_codepages.py,",
        "// do not edit): bytes 0x80..0xFF -> Unicode, 0xFFFD unassigned.  Below 0x80 every page is ASCII.",
        "",
        "/// the table of a $DWGCODEPAGE name (upper case): None for names without one (the multi-byte pages,",
        "/// unknown names)",
        "pub(crate) fn table(name: &str) -> Option<&'static [u16; 128]> {",
        "    match name {",
    ]
    for i, (names, _) in enumerate(PAGES):
        pats = " | ".join(f'"{n}"' for n in names)
        lines.append(f"        {pats} => Some(&T{i}),")
    lines += [
        "        _ => None,",
        "    }",
        "}",
        "",
    ]
    for i, (names, codec) in enumerate(PAGES):
        t = table(codec)
        lines.append(f"// {names[0]}")
        lines.append(f"static T{i}: [u16; 128] = [")
        for r in range(0, 128, 16):
            lines.append("    " + ", ".join(f"0x{v:04X}" for v in t[r:r + 16]) + ",")
        lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("codepages.rs is current" if ok else "codepages.rs is stale: python tools/gen_dxf_codepages.py")
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
