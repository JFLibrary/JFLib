"""psl_gen.py -- lib/netpkt/psl_data.rs from the Public Suffix List (publicsuffix.org), pinned.

    python tools/psl_gen.py            write lib/netpkt/psl_data.rs (and licenses/PSL-LICENSE.txt)
    python tools/psl_gen.py --check    exit 1 when the file is not what the pinned list gives
    python tools/psl_gen.py --commit SHA   another commit of publicsuffix/list (then update PIN)

The list (public_suffix_list.dat and its LICENSE, MPL-2.0) comes once with tools/suite_fetch.py
into build/vectors.  Both sections count, ICANN and PRIVATE, as browsers take them for cookies.
Labels beyond ASCII become their A-labels ("xn--..."): URLs reach netpkt in ASCII.  The rules go
into one string, sorted bytewise, one per line ("co.uk", "*.ck", "!www.ck"), with the offset of
each line; netpkt::psl looks them up by binary search.  To update: a newer commit of the list in
PIN (and DATE), run this, run coretest --only cookie,psl, commit the generated file."""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lib" / "netpkt" / "psl_data.rs"
LICENSE_OUT = ROOT / "lib" / "netpkt" / "licenses" / "PSL-LICENSE.txt"
REPO = "publicsuffix/list"
PIN = "73edc270543c9a079e6a21f310adc5744ee7c20d"
DATE = "2026-11-27"


def a_label(label):
    if label.isascii():
        return label
    return "xn--" + label.encode("punycode").decode("ascii")


def rules(text):
    """(rule, private) of every line that is one, A-labels throughout"""
    out, private = [], False
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("// ===BEGIN PRIVATE DOMAINS==="):
            private = True
        if not line or line.startswith("//"):
            continue
        rule = line.split()[0].lower()
        bang = rule.startswith("!")
        labels = (rule[1:] if bang else rule).split(".")
        rule = ("!" if bang else "") + ".".join(l if l == "*" else a_label(l) for l in labels)
        out.append((rule, private))
    return out


def render(rs, commit, date):
    names = sorted({r for r, _ in rs})
    data = "\n".join(names) + "\n"
    offs, at = [], 0
    for n in names:
        offs.append(at)
        at += len(n) + 1
    offs.append(at)
    lines = [
        "// psl_data -- the Public Suffix List, generated by tools/psl_gen.py; do not edit.",
        f"// From https://github.com/{REPO} at {commit} ({date}): ICANN and PRIVATE sections,",
        "// A-labels, one rule per line, sorted bytewise; OFFS[i] is where line i starts.",
        "//",
        "// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a",
        "// copy of the MPL was not distributed with this file, You can obtain one at",
        "// https://mozilla.org/MPL/2.0/ (the text is in licenses/PSL-LICENSE.txt).",
        "",
        f'pub(crate) const COMMIT: &str = "{commit}";',
        f'pub(crate) const DATE: &str = "{date}";',
        "",
        "/// the rules, one per line",
        "pub(crate) static DATA: &str = concat!(",
    ]
    for i in range(0, len(names), 8):
        chunk = "".join(n + "\n" for n in names[i:i + 8])
        lines.append('    "' + chunk.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '",')
    lines.append(");")
    lines.append("")
    lines.append(f"/// where each line of DATA starts ({len(names)} rules, then the end)")
    lines.append(f"pub(crate) static OFFS: [u32; {len(offs)}] = [")
    for i in range(0, len(offs), 16):
        lines.append("    " + ", ".join(str(o) for o in offs[i:i + 16]) + ",")
    lines.append("];")
    assert data == "".join(n + "\n" for n in names)
    return "\n".join(lines) + "\n", len(names)


def main():
    ap = argparse.ArgumentParser(description="the Public Suffix List as lib/netpkt/psl_data.rs")
    ap.add_argument("--check", action="store_true", help="only compare with the file in the repo")
    ap.add_argument("--commit", default=PIN)
    ap.add_argument("--date", default=DATE)
    a = ap.parse_args()
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from suite_fetch import fetch
    folder = fetch(REPO, a.commit, ["public_suffix_list.dat", "LICENSE"])
    text = (folder / "public_suffix_list.dat").read_text(encoding="utf-8")
    rs = rules(text)
    src, n = render(rs, a.commit, a.date)
    lic = (folder / "LICENSE").read_text(encoding="utf-8")
    if a.check:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == src and LICENSE_OUT.exists() and LICENSE_OUT.read_text(encoding="utf-8") == lic
        print(f"psl_gen: {OUT.relative_to(ROOT)} " + ("is up to date" if same else "differs from the pinned list"))
        return 0 if same else 1
    OUT.write_text(src, encoding="utf-8")
    LICENSE_OUT.parent.mkdir(parents=True, exist_ok=True)
    LICENSE_OUT.write_text(lic, encoding="utf-8")
    private = sum(1 for _, p in rs if p)
    print(f"psl_gen: {n} rules ({len(rs) - private} ICANN, {private} private) from {REPO} @ {a.commit[:12]} -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
