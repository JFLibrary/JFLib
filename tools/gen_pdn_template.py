#!/usr/bin/env python3
"""gen_pdn_template.py -- the NRBF class templates of the PDN writer for Rust (r9-pdn).

  python tools/gen_pdn_template.py          writes lib/img_pdn/template.rs

The assembly writer (ASMLIB/src/img/pdn.s, frozen reference) carries a block generated by
tools/pdn_template.py from a paint.net 5.1 file: class records with library-id patches, the
library names, the KeyValuePair array tail and the savedWith version.  This script reads that
block (between "# BEGIN pdn_template.py" and "# END pdn_template.py") and writes the same
bytes as Rust statics, so both writers emit identical files.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PDN_S = ROOT / "ASMLIB" / "src" / "img" / "pdn.s"
OUT = ROOT / "lib" / "img_pdn" / "template.rs"


def parse_block():
    text = PDN_S.read_text(encoding="utf-8")
    a = text.index("# BEGIN pdn_template.py")
    b = text.index("# END pdn_template.py")
    block = text[a:b].splitlines()
    labels = {}  # label -> list of items: bytes or ("quad", [names])
    order = []
    cur = None
    for line in block[1:]:
        s = line.split("#", 1)[0].strip()
        if not s:
            continue
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$", s)
        if m:
            cur = m.group(1)
            labels[cur] = []
            order.append(cur)
            s = m.group(2).strip()
            if not s:
                continue
        if s.startswith(".") and cur is not None:
            d, _, rest = s.partition(" ")
            rest = rest.strip()
            if d == ".byte":
                labels[cur].append(bytes(int(x, 0) for x in rest.split(",")))
            elif d == ".short":
                labels[cur].append(b"".join(int(x, 0).to_bytes(2, "little") for x in rest.split(",")))
            elif d == ".long":
                labels[cur].append(b"".join(int(x, 0).to_bytes(4, "little") for x in rest.split(",")))
            elif d == ".quad":
                labels[cur].append(("quad", [x.strip() for x in rest.split(",")]))
            elif d == ".asciz":
                labels[cur].append(eval(rest).encode("utf-8") + b"\0")  # noqa: S307 (frozen source)
            elif d in (".p2align", ".section", ".text"):
                pass
            else:
                raise SystemExit(f"unknown directive {d} in the template block")
    return labels, order


def raw(items):
    out = b""
    for it in items:
        if isinstance(it, tuple):
            raise SystemExit("unexpected .quad")
        out += it
    return out


def rust_bytes(b, ind="    "):
    lines = []
    for i in range(0, len(b), 16):
        lines.append(ind + ", ".join(f"0x{x:02x}" for x in b[i:i + 16]) + ",")
    return "\n".join(lines)


def main():
    labels, order = parse_block()
    out = []
    out.append("// template -- the NRBF class templates of the PDN writer (generated, do not edit)")
    out.append("//                                         [src/img/pdn.s: the pdn_template.py block]")
    out.append("//")
    out.append("// Generated by tools/gen_pdn_template.py from the block of the frozen assembly (itself made")
    out.append("// by tools/pdn_template.py from a paint.net 5.1 file).  A class template: the writer's slot")
    out.append("// (first-instance table index), the record type (4 SystemClassWithMembersAndTypes / 5")
    out.append("// ClassWithMembersAndTypes), the library-id patches {offset in the body, library index} and")
    out.append("// the body (everything after the object id, library ids zeroed).")
    out.append("")
    out.append("/// a class record template")
    out.append("pub struct Tpl {")
    out.append("    pub slot: u8,")
    out.append("    pub rt: u8,")
    out.append("    pub patches: &'static [(u16, u8)],")
    out.append("    pub body: &'static [u8],")
    out.append("}")
    out.append("")
    tpl_names = []
    for lab in order:
        if not lab.startswith("pt_c_"):
            continue
        b = raw(labels[lab])
        slot, rt, npatch, z = b[0], b[1], b[2], b[3]
        assert z == 0
        blen = int.from_bytes(b[4:8], "little")
        patches = []
        p = 8
        for _ in range(npatch):
            off = int.from_bytes(b[p:p + 2], "little")
            lib = b[p + 2]
            assert b[p + 3] == 0
            patches.append((off, lib))
            p += 4
        body = b[p:p + blen]
        assert len(body) == blen, lab
        name = lab[5:].upper()
        tpl_names.append(name)
        out.append(f"pub static {name}: Tpl = Tpl {{")
        out.append(f"    slot: {slot},")
        out.append(f"    rt: {rt},")
        out.append("    patches: &[" + ", ".join(f"({o}, {l})" for o, l in patches) + "],")
        out.append("    body: &[")
        out.append(rust_bytes(body, "        "))
        out.append("    ],")
        out.append("};")
        out.append("")
    # libraries: {u32 n, n bytes}
    for lab in ("pt_lib0", "pt_lib1", "pt_kvp_tail"):
        b = raw(labels[lab])
        n = int.from_bytes(b[:4], "little")
        assert len(b) == 4 + n, lab
        out.append(f"pub static {lab[3:].upper()}: [u8; {n}] = [")
        out.append(rust_bytes(b[4:]))
        out.append("];")
        out.append("")
    libs = labels["pt_libs"][0][1]
    out.append("/// the library names (LengthPrefixedString bytes) by library index  [pt_libs]")
    out.append("pub static LIBS: [&[u8]; %d] = [%s];" % (len(libs), ", ".join(f"&{x[3:].upper()}" for x in libs)))
    out.append("")
    for lab, what in (("pt_blendop", "the UserBlendOps class per blend mode  [pt_blendop]"),
                      ("pt_blp", "BitmapLayerProperties per blend mode  [pt_blp]")):
        names = labels[lab][0][1]
        out.append(f"/// {what}")
        out.append("pub static %s: [&Tpl; %d] = [%s];" % (lab[3:].upper(), len(names),
                                                       ", ".join(f"&{x[5:].upper()}" for x in names)))
        out.append("")
    ver = raw(labels["pt_version"])
    vals = [int.from_bytes(ver[i:i + 4], "little") for i in range(0, 16, 4)]
    out.append("/// System.Version {_Major, _Minor, _Build, _Revision} as written  [pt_version]")
    out.append("pub static VERSION: [u8; 16] = [")
    out.append(rust_bytes(ver))
    out.append("];")
    out.append("")
    vs = raw(labels["pt_verstr"]).rstrip(b"\0").decode()
    assert vs == ".".join(map(str, vals))
    out.append("/// the savedWithVersion attribute of the XML header  [pt_verstr]")
    out.append(f'pub static VERSTR: &[u8] = b"{vs}";')
    out.append("")
    text = "\n".join(out)
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(tpl_names)} templates")
    return 0


if __name__ == "__main__":
    sys.exit(main())
