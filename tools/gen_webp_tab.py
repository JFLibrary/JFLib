#!/usr/bin/env python3
"""gen_webp_tab.py -- the big lookup tables of the WebP codec (img_webp) from the assembly.

Reads the .rodata tables of ASMLIB/src/img/webp_vp8.s and webp_vp8_enc.s and writes
lib/img_webp/tab.rs (committed).  Run it again only if the assembly tables change:

    python tools/gen_webp_tab.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "ASMLIB" / "src" / "img"
OUT = ROOT / "lib" / "img_webp" / "tab.rs"

# (asm file, label, rust name, rust type, doc)
TABLES = [
    ("webp_vp8.s", "v8_proba0", "PROBA0", "u8", "CoeffsProba0[4][8][3][11]  [v8_proba0]"),
    ("webp_vp8.s", "v8_update", "UPDATE", "u8", "CoeffsUpdateProba[4][8][3][11]  [v8_update]"),
    ("webp_vp8.s", "v8_bmodes", "BMODES", "u8", "kBModesProba[top 10][left 10][9]  [v8_bmodes]"),
    ("webp_vp8.s", "v8_dctab", "DCTAB", "u8", "kDcTable[128]  [v8_dctab]"),
    ("webp_vp8.s", "v8_actab", "ACTAB", "u16", "kAcTable[128]  [v8_actab]"),
    ("webp_vp8.s", "v8_p4tab", "P4TAB", "u8",
     "4x4 sub-block predictors VE .. HU as pixel recipes {op, i0, i1, i2} per pixel (raster\n"
     "/// order): op 0 = AVG3(e[i0], e[i1], e[i2]), 1 = AVG2(e[i0], e[i1]), 2 = e[i0]; edge e[13] =\n"
     "/// L K J I X A B C D E F G H  [v8_p4tab]"),
    ("webp_vp8.s", "v8_zigzag", "ZIGZAG", "u8", "coefficient scan order  [v8_zigzag]"),
    ("webp_vp8.s", "v8_cat", "CAT", "u8", "extra-bit probabilities of categories 3..6 (12 bytes each, 0-terminated)  [v8_cat]"),
    ("webp_vp8_enc.s", "ve_g2l", "G2L", "u16", "libwebp kGammaToLinearTab (gamma 0.80, 12 bits)  [ve_g2l]"),
]


def values(text, label):
    lines = text.splitlines()
    for i, ln in enumerate(lines):
        if re.match(rf"^{label}:", ln.strip()):
            break
    else:
        raise SystemExit(f"label {label} not found")
    out = []
    first = lines[i].split(":", 1)[1]
    for ln in [first] + lines[i + 1:]:
        s = ln.split("#", 1)[0].strip()
        if not s:
            continue
        if re.match(r"^[A-Za-z_.][\w.]*:", s) and out:
            break
        m = re.match(r"^\.(byte|short|long|quad)\s+(.*)$", s)
        if m:
            out += [int(v.strip(), 0) for v in m.group(2).split(",")]
        elif s.startswith((".p2align", ".globl", ".section", ".text")) or s == "":
            if out and s.startswith((".section", ".text", ".p2align", ".globl")):
                break
        else:
            break
    return out


def main():
    texts = {}
    parts = [
        "// tab -- the big lookup tables of the WebP codec, generated by tools/gen_webp_tab.py",
        "// from the .rodata of ASMLIB/src/img/webp_vp8.s and webp_vp8_enc.s (do not edit by hand)",
        "//                                                [src/img/webp_vp8.s, webp_vp8_enc.s]",
        "",
    ]
    for f, label, name, ty, doc in TABLES:
        t = texts.setdefault(f, (SRC / f).read_text(encoding="utf-8"))
        v = values(t, label)
        if ty == "u16":
            v = [x & 0xFFFF for x in v]
        parts.append(f"/// {doc}")
        parts.append(f"pub static {name}: [{ty}; {len(v)}] = [")
        per = 16 if ty == "u8" else 12
        for k in range(0, len(v), per):
            parts.append("    " + ", ".join(str(x) for x in v[k:k + per]) + ",")
        parts.append("];")
        parts.append("")
    OUT.write_bytes(("\n".join(parts)).encode())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
