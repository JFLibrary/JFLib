#!/usr/bin/env python3
"""gen_av1ftx.py -- lib/img_av1/ftx.rs from ASMLIB/src/img/av1_ftx.s (r9-av1enc)

    python tools/gen_av1ftx.py

The assembly file is generated by tools/av1_gen.py (the encoder model's forward butterflies as
straight-line code, the cost and quantizer-scale tables); this script reads that frozen
reference back -- every H / B step and both tables -- and writes the same straight-line code as
Rust, so the two cannot drift apart.  Rerun only when the assembly changes (it does not: the
assembly is frozen); the output is checked in.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "ASMLIB" / "src" / "img" / "av1_ftx.s"
OUT = ROOT / "lib" / "img_av1" / "ftx.rs"

FNS = [("dct4", 4), ("dct8", 8), ("dct16", 16), ("dct32", 32), ("dct64", 64), ("adst8", 8), ("adst16", 16)]


def parse():
    lines = [ln.split("#")[0].strip() for ln in SRC.read_text(encoding="utf-8").splitlines()]
    lines = [ln for ln in lines if ln]
    fns, tabs = {}, {}
    i, cur, tab = 0, None, None
    while i < len(lines):
        ln = lines[i]
        m = re.match(r"^av1_ftx_(\w+):$", ln)
        if m:
            cur, tab = m.group(1), None
            fns[cur] = []
            i += 1
            continue
        m = re.match(r"^(av1e_\w+):$", ln)
        if m:
            cur, tab = None, m.group(1)
            tabs[tab] = []
            i += 1
            continue
        if tab and re.match(r"^\.(short|long)\s", ln):
            tabs[tab] += [int(v) for v in ln.split(None, 1)[1].split(",")]
            i += 1
            continue
        if cur is None:
            i += 1
            continue
        if ln == "ret":
            cur = None
            i += 1
            continue
        # H: mov eax, [rcx + A]; mov edx, [rcx + B]; lea r8d, [rax + rdx]; sub eax, edx;
        #    mov [rcx + A], r8d; mov [rcx + B], eax
        m = re.match(r"^mov\s+eax, \[rcx \+ (\d+)\]$", ln)
        if m:
            a = int(m.group(1))
            b = int(re.match(r"^mov\s+edx, \[rcx \+ (\d+)\]$", lines[i + 1]).group(1))
            assert re.match(r"^lea\s+r8d, \[rax \+ rdx\]$", lines[i + 2]), lines[i + 2]
            assert re.match(r"^sub\s+eax, edx$", lines[i + 3]), lines[i + 3]
            assert lines[i + 4].replace(" ", "") == "mov[rcx+%d],r8d" % a, lines[i + 4]
            assert lines[i + 5].replace(" ", "") == "mov[rcx+%d],eax" % b, lines[i + 5]
            fns[cur].append(("H", a // 4, b // 4))
            i += 6
            continue
        # B: movsxd r8, [U]; movsxd r9, [V]; imul rax, r8, C; imul rdx, r9, S; sub rax, rdx;
        #    add rax, 2048; sar rax, 12; imul r8, r8, S2; imul r9, r9, C2; add r8, r9;
        #    add r8, 2048; sar r8, 12; mov [A], eax; mov [B], r8d
        m = re.match(r"^movsxd\s+r8, DWORD PTR \[rcx \+ (\d+)\]$", ln)
        if m:
            u = int(m.group(1))
            v = int(re.match(r"^movsxd\s+r9, DWORD PTR \[rcx \+ (\d+)\]$", lines[i + 1]).group(1))
            c = int(re.match(r"^imul\s+rax, r8, (-?\d+)$", lines[i + 2]).group(1))
            s = int(re.match(r"^imul\s+rdx, r9, (-?\d+)$", lines[i + 3]).group(1))
            assert lines[i + 4].replace(" ", "") == "subrax,rdx"
            assert lines[i + 5].replace(" ", "") == "addrax,2048"
            assert lines[i + 6].replace(" ", "") == "sarrax,12"
            s2 = int(re.match(r"^imul\s+r8, r8, (-?\d+)$", lines[i + 7]).group(1))
            c2 = int(re.match(r"^imul\s+r9, r9, (-?\d+)$", lines[i + 8]).group(1))
            assert lines[i + 9].replace(" ", "") == "addr8,r9"
            assert lines[i + 10].replace(" ", "") == "addr8,2048"
            assert lines[i + 11].replace(" ", "") == "sarr8,12"
            a = int(re.match(r"^mov\s+\[rcx \+ (\d+)\], eax$", lines[i + 12]).group(1))
            b = int(re.match(r"^mov\s+\[rcx \+ (\d+)\], r8d$", lines[i + 13]).group(1))
            fns[cur].append(("B", a // 4, b // 4, u // 4, v // 4, c, s, s2, c2))
            i += 14
            continue
        raise SystemExit(f"gen_av1ftx: unexpected line in {cur}: {ln}")
    return fns, tabs


def main():
    fns, tabs = parse()
    o = []
    w = o.append
    w("// ftx -- forward DCT4 .. DCT64, ADST8 and ADST16 butterflies of the AV1 encoder as")
    w("// straight-line code, and the encoder's tables  [src/img/av1_ftx.s]")
    w("//")
    w("// GENERATED by tools/gen_av1ftx.py from the assembly (itself generated by tools/av1_gen.py")
    w("// from tools/av1_enc_ref.py); do not edit.")
    w("//")
    for name, n in FNS:
        w(f"//   {name + '(t)':<12}{len(fns[name])} butterflies on t: [i32; {n}]")
    w("//   COST        u16[1024] Q8 bits of a symbol of probability (i + 0.5) / 1024  [av1e_cost]")
    w("//   KQ          u32[TX_SIZES_ALL] quantizer scale K (Q16) per transform size  [av1e_kq]")
    w("//")
    w("// t in place, no clamping (exact for 8 / 10-bit residuals); the permutations are the")
    w("// caller's (DCT: result i belongs to coefficient brev(n, i); ADST: input index outp(i) with")
    w("// the sign of odd i, result i to coefficient i - 1 (odd i) / N - 1 - i).  r(): a rotation")
    w("// with 64-bit products, h(): Ta + Tb, Ta - Tb (32-bit, wrapping as the assembly's lea / sub).")
    w("")
    w("// h(t, a, b): t[a], t[b] = t[a] + t[b], t[a] - t[b]")
    w("#[inline(always)]")
    w("fn h<const N: usize>(t: &mut [i32; N], a: usize, b: usize) {")
    w("    let x = t[a];")
    w("    let y = t[b];")
    w("    t[a] = x.wrapping_add(y);")
    w("    t[b] = x.wrapping_sub(y);")
    w("}")
    w("")
    w("// r(t, a, b, u, v, c, s, s2, c2): x = t[u], y = t[v];")
    w("// t[a] = (x * c - y * s + 2048) >> 12, t[b] = (x * s2 + y * c2 + 2048) >> 12")
    w("#[inline(always)]")
    w("#[allow(clippy::too_many_arguments)]")
    w("fn r<const N: usize>(t: &mut [i32; N], a: usize, b: usize, u: usize, v: usize, c: i64, s: i64, s2: i64, c2: i64) {")
    w("    let x = t[u] as i64;")
    w("    let y = t[v] as i64;")
    w("    let p = (x.wrapping_mul(c).wrapping_sub(y.wrapping_mul(s)).wrapping_add(2048)) >> 12;")
    w("    let q = (x.wrapping_mul(s2).wrapping_add(y.wrapping_mul(c2)).wrapping_add(2048)) >> 12;")
    w("    t[a] = p as i32;")
    w("    t[b] = q as i32;")
    w("}")
    for name, n in FNS:
        w("")
        w(f"/// av1_ftx_{name}: {len(fns[name])} butterflies")
        w(f"pub fn {name}(t: &mut [i32; {n}]) {{")
        for op in fns[name]:
            if op[0] == "H":
                w(f"    h(t, {op[1]}, {op[2]});")
            else:
                _, a, b, u, v, c, s, s2, c2 = op
                w(f"    r(t, {a}, {b}, {u}, {v}, {c}, {s}, {s2}, {c2});")
        w("}")
    cost = tabs["av1e_cost"]
    kq = tabs["av1e_kq"]
    assert len(cost) == 1024 and len(kq) == 19, (len(cost), len(kq))
    w("")
    w("/// av1e_cost: Q8 bits of a symbol of probability (i + 0.5) / 1024")
    w("pub static COST: [u16; 1024] = [")
    for i in range(0, 1024, 16):
        w("    " + ", ".join(str(v) for v in cost[i:i + 16]) + ",")
    w("];")
    w("")
    w("/// av1e_kq: quantizer scale K (Q16) per transform size")
    w("pub static KQ: [u32; 19] = [")
    w("    " + ", ".join(str(v) for v in kq) + ",")
    w("];")
    OUT.write_bytes(("\n".join(o) + "\n").encode("utf-8"))
    print(f"gen_av1ftx: {OUT.relative_to(ROOT)}: " + ", ".join(f"{k} {len(v)}" for k, v in fns.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
