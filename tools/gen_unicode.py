"""gen_unicode.py -- the Unicode tables of ui::i18n's collation and case functions (lib/ui/i18n_unicode.rs)

    python tools/gen_unicode.py                       (Python's own copy of UnicodeData)
    python tools/gen_unicode.py --ucd UnicodeData.txt (a file of unicode.org/Public/<version>/ucd)

Only what core and alloc do not have (they bring the case mappings):
  DECOMP  the canonical decompositions of the BMP (one step: a letter -> base + mark, as in
          UnicodeData; i18n applies them recursively), without the CJK compatibility
          ideographs; accents become secondary differences of the collation
  COMPAT  compatibility decompositions of letters and digits in Latin-1, Latin Extended and
          the Latin ligatures (ĳ, ŀ, ǆ, ﬁ, ª, ²): sorted like their letters
  MARKS   the ranges of combining marks (canonical combining class > 0, BMP)
  ZEROS   the zeros of the decimal digit runs (Nd): every run is zero .. zero + 9
"""
import argparse
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lib" / "ui" / "i18n_unicode.rs"
# the letters of COMPAT: Latin-1 Supplement, Latin Extended-A / B, Latin Extended Additional,
# the Latin ligatures
COMPAT_RANGES = [(0x00A0, 0x024F), (0x1E00, 0x1EFF), (0xFB00, 0xFB06)]


class Ucd:
    """category, combining class, decomposition and decimal value of every code point"""

    def __init__(self, path=None):
        self.cat, self.ccc, self.dec, self.digit = {}, {}, {}, {}
        if path is None:
            self.version = unicodedata.unidata_version
            for cp in range(0x110000):
                c = chr(cp)
                self.cat[cp] = unicodedata.category(c)
                self.ccc[cp] = unicodedata.combining(c)
                self.dec[cp] = unicodedata.decomposition(c)
                self.digit[cp] = unicodedata.decimal(c, None)
            return
        self.version = Path(path).name
        for line in Path(path).read_text(encoding="utf-8").splitlines():
            f = line.split(";")
            if len(f) < 15:
                continue
            cp = int(f[0], 16)
            self.cat[cp] = f[2]
            self.ccc[cp] = int(f[3])
            self.dec[cp] = f[5]
            self.digit[cp] = int(f[6]) if f[6] else None

    def nfkd(self, cp):
        """the full compatibility decomposition of a code point"""
        d = self.dec.get(cp, "")
        if not d:
            return [cp]
        parts = d.split()
        if parts[0].startswith("<"):
            parts = parts[1:]
        return [x for p in parts for x in self.nfkd(int(p, 16))]


def tables(ucd):
    decomp = []
    for cp in range(0x10000):
        d = ucd.dec.get(cp, "")
        if not d or d.startswith("<") or 0xF900 <= cp <= 0xFAFF:
            continue
        parts = [int(p, 16) for p in d.split()]
        if len(parts) > 2 or any(p > 0xFFFF for p in parts):
            raise SystemExit(f"U+{cp:04X}: unexpected decomposition {d}")
        decomp.append((cp, parts[0], parts[1] if len(parts) > 1 else 0))
    compat = []
    for lo, hi in COMPAT_RANGES:
        for cp in range(lo, hi + 1):
            d = ucd.dec.get(cp, "")
            if not d.startswith(("<compat>", "<super>")):
                continue
            full = ucd.nfkd(cp)
            if all(ucd.cat.get(x, "Cn")[0] in "LN" for x in full):
                compat.append((cp, "".join(chr(x) for x in full)))
    marks = []
    for cp in range(0x10000):
        if ucd.ccc.get(cp, 0):
            if marks and marks[-1][1] == cp - 1:
                marks[-1][1] = cp
            else:
                marks.append([cp, cp])
    zeros = [cp for cp in range(0x110000) if ucd.cat.get(cp) == "Nd" and ucd.digit.get(cp) == 0]
    return decomp, compat, marks, zeros


def rust_str(s):
    return "".join(c if c.isalnum() and ord(c) < 0x80 else f"\\u{{{ord(c):X}}}" for c in s)


def emit(ucd, decomp, compat, marks, zeros):
    out = [
        "// i18n_unicode -- generated by tools/gen_unicode.py from UnicodeData "
        f"(Unicode {ucd.version}): canonical",
        "// decompositions, compatibility letters, combining marks and decimal digits for the",
        "// collation and case functions of ui::i18n.  Do not edit.",
        "",
        f"/// (code point, first, second) canonical decompositions of the BMP, one step, sorted ({len(decomp)})",
        f"pub(super) static DECOMP: [(u16, u16, u16); {len(decomp)}] = [",
    ]
    for k in range(0, len(decomp), 6):
        out.append("    " + " ".join(f"(0x{a:04X}, 0x{b:04X}, 0x{c:04X})," for a, b, c in decomp[k:k + 6]))
    out += [
        "];",
        "",
        f"/// (code point, letters) compatibility decompositions of Latin letters and digits ({len(compat)})",
        f"pub(super) static COMPAT: [(u16, &str); {len(compat)}] = [",
    ]
    for k in range(0, len(compat), 6):
        out.append("    " + " ".join(f"(0x{a:04X}, \"{rust_str(s)}\")," for a, s in compat[k:k + 6]))
    out += [
        "];",
        "",
        f"/// (first, last) ranges of the combining marks (combining class > 0, BMP; {len(marks)})",
        f"pub(super) static MARKS: [(u16, u16); {len(marks)}] = [",
    ]
    for k in range(0, len(marks), 8):
        out.append("    " + " ".join(f"(0x{a:04X}, 0x{b:04X})," for a, b in marks[k:k + 8]))
    out += [
        "];",
        "",
        f"/// the zeros of the decimal digit runs (zero .. zero + 9; {len(zeros)})",
        f"pub(super) static ZEROS: [u32; {len(zeros)}] = [",
    ]
    for k in range(0, len(zeros), 10):
        out.append("    " + " ".join(f"0x{z:05X}," for z in zeros[k:k + 10]))
    out += ["];", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--ucd", help="UnicodeData.txt (default: Python's unicodedata)")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    ucd = Ucd(a.ucd)
    text = emit(ucd, *tables(ucd))
    Path(a.out).write_text(text, encoding="utf-8", newline="\n")
    print(f"{a.out}: Unicode {ucd.version}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
