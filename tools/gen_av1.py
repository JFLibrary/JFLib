#!/usr/bin/env python3
"""gen_av1.py -- generate the constant tables and the inverse butterflies of the Rust AV1
decoder (lib/img_av1/tab.rs, txfn.rs) from the same sources as the assembly's
tools/av1_gen.py (tools/av1_tables.py, tools/av1_ref.py).

    python tools/gen_av1.py [--check]

First regenerates the assembly files of tools/av1_gen.py into build/r9-av1/gen/ and checks that
they equal the checked-in ASMLIB/src/img/av1_tab.s, ASMLIB/inc/av1_tab.inc and
ASMLIB/src/img/av1_txfn.s byte for byte (so the Rust data is exactly what the assembly uses),
then writes the Rust files.  --check only compares (exit 1 when the Rust files are stale).

tab.rs: the CDF context layout as u16 element offsets (CDF_* / CDFN_*; the assembly's are byte
offsets), the default CDFs (CDF_NC, CDF_COEF_DEF[4]) and every table of av1_tab.s under its
upper-case name with the element type of the assembly's reads (u8 / i8 / u16 / i16).
txfn.rs: the butterfly stages of DCT4 .. DCT64, ADST8 and ADST16 as straight-line code, the
operations of av1_txfn.s: B( a, b, angle ) with 64-bit products, H( a, b ) clamped to
[ -hi - 1, hi ] with wrapping 32-bit sums.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import av1_gen as G  # noqa: E402
import av1_tables as T  # noqa: E402
import av1_ref as R  # noqa: E402

OUT_TAB = ROOT / "lib" / "img_av1" / "tab.rs"
OUT_TX = ROOT / "lib" / "img_av1" / "txfn.rs"
WORK = ROOT / "build" / "r9-av1" / "gen"


def check_asm():
    """regenerate the assembly files into WORK and compare them with the checked-in ones"""
    WORK.mkdir(parents=True, exist_ok=True)
    pairs = [("OUT_S", ROOT.parent / "legacy" / "ASMLIB" / "src" / "img" / "av1_tab.s"),
             ("OUT_INC", ROOT.parent / "legacy" / "ASMLIB" / "inc" / "av1_tab.inc"),
             ("OUT_TX", ROOT.parent / "legacy" / "ASMLIB" / "src" / "img" / "av1_txfn.s"),
             ("OUT_FTX", ROOT.parent / "legacy" / "ASMLIB" / "src" / "img" / "av1_ftx.s")]
    for name, ref in pairs:
        setattr(G, name, WORK / ref.name)
    G.main()
    bad = []
    for name, ref in pairs[:3]:
        if (WORK / ref.name).read_bytes() != ref.read_bytes():
            bad.append(ref.name)
    if bad:
        sys.exit("gen_av1: the regenerated %s differ from the checked-in assembly files" % ", ".join(bad))


def rs_array(name, kind, vals, per=16):
    out = ["pub static %s: [%s; %d] = [" % (name, kind, len(vals))]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("];")
    return out


def tab_rs():
    L = ["// tab -- constant tables of the AV1 decoder (generated by tools/gen_av1.py from the",
         "// sources of tools/av1_gen.py, which writes the assembly's av1_tab.s / av1_tab.inc; do not",
         "// edit)                                                   [src/img/av1_tab.s, inc/av1_tab.inc]",
         "//",
         "// CDF_* are u16 element offsets into the CDF context (the assembly's are byte offsets),",
         "// CDFN_* the symbol counts.  Every CDF array: N values (the last 32768), then the counter.",
         "#![allow(dead_code)]",
         ""]
    nc_vals, off = [], 0
    for name, tab in G.NC:
        v = [T.Default_Delta_Lf_Cdf] * T.CONST["FRAME_LF_COUNT"] if tab is None else getattr(T, tab)
        fl, sh = G.flat(v), G.shape(v)
        L.append("pub const CDF_%s: usize = %d; // %s" % (name, off, sh))
        L.append("pub const CDFN_%s: usize = %d;" % (name, sh[-1] - 1))
        nc_vals += fl
        off += len(fl)
    nc = off
    L.append("pub const CDF_COEF: usize = %d; // start of the coefficient CDFs" % nc)
    coef = [[] for _ in range(4)]
    for name, tab in G.COEF:
        v = getattr(T, tab)
        sh = G.shape(v[0])
        L.append("pub const CDF_%s: usize = %d; // %s" % (name, off, sh))
        L.append("pub const CDFN_%s: usize = %d;" % (name, sh[-1] - 1))
        for q in range(4):
            coef[q] += G.flat(v[q])
        off += len(G.flat(v[0]))
    L.append("pub const CDF_COEFSIZE: usize = %d;" % (off - nc))
    L.append("pub const CDF_LEN: usize = %d; // u16 elements of a CDF context" % ((2 * off + 15) // 16 * 8))
    L.append("")
    L.append("/// default non-coefficient CDFs (init_non_coeff_cdfs)")
    L += rs_array("CDF_NC", "u16", nc_vals)
    L.append("")
    L.append("/// default coefficient CDFs per base_q_idx class (init_coeff_cdfs)")
    L.append("pub static CDF_COEF_DEF: [[u16; %d]; 4] = [" % len(coef[0]))
    for q in range(4):
        L.append("    [")
        for i in range(0, len(coef[q]), 16):
            L.append("        " + ", ".join(str(v) for v in coef[q][i:i + 16]) + ",")
        L.append("    ],")
    L.append("];")
    lists = (("u8", ["Num_4x4_Blocks_Wide", "Num_4x4_Blocks_High", "Mi_Width_Log2", "Mi_Height_Log2",
                     "Size_Group", "Max_Tx_Size_Rect", "Max_Tx_Depth", "Partition_Subsize", "Subsampled_Size",
                     "Split_Tx_Size", "Tx_Width", "Tx_Height", "Tx_Width_Log2", "Tx_Height_Log2", "Tx_Size_Sqr",
                     "Tx_Size_Sqr_Up", "Adjusted_Tx_Size", "Transform_Row_Shift", "Mode_To_Txfm",
                     "Intra_Mode_Context", "Filter_Intra_Mode_To_Intra_Dir", "Tx_Type_In_Set_Intra",
                     "Tx_Type_Intra_Inv_Set1", "Tx_Type_Intra_Inv_Set2", "Palette_Color_Hash_Multipliers",
                     "Coeff_Base_Ctx_Offset", "Coeff_Base_Pos_Ctx_Offset", "Sm_Weights_Tx_4x4",
                     "Sm_Weights_Tx_8x8", "Sm_Weights_Tx_16x16", "Sm_Weights_Tx_32x32", "Sm_Weights_Tx_64x64",
                     "Intra_Edge_Kernel", "Quantizer_Matrix", "Cdef_Uv_Dir", "Cdef_Pri_Taps", "Cdef_Sec_Taps",
                     "Sgr_Params", "Segmentation_Feature_Bits", "Segmentation_Feature_Signed",
                     "Segmentation_Feature_Max", "Remap_Lr_Type", "Wiener_Taps_K"]),
             ("i8", ["Palette_Color_Context", "Intra_Filter_Taps", "Mag_Ref_Offset_With_Tx_Class",
                     "Sig_Ref_Diff_Offset", "Cdef_Directions", "Wiener_Taps_Min", "Wiener_Taps_Max",
                     "Wiener_Taps_Mid", "Sgrproj_Xqd_Min", "Sgrproj_Xqd_Max", "Sgrproj_Xqd_Mid"]),
             ("u16", ["Mode_To_Angle", "Dr_Intra_Derivative", "Dc_Qlookup", "Ac_Qlookup", "Qm_Offset",
                      "Cos128_Lookup", "Div_Table"]),
             ("i16", ["Upscale_Filter", "Gaussian_Sequence"]))
    for kind, names in lists:
        for n in names:
            L.append("")
            L.append("/// %s %s" % (n, T.DIMS[n]))
            L += rs_array(n.upper(), kind, G.flat(getattr(T, n)))
    for n in range(2, 7):
        L.append("")
        L += rs_array("BREV%d" % n, "u8", [R.brev(n, i) for i in range(1 << n)])
    for n in (3, 4):
        n0 = 1 << n
        L.append("")
        L.append("/// ADST%d input permutation" % n0)
        L += rs_array("ADST_IN%d" % n0, "u8", [(i - 1) if (i & 1) else (n0 - i - 1) for i in range(n0)])
        outp = []
        for i in range(n0):
            a = (i >> 3) & 1
            b = ((i >> 2) & 1) ^ ((i >> 3) & 1)
            c = ((i >> 1) & 1) ^ ((i >> 2) & 1)
            d = (i & 1) ^ ((i >> 1) & 1)
            idx = ((d << 3) | (c << 2) | (b << 1) | a) >> (4 - n)
            outp.append(idx | (0x80 if i & 1 else 0))
        L.append("/// ADST%d output permutation: index | 0x80 when negated" % n0)
        L += rs_array("ADST_OUT%d" % n0, "u8", outp)
    for n in T.DIMS:
        if "_Scan_" in n:
            L.append("")
            L += rs_array(n.upper(), "u16", G.flat(getattr(T, n)))
    return "\n".join(L) + "\n"


def txfn_rs():
    L = ["// txfn -- butterfly stages of the AV1 inverse DCT4 .. DCT64, ADST8 and ADST16 as straight-line",
         "// code (generated by tools/gen_av1.py from the B / H calls of tools/av1_ref.py, like the",
         "// assembly's av1_txfn.s; do not edit)                          [src/img/av1_txfn.s]",
         "//",
         "// t: the already permuted values (DCT: bit reversal, ADST: input permutation; the ADST output",
         "// permutation is the caller's); hi = ( 1 << ( r - 1 ) ) - 1, H( ) results are clamped to",
         "// [ -hi - 1, hi ] (sums wrap at 32 bits).  B( a, b, angle ): Round2( Ta * cos - Tb * sin, 12 ),",
         "// Round2( Ta * sin + Tb * cos, 12 ) with 64-bit products (low 32 bits kept), flip = exchange.",
         "",
         "#[inline(always)]",
         "fn bf(t: &mut [i32], a: usize, b: usize, c: i64, s: i64, flip: bool) {",
         "    let (x, y) = (t[a] as i64, t[b] as i64);",
         "    let u = ((x * c - y * s + 2048) >> 12) as i32;",
         "    let v = ((x * s + y * c + 2048) >> 12) as i32;",
         "    if flip {",
         "        t[a] = v;",
         "        t[b] = u;",
         "    } else {",
         "        t[a] = u;",
         "        t[b] = v;",
         "    }",
         "}",
         "",
         "#[inline(always)]",
         "fn hf(t: &mut [i32], a: usize, b: usize, hi: i32) {",
         "    let lo = !hi;",
         "    let (x, y) = (t[a], t[b]);",
         "    t[a] = x.wrapping_add(y).clamp(lo, hi);",
         "    t[b] = x.wrapping_sub(y).clamp(lo, hi);",
         "}"]
    for name, fn, n in G.TXFNS:
        ops = G.record_ops(fn, n)
        L.append("")
        L.append("/// av1_tx_%s: %d butterflies" % (name, len(ops)))
        L.append("pub fn %s(t: &mut [i32; %d], hi: i32) {" % (name, 1 << n))
        for a, b, angle, flags in ops:
            if flags & 1:
                L.append("    hf(t, %d, %d, hi);" % (a, b))
            else:
                L.append("    bf(t, %d, %d, %d, %d, %s);" % (a, b, R.cos128(angle), R.sin128(angle),
                                                           "true" if flags & 2 else "false"))
        L.append("}")
    return "\n".join(L) + "\n"


def main():
    check_asm()
    files = {OUT_TAB: tab_rs(), OUT_TX: txfn_rs()}
    if "--check" in sys.argv:
        stale = [p.name for p, s in files.items() if not p.exists() or p.read_bytes() != s.encode()]
        print("gen_av1: " + ("stale: " + ", ".join(stale) if stale else "up to date"))
        sys.exit(1 if stale else 0)
    for p, s in files.items():
        p.write_bytes(s.encode())
        print("gen_av1: wrote %s (%d lines)" % (p.relative_to(ROOT), s.count("\n")))


if __name__ == "__main__":
    main()
