#!/usr/bin/env python3
"""gen_jxl.py -- the constant tables of the JPEG XL codec for the Rust rebuild.

Reads ASMLIB/src/img/jxl_tab.s (generated by tools/jxl_gen.py from the model tools/jxl_ref.py;
part of the frozen assembly reference) and writes lib/img_jxl/tab.rs with the same values,
bit for bit: f32 / f64 tables as from_bits constants, integer tables with their element type.

    python tools/gen_jxl.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "ASMLIB" / "src" / "img" / "jxl_tab.s"
OUT = ROOT / "lib" / "img_jxl" / "tab.rs"

# element type of every table (the assembly only knows .byte / .short / .long / .quad)
TYPES = {
    "jxt_opsin_def": "f32", "jxt_up2": "f32", "jxt_dm": "f32", "jxt_fastpow": "f32", "jxt_afv": "f32",
    "jxt_wc": "f32", "jxt_rs": "f32", "jxt_rsd": "f32", "jxt_afvbasis": "f32", "jxt_srgb": "f32",
    "jxt_ycc": "f32", "jxt_noise": "f32", "jxt_epf": "f32", "jxt_srgblin": "f32", "jxt_dq8": "f32",
    "jxt_venc": "f32",
    "jxt_rndd": "f64", "jxt_vencd": "f64",
    "jxt_histhuff": "u8", "jxt_histcode": "u8", "jxt_iccheader": "u8", "jxt_icckind1": "u8",
    "jxt_icckind2": "u8", "jxt_acslog2": "u8", "jxt_strategyorder": "u8", "jxt_acsqt": "u8",
    "jxt_qtsx": "u8", "jxt_freqctx": "u8", "jxt_acclus": "u8",
    "jxt_special": "i8",
    "jxt_icctags": "u32", "jxt_iccxyz": "u32", "jxt_icctypes": "u32", "jxt_lfdef": "u32", "jxt_qlib": "u32",
    "jxt_deltapal": "i16",
    "jxt_nzctx": "u16",
}


def parse():
    tabs = {}
    comments = {}
    order = []
    cur = None
    last_comment = ""
    for line in SRC.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if s.startswith("#"):
            last_comment = s[1:].strip()
            continue
        m = re.match(r"^([a-z_0-9]+):$", s)
        if m:
            cur = m.group(1)
            tabs[cur] = []
            comments[cur] = last_comment
            order.append(cur)
            continue
        m = re.match(r"^\.(byte|short|long|quad)\s+(.*)$", s)
        if m and cur:
            for v in m.group(2).split(","):
                v = v.strip()
                tabs[cur].append(int(v, 0))
    return order, tabs, comments


def emit(order, tabs, comments):
    out = ["// tab -- JPEG XL tables (GENERATED by tools/gen_jxl.py from ASMLIB/src/img/jxl_tab.s, which",
           "// tools/jxl_gen.py derives from the model tools/jxl_ref.py; do not edit)   [src/img/jxl_tab.s]",
           ""]
    for name in order:
        vals = tabs[name]
        ty = TYPES[name]
        rname = name[4:].upper()
        out.append("/// %s" % comments[name])
        out.append("pub static %s: [%s; %d] = [" % (rname, ty, len(vals)))
        per = 8 if ty in ("f32", "f64", "u32") else 16
        for i in range(0, len(vals), per):
            chunk = vals[i:i + per]
            if ty == "f32":
                items = ["f32::from_bits(0x%08x)" % (v & 0xFFFFFFFF) for v in chunk]
            elif ty == "f64":
                items = ["f64::from_bits(0x%016x)" % (v & 0xFFFFFFFFFFFFFFFF) for v in chunk]
            elif ty == "u32":
                items = ["0x%08x" % (v & 0xFFFFFFFF) for v in chunk]
            elif ty == "i8":
                items = [str(v if v < 128 else v - 256) for v in chunk]
            elif ty == "i16":
                items = [str(v if v < 32768 else v - 65536) for v in chunk]
            else:
                items = [str(v) for v in chunk]
            out.append("    " + ", ".join(items) + ",")
        out.append("];")
        out.append("")
    OUT.write_bytes(("\n".join(out)).encode("utf-8"))
    print("wrote", OUT, len(order), "tables")


if __name__ == "__main__":
    emit(*parse())
