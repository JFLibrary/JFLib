#!/usr/bin/env python3
"""gen_charsets.py -- lib/spell/charsets.rs: the 8-bit character sets of Hunspell's SET

    python tools/gen_charsets.py            write lib/spell/charsets.rs
    python tools/gen_charsets.py --check    exit 1 when the file is not what this script writes

Each table maps the bytes 0x80..0xFF of one character set to Unicode (0xFFFD: unassigned),
taken from Python's codecs.  The names are the ones Hunspell's .aff files use after SET
(compared without case, '-' and '_'), plus a few common spellings.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "lib" / "spell" / "charsets.rs"

# (Hunspell name and aliases, Python codec)
SETS = [
    (["ISO8859-2", "latin2"], "iso8859-2"),
    (["ISO8859-3", "latin3"], "iso8859-3"),
    (["ISO8859-4", "latin4"], "iso8859-4"),
    (["ISO8859-5"], "iso8859-5"),
    (["ISO8859-6"], "iso8859-6"),
    (["ISO8859-7"], "iso8859-7"),
    (["ISO8859-8"], "iso8859-8"),
    (["ISO8859-9", "latin5"], "iso8859-9"),
    (["ISO8859-10", "latin6"], "iso8859-10"),
    (["ISO8859-13", "latin7"], "iso8859-13"),
    (["ISO8859-14", "latin8"], "iso8859-14"),
    (["ISO8859-15", "latin9"], "iso8859-15"),
    (["ISO8859-16", "latin10"], "iso8859-16"),
    (["KOI8-R"], "koi8-r"),
    (["KOI8-U"], "koi8-u"),
    (["microsoft-cp1251", "cp1251", "windows-1251"], "cp1251"),
    (["microsoft-cp1252", "cp1252", "windows-1252"], "cp1252"),
    (["TIS620-2533", "TIS-620", "TIS620"], "tis-620"),
]


def key(name):
    return name.lower().replace("-", "").replace("_", "")


def table(codec):
    out = []
    for b in range(0x80, 0x100):
        try:
            out.append(ord(bytes([b]).decode(codec)))
        except UnicodeDecodeError:
            out.append(0xFFFD)
    return out


def render():
    lines = [
        "// charsets -- the 8-bit character sets of Hunspell's SET (generated by tools/gen_charsets.py,",
        "// do not edit): bytes 0x80..0xFF -> Unicode, 0xFFFD unassigned.  ISO8859-1 needs no table",
        "// (the byte is the code point).",
        "",
        "/// the table of a SET name (compared without case, '-' and '_'): None for UTF-8, ISO8859-1",
        "/// and unknown names (read as ISO8859-1)",
        "pub(crate) fn table(name: &str) -> Option<&'static [u16; 128]> {",
        "    let k = squash(name);",
        "    match k.as_str() {",
    ]
    for i, (names, _) in enumerate(SETS):
        pats = " | ".join(f'"{k}"' for k in dict.fromkeys(key(n) for n in names))
        lines.append(f"        {pats} => Some(&T{i}),")
    lines += [
        "        _ => None,",
        "    }",
        "}",
        "",
        "fn squash(name: &str) -> alloc::string::String {",
        "    name.chars().filter(|c| *c != '-' && *c != '_').flat_map(|c| c.to_lowercase()).collect()",
        "}",
        "",
    ]
    for i, (names, codec) in enumerate(SETS):
        t = table(codec)
        lines.append(f"// {names[0]}")
        lines.append(f"static T{i}: [u16; 128] = [")
        for r in range(0, 128, 16):
            lines.append("    " + ", ".join(f"0x{v:04X}" for v in t[r:r + 16]) + ",")
        lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("charsets.rs is current" if ok else "charsets.rs is stale: python tools/gen_charsets.py")
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
