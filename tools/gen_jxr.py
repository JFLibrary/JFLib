#!/usr/bin/env python3
"""gen_jxr.py -- the large JPEG XR tables of the assembly as Rust statics (R9-jxr).

Reads the data blocks jxv_lut / jxv_delta (ASMLIB/src/img/jxr_ent.s: adaptive VLC decode
tables and their discriminant delta rows), jxc_recip / jxc_srgb (ASMLIB/src/img/jxr_color.s:
unpremultiply reciprocals, linear -> sRGB table) and jxw_vlc / jxw_qps8 / jxw_qps420
(ASMLIB/src/img/jxr_enc.s: VLC code tables of the encoder, jxrlib's quality -> QP tables) and
writes lib/img_jxr/tab.rs.

  python tools/gen_jxr.py            # rewrite tab.rs
  python tools/gen_jxr.py --check    # exit 1 when tab.rs is out of date
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENT = ROOT / "ASMLIB" / "src" / "img" / "jxr_ent.s"
COLOR = ROOT / "ASMLIB" / "src" / "img" / "jxr_color.s"
ENC = ROOT / "ASMLIB" / "src" / "img" / "jxr_enc.s"
OUT = ROOT / "lib" / "img_jxr" / "tab.rs"


def block(path, label):
    """the values of the .byte / .short / .long lines after `label:` up to the next label"""
    vals = []
    on = False
    for ln in path.read_text(encoding="utf-8").splitlines():
        s = ln.split("#")[0].strip()
        if re.match(r"^[A-Za-z_.][\w.]*:", s):
            if on:
                break
            if s.startswith(label + ":"):
                on = True
                s = s[len(label) + 1:].strip()
        if not on or not s:
            continue
        m = re.match(r"^\.(byte|short|long)\s+(.*)$", s)
        if not m:
            if s.startswith(".p2align") or s.startswith(".section"):
                if vals:
                    break
                continue
            raise SystemExit(f"{path.name}: unexpected line in {label}: {ln}")
        for v in m.group(2).split(","):
            vals.append(int(v.strip(), 0))
    if not vals:
        raise SystemExit(f"{path.name}: {label} not found")
    return vals


def rows(vals, per, fmt):
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(fmt(v) for v in vals[i:i + per]) + ",")
    return "\n".join(out)


def main():
    lut = block(ENT, "jxv_lut")
    delta = block(ENT, "jxv_delta")
    recip = block(COLOR, "jxc_recip")
    srgb = block(COLOR, "jxc_srgb")
    vlc = block(ENC, "jxw_vlc")
    qps8 = block(ENC, "jxw_qps8")
    qps420 = block(ENC, "jxw_qps420")
    assert len(lut) == 17 * 256, len(lut)
    assert len(delta) % 16 == 0
    assert len(recip) == 256 and len(srgb) == 4096
    assert len(vlc) == 17 * 16 and len(qps8) == 72 and len(qps420) == 72
    text = f"""// tab -- generated by tools/gen_jxr.py from jxv_lut / jxv_delta (jxr_ent.s) and
// jxc_recip / jxc_srgb (jxr_color.s), jxw_vlc / jxw_qps8 / jxw_qps420 (jxr_enc.s); do not edit
//                                                     [src/img/jxr_ent.s, jxr_color.s, jxr_enc.s]

/// adaptive VLC decode tables: 256 x (symbol | length << 8) per table, tables of n = 4 (1),
/// 5 (2), 6 (4), 7 (2), 8 (1), 9 (2), 12 (5) symbols (JXV_L* = first entry of an alphabet);
/// zero-padded to 8192 entries (index & 8191 needs no bounds check)
pub static JXV_LUT: [u16; 8192] = [
{rows(lut + [0] * (8192 - len(lut)), 16, lambda v: f"0x{v:04X}")}
];

/// discriminant delta rows (i8[16]): row 0 zero, then T(t) - T(t + 1) code lengths;
/// zero-padded to 256 entries (index & 255)
pub static JXV_DELTA: [i8; 256] = [
{rows([v if v < 128 else v - 256 for v in delta] + [0] * (256 - len(delta)), 16, str)}
];

/// floor(255 * 2^16 / a), a = 0 -> 0
pub static RECIP: [u32; 256] = [
{rows(recip, 8, str)}
];

/// 8-bit sRGB of the linear value i / 4095
pub static SRGB: [u8; 4096] = [
{rows(srgb, 32, str)}
];

/// encoder VLC codes: code | length << 8 per table (16 entries) x symbol; tables as JXV_LUT
pub static ENC_VLC: [u16; {len(vlc)}] = [
{rows(vlc, 8, lambda v: f"0x{v:04X}")}
];

/// jxrlib DPK_QPS_8 (Y U V YHP UHP VHP) per quality step
pub static QPS8: [u8; 72] = [
{rows(qps8, 18, str)}
];

/// jxrlib DPK_QPS_420 (row 10 repeated)
pub static QPS420: [u8; 72] = [
{rows(qps420, 18, str)}
];
"""
    data = text.encode("utf-8")
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_bytes() == data
        print("tab.rs up to date" if ok else "tab.rs out of date")
        sys.exit(0 if ok else 1)
    OUT.write_bytes(data)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
